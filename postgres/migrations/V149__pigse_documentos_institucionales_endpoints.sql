-- Implementa los endpoints de "PIGSE-Endpoints.postman_collection.json"
-- (Gestión Documental institucional + Monitoreo y Cumplimiento) contra
-- academico_test -- el microservicio pigse (V148) pasa a apuntar ahí en
-- vez de a su propio schema aislado.
--
-- Desviaciones deliberadas respecto a la colección:
--   * DELETE /documentos/:tipo -> PATCH. ck_query_http_method sólo admite
--     GET/POST/PUT/PATCH (Query.httpMethod excluye DELETE a propósito,
--     ver su javadoc: "evita que una URL sugiera un borrado directo
--     sobre tablas"). El front tiene que pedir PATCH, no DELETE.
--   * :tipo en minúscula -> :TIPO. ParamNamespace exige
--     [A-Z][A-Z0-9_]* para cualquier variable de ruta.
--
-- Regla de negocio PEI/PEC/PMI (confirmada por el usuario):
--   * PEI y PEC son EXCLUYENTES -- un EE necesita uno u otro, nunca los
--     dos. Se resuelve por TESTABLECIMIENTO.ETNIAS: 'S' (etnoeducativo)
--     -> aplica PEC, PEI queda NO_APLICA; 'N' -> aplica PEI, PEC queda
--     NO_APLICA.
--   * PMI siempre aplica, para cualquier EE.
--   * globalProgress excluye del denominador los documentos NO_APLICA.

-- 1. Tablas -- mismo formato TXXX de siempre, FK a TESTABLECIMIENTO y
--    al TARCHIVO real de academico_test (no al pigse.tarchivo de V148:
--    ver el punto 2 más abajo, el bind pasa a apuntar acá).
CREATE TABLE IF NOT EXISTS academico_test.tdocumento_institucional (
    pk_documento_institucional BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    fk_testablecimiento        BIGINT NOT NULL,
    tipo                       VARCHAR(10) NOT NULL,
    fk_tarchivo                BIGINT,
    created_by                 VARCHAR(120) NOT NULL,
    created_at                 TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    modified_by                VARCHAR(120),
    modified_at                TIMESTAMP,
    active                     BOOLEAN DEFAULT TRUE NOT NULL,
    CONSTRAINT tdocumento_institucional_pk PRIMARY KEY (pk_documento_institucional),
    CONSTRAINT tdocumento_institucional_tipo_chk CHECK (tipo IN ('PEI', 'PEC', 'PMI')),
    CONSTRAINT fk_tdocumento_inst_testablec FOREIGN KEY (fk_testablecimiento)
        REFERENCES academico_test.testablecimiento (pk_establecimiento),
    CONSTRAINT fk_tdocumento_inst_tarchivo FOREIGN KEY (fk_tarchivo)
        REFERENCES academico_test.tarchivo (pk_tarchivo)
);

-- Un documento VIGENTE por EE+tipo -- reemplazar es UPDATE, no un
-- segundo INSERT (ver fn_pigse_documento_guardar).
CREATE UNIQUE INDEX IF NOT EXISTS uq_tdocumento_inst_ee_tipo
    ON academico_test.tdocumento_institucional (fk_testablecimiento, tipo)
    WHERE active = true;

CREATE TABLE IF NOT EXISTS academico_test.tdocumento_institucional_hist (
    pk_documento_institucional_hist BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    fk_documento_institucional       BIGINT NOT NULL,
    fk_tarchivo                      BIGINT NOT NULL,
    reemplazado_by                   VARCHAR(120) NOT NULL,
    reemplazado_at                   TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT tdoc_inst_hist_pk PRIMARY KEY (pk_documento_institucional_hist),
    CONSTRAINT fk_tdoc_inst_hist_doc FOREIGN KEY (fk_documento_institucional)
        REFERENCES academico_test.tdocumento_institucional (pk_documento_institucional),
    CONSTRAINT fk_tdoc_inst_hist_archivo FOREIGN KEY (fk_tarchivo)
        REFERENCES academico_test.tarchivo (pk_tarchivo)
);

COMMENT ON TABLE academico_test.tdocumento_institucional IS
    'PIGSE — documento institucional vigente por establecimiento y tipo (PEI/PEC/PMI). fk_tarchivo NULL = PENDIENTE.';
COMMENT ON TABLE academico_test.tdocumento_institucional_hist IS
    'PIGSE — versiones reemplazadas (upload nuevo) o retiradas (PATCH .../:TIPO) de un documento institucional.';


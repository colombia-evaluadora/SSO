-- 5. Funciones PL/pgSQL -- mismo patrón que fn_est_crear (V53):
--    "SELECT schema.fn_x(...)" es la query que se guarda en el
--    catálogo; la función hace el trabajo real (incluida cualquier
--    escritura) y el statement que ve query-service sigue siendo un
--    SELECT.

-- Establecimiento del usuario autenticado -- mismo join que
-- FileDestinationAccessService#establecimientoDelUsuario (file-service,
-- V66), acá en SQL porque estas queries lo necesitan del lado del
-- catálogo, no de file-service. A diferencia de esa versión (que
-- devuelve Optional.empty() en la ambigüedad), acá se hace RAISE
-- EXCEPTION -- no hay "ruta feliz sin establecimiento" para un
-- endpoint de negocio como éste.
CREATE OR REPLACE FUNCTION academico_test.fn_pigse_mi_establecimiento(p_email TEXT)
RETURNS BIGINT AS $$
DECLARE
    v_pk    BIGINT;
    v_count INT;
BEGIN
    SELECT COUNT(DISTINCT te.pk_establecimiento), MIN(te.pk_establecimiento)
      INTO v_count, v_pk
      FROM academico_test.tusuario t
      JOIN academico_test.tsede_usuario su ON su.fk_tusuario = t.pk_tusuario
      JOIN academico_test.tsede s ON s.pk_tsede = su.fk_tsede
      JOIN academico_test.testablecimiento te ON te.pk_establecimiento = s.fk_testablecimiento
     WHERE upper(t.cuenta) = upper(p_email)
       AND t.active AND su.active AND su.tlv_estado = 'ACTIVO' AND s.active AND te.active;

    IF v_count IS NULL OR v_count <> 1 THEN
        RAISE EXCEPTION 'pigse: % no está vinculado a exactamente un establecimiento (encontrados: %)',
            p_email, COALESCE(v_count, 0);
    END IF;
    RETURN v_pk;
END;
$$ LANGUAGE plpgsql STABLE;

-- Documentos (PEI/PEC/PMI) de un EE, con status COMPLETO/PENDIENTE/
-- NO_APLICA -- ver la regla de exclusión PEI<->PEC al inicio del
-- archivo. Reusada por "documentos" (GET) y por cumplimiento/listar.
CREATE OR REPLACE FUNCTION academico_test.fn_pigse_documentos_listar(p_fk_establecimiento BIGINT)
RETURNS TABLE (
    id           TEXT,
    "type"       TEXT,
    "typeName"   TEXT,
    status       TEXT,
    "fileName"   TEXT,
    "uploadedAt" TIMESTAMP,
    "sizeBytes"  BIGINT
) AS $$
    SELECT
        tipos.tipo AS id,
        tipos.tipo AS "type",
        tipos.nombre AS "typeName",
        CASE
            WHEN tipos.tipo = 'PEI' AND te.etnias = 'S' THEN 'NO_APLICA'
            WHEN tipos.tipo = 'PEC' AND te.etnias = 'N' THEN 'NO_APLICA'
            WHEN d.fk_tarchivo IS NOT NULL THEN 'COMPLETO'
            ELSE 'PENDIENTE'
        END AS status,
        ta.nombre AS "fileName",
        ta.created_at AS "uploadedAt",
        ta.peso AS "sizeBytes"
      FROM academico_test.testablecimiento te
     CROSS JOIN (VALUES
                    ('PEI', 'Proyecto Educativo Institucional (PEI)'),
                    ('PEC', 'Proyecto Educativo Comunitario (PEC)'),
                    ('PMI', 'Plan de Mejoramiento Institucional (PMI)')
                ) AS tipos(tipo, nombre)
      LEFT JOIN academico_test.tdocumento_institucional d
             ON d.fk_testablecimiento = te.pk_establecimiento
            AND d.tipo = tipos.tipo
            AND d.active
      LEFT JOIN academico_test.tarchivo ta ON ta.pk_tarchivo = d.fk_tarchivo
     WHERE te.pk_establecimiento = p_fk_establecimiento
     ORDER BY tipos.tipo;
$$ LANGUAGE sql STABLE;

-- Sube (o reemplaza) el documento vigente de un EE+tipo. Reemplazar
-- es UPDATE de la fila vigente + INSERT en el histórico con el
-- fk_tarchivo saliente -- nunca un segundo INSERT en
-- tdocumento_institucional (el índice único ee+tipo activo lo
-- impediría igual).
CREATE OR REPLACE FUNCTION academico_test.fn_pigse_documento_guardar(
    p_pk_usuario   BIGINT,
    p_email        VARCHAR,
    p_tipo         VARCHAR,
    p_fk_tarchivo  BIGINT
)
RETURNS TABLE (
    id           TEXT,
    "type"       TEXT,
    "typeName"   TEXT,
    status       TEXT,
    "fileName"   TEXT,
    "uploadedAt" TIMESTAMP,
    "sizeBytes"  BIGINT
) AS $$
DECLARE
    v_fk_establecimiento BIGINT;
    v_pk_doc             BIGINT;
    v_fk_tarchivo_previo  BIGINT;
BEGIN
    IF p_fk_tarchivo IS NULL THEN
        RAISE EXCEPTION 'pigse: p_fk_tarchivo es obligatorio (archivo no subido)';
    END IF;

    v_fk_establecimiento := academico_test.fn_pigse_mi_establecimiento(p_email);

    SELECT pk_documento_institucional, fk_tarchivo
      INTO v_pk_doc, v_fk_tarchivo_previo
      FROM academico_test.tdocumento_institucional
     WHERE fk_testablecimiento = v_fk_establecimiento AND tipo = p_tipo AND active;

    IF v_pk_doc IS NULL THEN
        INSERT INTO academico_test.tdocumento_institucional
            (fk_testablecimiento, tipo, fk_tarchivo, created_by)
        VALUES (v_fk_establecimiento, p_tipo, p_fk_tarchivo, p_email)
        RETURNING pk_documento_institucional INTO v_pk_doc;
    ELSE
        UPDATE academico_test.tdocumento_institucional
           SET fk_tarchivo = p_fk_tarchivo, modified_by = p_email, modified_at = CURRENT_TIMESTAMP
         WHERE pk_documento_institucional = v_pk_doc;

        IF v_fk_tarchivo_previo IS NOT NULL THEN
            INSERT INTO academico_test.tdocumento_institucional_hist
                (fk_documento_institucional, fk_tarchivo, reemplazado_by)
            VALUES (v_pk_doc, v_fk_tarchivo_previo, p_email);
        END IF;
    END IF;

    RETURN QUERY
    SELECT * FROM academico_test.fn_pigse_documentos_listar(v_fk_establecimiento)
     WHERE fn_pigse_documentos_listar.id = p_tipo;
END;
$$ LANGUAGE plpgsql;

-- Retira la versión vigente (vuelve a PENDIENTE) -- NO borra el
-- archivo físico ni la fila de TARCHIVO, sólo desvincula y deja
-- rastro en el histórico (misma tabla que usa un reemplazo por
-- upload). Ver javadoc de ArchivoRepository#descartar en file-service
-- para el motivo equivalente del lado de S3: nunca borrar en el
-- camino feliz, sólo dejar de referenciar.
CREATE OR REPLACE FUNCTION academico_test.fn_pigse_documento_eliminar(
    p_pk_usuario BIGINT,
    p_email      VARCHAR,
    p_tipo       VARCHAR
)
RETURNS TABLE (
    id           TEXT,
    "type"       TEXT,
    "typeName"   TEXT,
    status       TEXT,
    "fileName"   TEXT,
    "uploadedAt" TIMESTAMP,
    "sizeBytes"  BIGINT
) AS $$
DECLARE
    v_fk_establecimiento BIGINT;
    v_pk_doc             BIGINT;
    v_fk_tarchivo_previo BIGINT;
BEGIN
    v_fk_establecimiento := academico_test.fn_pigse_mi_establecimiento(p_email);

    SELECT pk_documento_institucional, fk_tarchivo
      INTO v_pk_doc, v_fk_tarchivo_previo
      FROM academico_test.tdocumento_institucional
     WHERE fk_testablecimiento = v_fk_establecimiento AND tipo = p_tipo AND active;

    IF v_pk_doc IS NULL OR v_fk_tarchivo_previo IS NULL THEN
        RAISE EXCEPTION 'pigse: tipo % desconocido o ya está PENDIENTE para este establecimiento', p_tipo
            USING ERRCODE = 'P0002';
    END IF;

    UPDATE academico_test.tdocumento_institucional
       SET fk_tarchivo = NULL, modified_by = p_email, modified_at = CURRENT_TIMESTAMP
     WHERE pk_documento_institucional = v_pk_doc;

    INSERT INTO academico_test.tdocumento_institucional_hist
        (fk_documento_institucional, fk_tarchivo, reemplazado_by)
    VALUES (v_pk_doc, v_fk_tarchivo_previo, p_email);

    RETURN QUERY
    SELECT * FROM academico_test.fn_pigse_documentos_listar(v_fk_establecimiento)
     WHERE fn_pigse_documentos_listar.id = p_tipo;
END;
$$ LANGUAGE plpgsql;

-- Métricas globales del tablero de cumplimiento -- una sola fila,
-- cada tipo como sub-objeto JSON (mismo shape que espera el front).
-- Denominador de "total" excluye NO_APLICA por tipo (regla PEI<->PEC).
CREATE OR REPLACE FUNCTION academico_test.fn_pigse_cumplimiento_metricas()
RETURNS TABLE (
    "totalEstablishments" BIGINT,
    pei                   JSONB,
    pec                   JSONB,
    pmi                   JSONB
) AS $$
    WITH ee AS (
        SELECT pk_establecimiento, etnias FROM academico_test.testablecimiento WHERE active
    ),
    docs AS (
        SELECT ee.pk_establecimiento,
               d.tipo,
               d.fk_tarchivo IS NOT NULL AS completo
          FROM ee
          LEFT JOIN academico_test.tdocumento_institucional d
                 ON d.fk_testablecimiento = ee.pk_establecimiento AND d.active
    )
    SELECT
        (SELECT count(*) FROM ee) AS "totalEstablishments",
        jsonb_build_object(
            'completed', count(*) FILTER (WHERE docs.tipo = 'PEI' AND docs.completo),
            'total',     count(*) FILTER (WHERE ee.etnias = 'N'),
            'percent',   CASE WHEN count(*) FILTER (WHERE ee.etnias = 'N') = 0 THEN 0
                              ELSE round(100.0 * count(*) FILTER (WHERE docs.tipo = 'PEI' AND docs.completo)
                                         / count(*) FILTER (WHERE ee.etnias = 'N'))
                          END
        ) AS pei,
        jsonb_build_object(
            'completed', count(*) FILTER (WHERE docs.tipo = 'PEC' AND docs.completo),
            'total',     count(*) FILTER (WHERE ee.etnias = 'S'),
            'percent',   CASE WHEN count(*) FILTER (WHERE ee.etnias = 'S') = 0 THEN 0
                              ELSE round(100.0 * count(*) FILTER (WHERE docs.tipo = 'PEC' AND docs.completo)
                                         / count(*) FILTER (WHERE ee.etnias = 'S'))
                          END
        ) AS pec,
        jsonb_build_object(
            'completed', count(*) FILTER (WHERE docs.tipo = 'PMI' AND docs.completo),
            'total',     (SELECT count(*) FROM ee),
            'percent',   CASE WHEN (SELECT count(*) FROM ee) = 0 THEN 0
                              ELSE round(100.0 * count(*) FILTER (WHERE docs.tipo = 'PMI' AND docs.completo)
                                         / (SELECT count(*) FROM ee))
                          END
        ) AS pmi
      FROM ee
      LEFT JOIN docs ON docs.pk_establecimiento = ee.pk_establecimiento;
$$ LANGUAGE sql STABLE;

-- Detalle por establecimiento -- mismos status que fn_pigse_documentos_listar,
-- pivotados de 3 filas (PEI/PEC/PMI) a 3 columnas JSON.
-- globalProgress excluye NO_APLICA del denominador (PMI siempre cuenta;
-- de PEI/PEC sólo el que aplica para ese EE, ver la regla de exclusión
-- al inicio del archivo).
CREATE OR REPLACE FUNCTION academico_test.fn_pigse_cumplimiento_listar()
RETURNS TABLE (
    id                  BIGINT,
    "establishmentName" TEXT,
    pei                 JSONB,
    pec                 JSONB,
    pmi                 JSONB,
    "globalProgress"    INT
) AS $$
    SELECT
        te.pk_establecimiento AS id,
        te.nombre AS "establishmentName",
        jsonb_build_object('status', d_pei.status, 'fileName', d_pei."fileName") AS pei,
        jsonb_build_object('status', d_pec.status, 'fileName', d_pec."fileName") AS pec,
        jsonb_build_object('status', d_pmi.status, 'fileName', d_pmi."fileName") AS pmi,
        CASE
            WHEN (CASE WHEN d_pei.status <> 'NO_APLICA' THEN 1 ELSE 0 END
                  + CASE WHEN d_pec.status <> 'NO_APLICA' THEN 1 ELSE 0 END
                  + CASE WHEN d_pmi.status <> 'NO_APLICA' THEN 1 ELSE 0 END) = 0 THEN 0
            ELSE round(
                100.0 * (
                    CASE WHEN d_pei.status = 'COMPLETO' THEN 1 ELSE 0 END
                    + CASE WHEN d_pec.status = 'COMPLETO' THEN 1 ELSE 0 END
                    + CASE WHEN d_pmi.status = 'COMPLETO' THEN 1 ELSE 0 END
                ) / (
                    CASE WHEN d_pei.status <> 'NO_APLICA' THEN 1 ELSE 0 END
                    + CASE WHEN d_pec.status <> 'NO_APLICA' THEN 1 ELSE 0 END
                    + CASE WHEN d_pmi.status <> 'NO_APLICA' THEN 1 ELSE 0 END
                )
            )
        END AS "globalProgress"
      FROM academico_test.testablecimiento te
      JOIN LATERAL (
              SELECT * FROM academico_test.fn_pigse_documentos_listar(te.pk_establecimiento) WHERE id = 'PEI'
          ) d_pei ON true
      JOIN LATERAL (
              SELECT * FROM academico_test.fn_pigse_documentos_listar(te.pk_establecimiento) WHERE id = 'PEC'
          ) d_pec ON true
      JOIN LATERAL (
              SELECT * FROM academico_test.fn_pigse_documentos_listar(te.pk_establecimiento) WHERE id = 'PMI'
          ) d_pmi ON true
     WHERE te.active
     ORDER BY te.nombre;
$$ LANGUAGE sql STABLE;


-- ===========================================================================
-- fn_unidad_enunciado_relacionar
-- ===========================================================================
CREATE OR REPLACE FUNCTION academico_test.fn_unidad_enunciado_relacionar(
    p_pk_usuario_solicitante   BIGINT,
    p_fk_tunidad               BIGINT,
    p_fk_referente_enunciado   BIGINT
)
RETURNS BIGINT
LANGUAGE plpgsql
AS $$
DECLARE
    v_nombre_unidad       VARCHAR;
    v_nivel_unidad        BIGINT;
    v_padre_enunciado     BIGINT;
    v_nivel_enunciado     BIGINT;
    v_pk                  BIGINT;
BEGIN
    -- 0. Gate: capability EDITAR sobre PLANEADOR.
    PERFORM academico_test.fn_assert_permiso_seccion(
        p_pk_usuario_solicitante, 'PLANEADOR', 'EDITAR'
    );

    -- 1. Obligatorios.
    IF p_fk_tunidad IS NULL THEN
        RAISE EXCEPTION 'La unidad (FK_TUNIDAD) es obligatoria' USING ERRCODE = '22023';
    END IF;
    IF p_fk_referente_enunciado IS NULL THEN
        RAISE EXCEPTION 'El enunciado (FK_REFERENTE_ENUNCIADO) es obligatorio' USING ERRCODE = '22023';
    END IF;

    -- 2. Unidad existe/activa; nivel de ensenanza via su grado.
    SELECT u.NOMBRE, g.FK_TNIVEL_ENSENANZA
      INTO v_nombre_unidad, v_nivel_unidad
      FROM academico_test.TUNIDAD u
      JOIN academico_test.TGRADO g ON g.PK_TGRADO = u.FK_TGRADO
     WHERE u.PK_TUNIDAD = p_fk_tunidad
       AND u.ACTIVE = TRUE;

    IF v_nombre_unidad IS NULL THEN
        RAISE EXCEPTION 'FK_TUNIDAD (%) no existe o no esta activa', p_fk_tunidad USING ERRCODE = '23503';
    END IF;

    -- 3. Enunciado existe/activo, es nivel 1 (FK_PADRE IS NULL); nivel de
    --    ensenanza via su referente curricular.
    SELECT e.FK_PADRE, rc.FK_TNIVEL_ENSENANZA
      INTO v_padre_enunciado, v_nivel_enunciado
      FROM academico_test.TREFERENTE_ENUNCIADO e
      JOIN academico_test.TREFERENTE_CURRICULAR rc ON rc.PK_REFERENTE_CURRICULAR = e.FK_REFERENTE_CURRICULAR
     WHERE e.PK_REFERENTE_ENUNCIADO = p_fk_referente_enunciado
       AND e.ACTIVE = TRUE;

    IF v_nivel_enunciado IS NULL THEN
        RAISE EXCEPTION 'FK_REFERENTE_ENUNCIADO (%) no existe o no esta activo', p_fk_referente_enunciado USING ERRCODE = '23503';
    END IF;
    IF v_padre_enunciado IS NOT NULL THEN
        RAISE EXCEPTION 'FK_REFERENTE_ENUNCIADO (%) es una evidencia (nivel 2), no un enunciado (nivel 1)', p_fk_referente_enunciado
            USING ERRCODE = '22023';
    END IF;

    -- 4. Regla de negocio: mismo nivel de ensenanza entre unidad y referente
    --    curricular del enunciado.
    IF v_nivel_unidad IS DISTINCT FROM v_nivel_enunciado THEN
        RAISE EXCEPTION 'El enunciado (%) pertenece a un nivel de ensenanza distinto al de la unidad "%"', p_fk_referente_enunciado, v_nombre_unidad
            USING ERRCODE = '22023';
    END IF;

    -- 5. Get-or-create / reactivar sobre el indice unico parcial.
    SELECT PK_TUNIDAD_ENUNCIADO INTO v_pk
      FROM academico_test.TUNIDAD_ENUNCIADO
     WHERE FK_TUNIDAD = p_fk_tunidad
       AND FK_REFERENTE_ENUNCIADO = p_fk_referente_enunciado;

    IF v_pk IS NULL THEN
        INSERT INTO academico_test.TUNIDAD_ENUNCIADO (
            FK_TUNIDAD, FK_REFERENTE_ENUNCIADO, CREATED_BY, CREATED_AT, ACTIVE
        ) VALUES (
            p_fk_tunidad, p_fk_referente_enunciado, p_pk_usuario_solicitante::VARCHAR, CURRENT_TIMESTAMP, TRUE
        )
        RETURNING PK_TUNIDAD_ENUNCIADO INTO v_pk;
    ELSE
        UPDATE academico_test.TUNIDAD_ENUNCIADO
           SET ACTIVE = TRUE,
               MODIFIED_BY = p_pk_usuario_solicitante::VARCHAR,
               MODIFIED_AT = CURRENT_TIMESTAMP
         WHERE PK_TUNIDAD_ENUNCIADO = v_pk;
    END IF;

    RETURN v_pk;
END;
$$;

COMMENT ON FUNCTION academico_test.fn_unidad_enunciado_relacionar(BIGINT, BIGINT, BIGINT)
    IS 'Relaciona (o reactiva) un enunciado del referente curricular (TREFERENTE_ENUNCIADO nivel 1, FK_PADRE IS NULL) con una unidad (TUNIDAD_ENUNCIADO), validando que ambos compartan el mismo nivel de ensenanza (unidad: via TGRADO.FK_TNIVEL_ENSENANZA; enunciado: via TREFERENTE_CURRICULAR.FK_TNIVEL_ENSENANZA). Gate EDITAR sobre PLANEADOR. Retorna PK_TUNIDAD_ENUNCIADO. V136.';

-- ===========================================================================
-- fn_unidad_enunciado_quitar
-- ===========================================================================
CREATE OR REPLACE FUNCTION academico_test.fn_unidad_enunciado_quitar(
    p_pk_usuario_solicitante   BIGINT,
    p_pk_tunidad_enunciado     BIGINT
)
RETURNS BOOLEAN
LANGUAGE plpgsql
AS $$
BEGIN
    PERFORM academico_test.fn_assert_permiso_seccion(
        p_pk_usuario_solicitante, 'PLANEADOR', 'EDITAR'
    );

    IF NOT EXISTS (
        SELECT 1 FROM academico_test.TUNIDAD_ENUNCIADO
         WHERE PK_TUNIDAD_ENUNCIADO = p_pk_tunidad_enunciado AND ACTIVE = TRUE
    ) THEN
        RAISE EXCEPTION 'PK_TUNIDAD_ENUNCIADO (%) no existe o ya esta inactivo', p_pk_tunidad_enunciado USING ERRCODE = '23503';
    END IF;

    -- Desactiva en cascada las evidencias de actividades ligadas a esa
    -- unidad que colgaban de este enunciado (regla del punto 2: solo
    -- pueden existir mientras el enunciado siga relacionado con la unidad).
    UPDATE academico_test.TACTIVIDAD_EVIDENCIA ae
       SET ACTIVE = FALSE,
           MODIFIED_BY = p_pk_usuario_solicitante::VARCHAR,
           MODIFIED_AT = CURRENT_TIMESTAMP
      FROM academico_test.TUNIDAD_ENUNCIADO ue,
           academico_test.TREFERENTE_ENUNCIADO ev,
           academico_test.TACTIVIDAD a
     WHERE ue.PK_TUNIDAD_ENUNCIADO = p_pk_tunidad_enunciado
       AND ev.FK_PADRE = ue.FK_REFERENTE_ENUNCIADO
       AND ae.FK_REFERENTE_ENUNCIADO = ev.PK_REFERENTE_ENUNCIADO
       AND a.PK_TACTIVIDAD = ae.FK_TACTIVIDAD
       AND a.FK_TUNIDAD = ue.FK_TUNIDAD
       AND ae.ACTIVE = TRUE;

    UPDATE academico_test.TUNIDAD_ENUNCIADO
       SET ACTIVE = FALSE,
           MODIFIED_BY = p_pk_usuario_solicitante::VARCHAR,
           MODIFIED_AT = CURRENT_TIMESTAMP
     WHERE PK_TUNIDAD_ENUNCIADO = p_pk_tunidad_enunciado;

    RETURN TRUE;
END;
$$;

COMMENT ON FUNCTION academico_test.fn_unidad_enunciado_quitar(BIGINT, BIGINT)
    IS 'Borrado logico (ACTIVE=FALSE) de una relacion TUNIDAD_ENUNCIADO; arrastra la desactivacion de las TACTIVIDAD_EVIDENCIA de esa unidad cuyo enunciado padre era este. Gate EDITAR sobre PLANEADOR. V136.';

-- ===========================================================================
-- fn_actividad_evidencia_relacionar
-- ===========================================================================
CREATE OR REPLACE FUNCTION academico_test.fn_actividad_evidencia_relacionar(
    p_pk_usuario_solicitante   BIGINT,
    p_fk_tactividad            BIGINT,
    p_fk_referente_enunciado   BIGINT
)
RETURNS BIGINT
LANGUAGE plpgsql
AS $$
DECLARE
    v_titulo_actividad    VARCHAR;
    v_fk_tunidad          BIGINT;
    v_padre_evidencia     BIGINT;
    v_pk                  BIGINT;
BEGIN
    -- 0. Gate: capability EDITAR sobre PLANEADOR.
    PERFORM academico_test.fn_assert_permiso_seccion(
        p_pk_usuario_solicitante, 'PLANEADOR', 'EDITAR'
    );

    -- 1. Obligatorios.
    IF p_fk_tactividad IS NULL THEN
        RAISE EXCEPTION 'La actividad (FK_TACTIVIDAD) es obligatoria' USING ERRCODE = '22023';
    END IF;
    IF p_fk_referente_enunciado IS NULL THEN
        RAISE EXCEPTION 'La evidencia (FK_REFERENTE_ENUNCIADO) es obligatoria' USING ERRCODE = '22023';
    END IF;

    -- 2. Actividad existe/activa y tiene unidad relacionada (FK_TUNIDAD
    --    NOT NULL).
    SELECT a.TITULO, a.FK_TUNIDAD
      INTO v_titulo_actividad, v_fk_tunidad
      FROM academico_test.TACTIVIDAD a
     WHERE a.PK_TACTIVIDAD = p_fk_tactividad
       AND a.ACTIVE = TRUE;

    IF v_titulo_actividad IS NULL THEN
        RAISE EXCEPTION 'FK_TACTIVIDAD (%) no existe o no esta activa', p_fk_tactividad USING ERRCODE = '23503';
    END IF;
    IF v_fk_tunidad IS NULL THEN
        RAISE EXCEPTION 'La actividad "%" no tiene una unidad relacionada (FK_TUNIDAD)', v_titulo_actividad
            USING ERRCODE = '22023';
    END IF;

    -- 3. Evidencia existe/activa y es nivel 2 (FK_PADRE NOT NULL).
    SELECT e.FK_PADRE INTO v_padre_evidencia
      FROM academico_test.TREFERENTE_ENUNCIADO e
     WHERE e.PK_REFERENTE_ENUNCIADO = p_fk_referente_enunciado
       AND e.ACTIVE = TRUE;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'FK_REFERENTE_ENUNCIADO (%) no existe o no esta activo', p_fk_referente_enunciado USING ERRCODE = '23503';
    END IF;
    IF v_padre_evidencia IS NULL THEN
        RAISE EXCEPTION 'FK_REFERENTE_ENUNCIADO (%) es un enunciado (nivel 1), no una evidencia (nivel 2)', p_fk_referente_enunciado
            USING ERRCODE = '22023';
    END IF;

    -- 4. Regla de negocio: el enunciado padre de la evidencia debe estar
    --    relacionado (activo) con la unidad de la actividad.
    IF NOT EXISTS (
        SELECT 1 FROM academico_test.TUNIDAD_ENUNCIADO ue
         WHERE ue.FK_TUNIDAD = v_fk_tunidad
           AND ue.FK_REFERENTE_ENUNCIADO = v_padre_evidencia
           AND ue.ACTIVE = TRUE
    ) THEN
        RAISE EXCEPTION 'El enunciado padre de la evidencia (%) no esta relacionado con la unidad de la actividad "%"', p_fk_referente_enunciado, v_titulo_actividad
            USING ERRCODE = '22023';
    END IF;

    -- 5. Get-or-create / reactivar sobre el indice unico parcial.
    SELECT PK_TACTIVIDAD_EVIDENCIA INTO v_pk
      FROM academico_test.TACTIVIDAD_EVIDENCIA
     WHERE FK_TACTIVIDAD = p_fk_tactividad
       AND FK_REFERENTE_ENUNCIADO = p_fk_referente_enunciado;

    IF v_pk IS NULL THEN
        INSERT INTO academico_test.TACTIVIDAD_EVIDENCIA (
            FK_TACTIVIDAD, FK_REFERENTE_ENUNCIADO, CREATED_BY, CREATED_AT, ACTIVE
        ) VALUES (
            p_fk_tactividad, p_fk_referente_enunciado, p_pk_usuario_solicitante::VARCHAR, CURRENT_TIMESTAMP, TRUE
        )
        RETURNING PK_TACTIVIDAD_EVIDENCIA INTO v_pk;
    ELSE
        UPDATE academico_test.TACTIVIDAD_EVIDENCIA
           SET ACTIVE = TRUE,
               MODIFIED_BY = p_pk_usuario_solicitante::VARCHAR,
               MODIFIED_AT = CURRENT_TIMESTAMP
         WHERE PK_TACTIVIDAD_EVIDENCIA = v_pk;
    END IF;

    RETURN v_pk;
END;
$$;

COMMENT ON FUNCTION academico_test.fn_actividad_evidencia_relacionar(BIGINT, BIGINT, BIGINT)

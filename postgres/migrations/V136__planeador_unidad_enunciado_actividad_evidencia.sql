-- ===========================================================================
-- V136 — Planeador educativo: relaciones UNIDAD<->ENUNCIADO (referente
-- curricular) y ACTIVIDAD<->EVIDENCIA (CU-86e311xxp).
--
-- Contexto (diagrama de dependencias del Planeador):
--   * TUNIDAD ya se acoge opcionalmente a UN TREFERENTE_CURRICULAR
--     (FK_REFERENTE_CURRICULAR, V212/V216). Falta el detalle: cuales
--     ENUNCIADOS de ese arbol curricular aplican/se seleccionaron para
--     esa unidad concreta.
--   * TREFERENTE_ENUNCIADO (V212, rama CU-86e311xqh) es una UNICA tabla
--     auto-referenciada via FK_PADRE que modela tanto "enunciados"
--     (FK_PADRE IS NULL, nivel 1) como "evidencias" (FK_PADRE NOT NULL,
--     nivel 2, hijas de un enunciado) -- NO existen tablas separadas
--     ENUNCIADO/EVIDENCIA. Ver V212 para el detalle del modelo.
--   * TACTIVIDAD tiene FK_TUNIDAD (V22; se vuelve NULLABLE en V218,
--     rama CU-86e329pvq, no mergeada aqui todavia -- hoy en esta rama
--     sigue NOT NULL). Una actividad ligada a una unidad puede marcar
--     que EVIDENCIAS (nivel 2 de TREFERENTE_ENUNCIADO) sustenta, pero
--     solo las que cuelguen de un enunciado que YA fue relacionado con
--     esa unidad (tabla del punto 1).
--
-- Tablas nuevas:
--   1) TUNIDAD_ENUNCIADO         -- N:N TUNIDAD <-> TREFERENTE_ENUNCIADO
--                                    (solo nivel 1, FK_PADRE IS NULL).
--   2) TACTIVIDAD_EVIDENCIA      -- N:N TACTIVIDAD <-> TREFERENTE_ENUNCIADO
--                                    (solo nivel 2, FK_PADRE NOT NULL).
--   3) TACTIVIDAD_CRITERIO_UNIDAD -- N:N TACTIVIDAD <-> TCRITERIO_UNIDAD
--                                    (criterios de la rubrica de la unidad
--                                    de la actividad, V22).
--
-- Validacion de reglas de negocio: siguiendo el patron ya usado en el
-- repo (fn_unidad_crear V216, fn_actividad_crear V224 -- ver
-- fn_assert_permiso_seccion y validaciones de FKs "existe y esta activo"
-- dentro de la funcion, NO triggers de tabla), las reglas se validan en
-- fn_unidad_enunciado_relacionar, fn_actividad_evidencia_relacionar y
-- fn_actividad_criterio_relacionar:
--   * fn_unidad_enunciado_relacionar: el enunciado debe ser de nivel 1
--     (FK_PADRE IS NULL) y su referente curricular debe tener el MISMO
--     nivel de ensenanza que la unidad (nivel de la unidad = nivel del
--     TGRADO de la unidad, via TGRADO.FK_TNIVEL_ENSENANZA).
--   * fn_actividad_evidencia_relacionar: la evidencia debe ser de nivel 2
--     (FK_PADRE NOT NULL) y su padre (el enunciado) debe estar presente
--     en TUNIDAD_ENUNCIADO para la MISMA unidad de la actividad
--     (TACTIVIDAD.FK_TUNIDAD).
--   * fn_actividad_criterio_relacionar: el criterio (TCRITERIO_UNIDAD)
--     debe pertenecer a la rubrica (TRUBRICA_UNIDAD) de la MISMA unidad
--     que la actividad (TACTIVIDAD.FK_TUNIDAD).
--
-- Nomenclatura/estilo: sigue V22/V212/V216 (mayusculas, PK_/FK_ BIGINT
-- IDENTITY, auditoria CREATED_BY/CREATED_AT/MODIFIED_BY/MODIFIED_AT +
-- ACTIVE, indice parcial IDX_..._ACTIVE WHERE ACTIVE = true, unicidad
-- solo entre filas vivas via indice unico parcial -- patron V65) y
-- V216/V224 (gate fn_assert_permiso_seccion sobre la seccion PLANEADOR,
-- get-or-create/reactivar sobre UNIQUE parcial, RAISE EXCEPTION con
-- nombre legible + ERRCODE).
-- ===========================================================================

SET search_path TO academico_test, public;

-- ---------------------------------------------------------------------------
-- 1) Tabla: TUNIDAD_ENUNCIADO
-- ---------------------------------------------------------------------------

CREATE TABLE IF NOT EXISTS TUNIDAD_ENUNCIADO (
  PK_TUNIDAD_ENUNCIADO BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  FK_TUNIDAD BIGINT NOT NULL,
  FK_REFERENTE_ENUNCIADO BIGINT NOT NULL,
  CREATED_BY VARCHAR(120) NOT NULL,
  CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
  MODIFIED_BY VARCHAR(120),
  MODIFIED_AT TIMESTAMP,
  ACTIVE BOOLEAN DEFAULT TRUE NOT NULL,
  CONSTRAINT PK_TUNIDAD_ENUNCIADO PRIMARY KEY (PK_TUNIDAD_ENUNCIADO),
  CONSTRAINT FK_TUNIDAD_ENUNCIADO_UNIDAD FOREIGN KEY (FK_TUNIDAD)
    REFERENCES TUNIDAD (PK_TUNIDAD) ON DELETE CASCADE,
  CONSTRAINT FK_TUNIDAD_ENUNCIADO_ENUNCIADO FOREIGN KEY (FK_REFERENTE_ENUNCIADO)
    REFERENCES TREFERENTE_ENUNCIADO (PK_REFERENTE_ENUNCIADO)
);

--  Indices
CREATE INDEX IF NOT EXISTS IDX_TUNIDAD_ENUNCIADO_UNIDAD ON TUNIDAD_ENUNCIADO (FK_TUNIDAD);
CREATE INDEX IF NOT EXISTS IDX_TUNIDAD_ENUNCIADO_ENUNCIADO ON TUNIDAD_ENUNCIADO (FK_REFERENTE_ENUNCIADO);
CREATE INDEX IF NOT EXISTS IDX_TUNIDAD_ENUNCIADO_ACTIVE ON TUNIDAD_ENUNCIADO (PK_TUNIDAD_ENUNCIADO) WHERE ACTIVE = true;

-- Unicidad solo entre filas vivas (patron V65): el mismo par unidad/enunciado
-- puede reinsertarse tras un borrado logico sin chocar con la fila inactiva.
CREATE UNIQUE INDEX IF NOT EXISTS U_TUNIDAD_ENUNCIADO_1
  ON TUNIDAD_ENUNCIADO (FK_TUNIDAD, FK_REFERENTE_ENUNCIADO)
  WHERE ACTIVE = true;

--  Comentarios de columna
COMMENT ON COLUMN TUNIDAD_ENUNCIADO.PK_TUNIDAD_ENUNCIADO IS 'Llave primaria de la tabla';
COMMENT ON COLUMN TUNIDAD_ENUNCIADO.FK_TUNIDAD IS 'Llave foranea a tabla TUNIDAD';
COMMENT ON COLUMN TUNIDAD_ENUNCIADO.FK_REFERENTE_ENUNCIADO IS 'Llave foranea a TREFERENTE_ENUNCIADO (nivel 1, FK_PADRE IS NULL) del mismo nivel de ensenanza que la unidad; el enunciado marcado como aplicable/seleccionado para esa unidad';

--  Comentario de tabla
COMMENT ON TABLE TUNIDAD_ENUNCIADO IS 'Relacion N:N entre TUNIDAD y los enunciados (TREFERENTE_ENUNCIADO nivel 1) del referente curricular que aplican a esa unidad';

-- ---------------------------------------------------------------------------
-- 2) Tabla: TACTIVIDAD_EVIDENCIA
-- ---------------------------------------------------------------------------


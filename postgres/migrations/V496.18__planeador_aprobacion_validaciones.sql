CREATE OR REPLACE FUNCTION academico_test.fn_solicitud_valor_vigente_recuperacion(
    p_pk_tactividad_estudiante BIGINT,
    p_tipo                     VARCHAR
)
RETURNS JSONB
LANGUAGE sql
STABLE
AS $$
    SELECT CASE WHEN p_tipo = 'RECUPERACION_REFUERZO' THEN
               (SELECT jsonb_build_object('calificacion', n.CALIFICACION, 'definitiva', n.DEFINITIVA)
                  FROM academico_test.TACTIVIDAD_ESTUDIANTE o
                  JOIN academico_test.TACTIVIDAD_NOTA n ON n.FK_TACTIVIDAD_ESTUDIANTE = o.PK_TACTIVIDAD_ESTUDIANTE AND n.ACTIVE = TRUE
                 WHERE o.FK_TACTIVIDAD = r.FK_TACTIVIDAD_RECUPERAR AND o.FK_TMATRICULA = ae.FK_TMATRICULA AND o.ACTIVE = TRUE)
           ELSE
               (SELECT jsonb_build_object('calificacion', sn.CALIFICACION, 'definitiva', sn.DEFINITIVA)
                  FROM academico_test.TASIGNATURA_NOTA sn
                 WHERE sn.FK_TMATRICULA = ae.FK_TMATRICULA AND sn.FK_TASIGNATURA = a.FK_TASIGNATURA AND sn.ACTIVE = TRUE
                   AND sn.FK_TPERIODO_EVALUACION = academico_test.fn_actividad_periodo_evaluacion(a.PK_TACTIVIDAD, ae.FK_TMATRICULA))
           END
      FROM academico_test.TACTIVIDAD_ESTUDIANTE ae
      JOIN academico_test.TACTIVIDAD a ON a.PK_TACTIVIDAD = ae.FK_TACTIVIDAD
      JOIN academico_test.TACTIVIDAD_RECUPERACION r ON r.FK_TACTIVIDAD = a.PK_TACTIVIDAD AND r.ACTIVE = TRUE
     WHERE ae.PK_TACTIVIDAD_ESTUDIANTE = p_pk_tactividad_estudiante;
$$;

COMMENT ON FUNCTION academico_test.fn_solicitud_valor_vigente_recuperacion(BIGINT, VARCHAR)
    IS 'Regla 70: valor que conserva el destino mientras la solicitud de recuperación está pendiente, {calificacion, definitiva}. RECUPERACION_REFUERZO: la nota del estudiante en la actividad original; otro tipo (Habilitación): su TASIGNATURA_NOTA del periodo de la actividad. NULL si no hay nota vigente. La usa fn_actividad_recuperacion_consolidar al abrir la solicitud.';

-- ---------------------------------------------------------------------------
-- Regla 31: el tope de recuperación rechaza; antes recortaba con LEAST.
-- Cuerpo de V227 con ese único cambio.
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION academico_test.fn_actividad_nota_ajustar_por_criterio(
    p_pk_tactividad BIGINT,
    p_valor         NUMERIC
)
RETURNS NUMERIC
LANGUAGE plpgsql
STABLE
AS $$
DECLARE
    v_fk_tgrado        BIGINT;
    v_fk_tasignatura   BIGINT;
    v_es_recuperacion  CHAR(1);
    v_pk_criterio      BIGINT;
    v_piso             NUMERIC;
    v_tope             NUMERIC;
    v_valor            NUMERIC := p_valor;
BEGIN
    IF v_valor IS NULL THEN
        RETURN NULL;
    END IF;

    SELECT a.FK_TASIGNATURA, a.ES_RECUPERACION
      INTO v_fk_tasignatura, v_es_recuperacion
      FROM academico_test.TACTIVIDAD a
     WHERE a.PK_TACTIVIDAD = p_pk_tactividad;

    v_fk_tgrado := academico_test.fn_actividad_grado_resolver(p_pk_tactividad);
    IF v_fk_tgrado IS NULL OR v_fk_tasignatura IS NULL THEN
        RETURN v_valor;
    END IF;

    v_pk_criterio := academico_test.fn_asignatura_criterio_evaluacion_vigente(v_fk_tasignatura, v_fk_tgrado);
    IF v_pk_criterio IS NULL THEN
        RETURN v_valor;
    END IF;

    IF v_es_recuperacion = 'S' THEN
        v_tope := academico_test.fn_criterio_evaluacion_porcentaje_maximo_recuperacion(v_pk_criterio);
        IF v_tope IS NOT NULL AND v_valor > v_tope THEN
            RAISE EXCEPTION 'La nota de recuperación de % (% %%) supera la nota máxima de recuperación del colegio (% %%)',
                academico_test.fn_actividad_etiqueta(p_pk_tactividad), round(v_valor, 2), v_tope
                USING ERRCODE = '22023';
        END IF;
    END IF;

    -- El piso va después: levanta también una recuperación.
    v_piso := academico_test.fn_criterio_evaluacion_porcentaje_inicial(v_pk_criterio);
    IF v_piso IS NOT NULL THEN
        v_valor := GREATEST(v_valor, v_piso);
    END IF;

    RETURN v_valor;
END;
$$;

COMMENT ON FUNCTION academico_test.fn_actividad_nota_ajustar_por_criterio(BIGINT, NUMERIC)
    IS 'Punto único de los dos límites de TCRITERIO_EVALUACION sobre una calificación (porcentaje 0-100). Regla 31: en una actividad de recuperación, un valor por encima de PORCENTAJE_MAXIMO_RECUPERACION se RECHAZA con 22023 (antes se recortaba). Después aplica el piso PORCENTAJE_INICIAL_CALIF a cualquier actividad. Sin grado, asignatura o criterio devuelve el valor intacto; NULL entra y sale NULL. No redondea. La usan los _interno de calificación (V496.6), el recálculo de V469 y la consolidación de la recuperación, que recorta antes la definitiva combinada para que el rechazo solo aplique a lo que digita el docente.';

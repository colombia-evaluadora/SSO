-- ---------------------------------------------------------------------------
-- Estado del periodo de evaluación (catálogo ESTADOPERIODOEVALUACION)
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION academico_test.fn_periodo_evaluacion_calificable(p_pk_tperiodo_evaluacion BIGINT)
RETURNS BOOLEAN
LANGUAGE sql
STABLE
AS $$
    -- VALOR '1' es "Calificable" (V339/V418); el nombre cubre un catálogo recodificado.
    SELECT lv.VALOR = '1' OR upper(TRIM(lv.NOMBRE)) = 'CALIFICABLE'
      FROM academico_test.TPERIODO_EVALUACION pe
      JOIN academico_test.TLISTA_VALOR lv ON lv.PK_LISTA_VALOR = pe.FK_TLV_ESTADO
     WHERE pe.PK_TPERIODO_EVALUACION = p_pk_tperiodo_evaluacion;
$$;

COMMENT ON FUNCTION academico_test.fn_periodo_evaluacion_calificable(BIGINT)
    IS 'TRUE si el periodo de evaluación está Calificable (Activo en el documento: Reglas 55, 75). NULL si el periodo no existe. La usan las reglas de "cuándo se exige aprobación".';

CREATE OR REPLACE FUNCTION academico_test.fn_periodo_evaluacion_admite_refuerzo(p_pk_tperiodo_evaluacion BIGINT)
RETURNS BOOLEAN
LANGUAGE sql
STABLE
AS $$
    -- "En Recuperaciones" es justamente el estado abierto para recuperar.
    SELECT academico_test.fn_periodo_evaluacion_calificable(pe.PK_TPERIODO_EVALUACION)
           OR upper(lv.NOMBRE) LIKE '%RECUPERACI%'
      FROM academico_test.TPERIODO_EVALUACION pe
      JOIN academico_test.TLISTA_VALOR lv ON lv.PK_LISTA_VALOR = pe.FK_TLV_ESTADO
     WHERE pe.PK_TPERIODO_EVALUACION = p_pk_tperiodo_evaluacion;
$$;

COMMENT ON FUNCTION academico_test.fn_periodo_evaluacion_admite_refuerzo(BIGINT)
    IS 'Regla 69: el periodo de la actividad original sigue vigente para un Refuerzo (Calificable o En Recuperaciones). NULL si el periodo no existe.';

-- ---------------------------------------------------------------------------
-- Cuándo se exige aprobación. Devuelven el TIPO, o NULL si se aplica directo.
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION academico_test.fn_recuperacion_tipo_aprobacion(p_pk_tactividad_estudiante BIGINT)
RETURNS VARCHAR
LANGUAGE sql
STABLE
AS $$
    -- Habilitación = destino NOTA_FINAL, siempre (Regla 69); Refuerzo = destino
    -- ACTIVIDAD, solo si el periodo de la ORIGINAL ya no está vigente. Un
    -- Refuerzo sin periodo resoluble se aplica directo, como hasta ahora.
    SELECT CASE
             WHEN lv.VALOR = 'NOTA_FINAL' THEN 'RECUPERACION_HABILITACION'
             WHEN lv.VALOR = 'ACTIVIDAD'
              AND academico_test.fn_periodo_evaluacion_admite_refuerzo(
                      academico_test.fn_actividad_periodo_evaluacion(r.FK_TACTIVIDAD_RECUPERAR, ae.FK_TMATRICULA)) = FALSE
                  THEN 'RECUPERACION_REFUERZO'
           END
      FROM academico_test.TACTIVIDAD_ESTUDIANTE ae
      JOIN academico_test.TACTIVIDAD a ON a.PK_TACTIVIDAD = ae.FK_TACTIVIDAD AND a.ES_RECUPERACION = 'S'
      JOIN academico_test.TACTIVIDAD_RECUPERACION r ON r.FK_TACTIVIDAD = a.PK_TACTIVIDAD AND r.ACTIVE = TRUE
      JOIN academico_test.TLISTA_VALOR lv ON lv.PK_LISTA_VALOR = r.FK_TLV_DESTINO_RECUPERACION
     WHERE ae.PK_TACTIVIDAD_ESTUDIANTE = p_pk_tactividad_estudiante;
$$;

CREATE OR REPLACE FUNCTION academico_test.fn_resultado_correccion_requiere_aprobacion(
    p_pk_tactividad_estudiante BIGINT,
    p_porcentaje               NUMERIC
)
RETURNS BOOLEAN
LANGUAGE sql
STABLE
AS $$
    -- Regla 55: solo CORREGIR un resultado ya capturado. La primera captura y
    -- las recuperaciones (que pasan por la Regla 69) no entran aquí.
    SELECT COALESCE(
             n.CALIFICACION IS NOT NULL
             AND p_porcentaje IS DISTINCT FROM n.CALIFICACION
             AND academico_test.fn_periodo_evaluacion_calificable(
                     academico_test.fn_actividad_periodo_evaluacion(ae.FK_TACTIVIDAD, ae.FK_TMATRICULA)) = FALSE,
             FALSE)
      FROM academico_test.TACTIVIDAD_ESTUDIANTE ae
      JOIN academico_test.TACTIVIDAD a ON a.PK_TACTIVIDAD = ae.FK_TACTIVIDAD
      LEFT JOIN academico_test.TACTIVIDAD_NOTA n
             ON n.FK_TACTIVIDAD_ESTUDIANTE = ae.PK_TACTIVIDAD_ESTUDIANTE AND n.ACTIVE = TRUE
     WHERE ae.PK_TACTIVIDAD_ESTUDIANTE = p_pk_tactividad_estudiante
       AND a.ES_RECUPERACION IS DISTINCT FROM 'S';
$$;

CREATE OR REPLACE FUNCTION academico_test.fn_asistencia_fecha_requiere_aprobacion(p_fk_tgrupo BIGINT, p_fecha DATE)
RETURNS BOOLEAN
LANGUAGE sql
STABLE
AS $$
    -- Regla 75: manda el periodo DE EVALUACIÓN de la fecha de la sesión. Un
    -- periodo que ya terminó por fechas también exige aprobación aunque siga
    -- Calificable. NULL si la fecha no cae en ninguno: bloqueo plano (V136).
    SELECT NOT academico_test.fn_periodo_evaluacion_calificable(pe.PK_TPERIODO_EVALUACION)
           OR pe.FECHA_FIN < CURRENT_DATE
      FROM academico_test.TPERIODO_EVALUACION pe
     WHERE pe.PK_TPERIODO_EVALUACION = academico_test.fn_asistencia_periodo_eval(p_fk_tgrupo, p_fecha);
$$;

COMMENT ON FUNCTION academico_test.fn_asistencia_fecha_requiere_aprobacion(BIGINT, DATE)
    IS 'TRUE si escribir asistencia de esa fecha exige aprobación del Coordinador (Regla 75: su periodo de evaluación no es Calificable o ya terminó por fechas); NULL si la fecha no cae en ningún periodo. La usan fn_asistencia_correccion_requiere_aprobacion y fn_asistencia_registrar_bulk.';


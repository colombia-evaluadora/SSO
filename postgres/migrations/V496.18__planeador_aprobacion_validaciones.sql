-- Regla 70: una recuperación ya aprobada con ESA nota se reconsolida sin pedir
-- de nuevo (cambió la base, no lo aprobado); otra nota vuelve a pedirla.
CREATE OR REPLACE FUNCTION academico_test.fn_recuperacion_aprobada_vigente(
    p_pk_tactividad_estudiante BIGINT,
    p_tipo                     VARCHAR,
    p_nota_recuperacion        NUMERIC
)
RETURNS BOOLEAN
LANGUAGE sql
STABLE
AS $$
    SELECT COALESCE((
        SELECT lv.VALOR = 'APROBADA'
               AND (s.VALOR_PROPUESTO->>'notaRecuperacion')::NUMERIC = p_nota_recuperacion
          FROM academico_test.TSOLICITUD_APROBACION s
          JOIN academico_test.TLISTA_VALOR lv ON lv.PK_LISTA_VALOR = s.FK_TLV_ESTADO
         WHERE s.TABLA_OBJETO = 'TACTIVIDAD_ESTUDIANTE'
           AND s.FK_OBJETO = p_pk_tactividad_estudiante
           AND s.FK_TLV_TIPO = academico_test.fn_tlv_solicitud_tipo_pk(p_tipo)
           AND s.ACTIVE = TRUE
         ORDER BY s.FECHA_SOLICITUD DESC, s.PK_TSOLICITUD_APROBACION DESC
         LIMIT 1), FALSE);
$$;


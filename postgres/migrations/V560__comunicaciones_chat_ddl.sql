-- V560 -- Schema comunicaciones: chat (canales, miembros, mensajes) (capa 0, DDL)
-- Que hace: crea canales y mensajes directos, membresia con marcador de lectura,
--   mensajes con respuestas, menciones y reacciones.
-- Por que aqui: lo escribe y lee comms-service (Java), no el motor de queries:
--   necesita publicar eventos de tiempo real tras cada commit. Sin funciones.
-- Depende de: public.users (id_user), V283 (fn_cdc_asegurar_auditoria).

CREATE SCHEMA IF NOT EXISTS comunicaciones;

CREATE TABLE IF NOT EXISTS comunicaciones.tcanal (
    pk_tcanal      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo           VARCHAR(10)  NOT NULL CHECK (tipo IN ('CANAL','DIRECTO')),
    categoria      VARCHAR(10)  NOT NULL DEFAULT 'GENERAL'
                     CHECK (categoria IN ('GENERAL','VOTACION','ENCUESTA','EXAMEN','ANUNCIO')),
    nombre         VARCHAR(100) NOT NULL,
    establecimiento VARCHAR(200),
    -- Un solo DM por pareja: "<id menor>:<id mayor>".
    clave_directo  VARCHAR(41),
    creado_por     BIGINT       NOT NULL REFERENCES public.users(id_user),
    created_at     TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    modified_at    TIMESTAMPTZ,
    eliminado_en   TIMESTAMPTZ,
    CHECK ((tipo = 'DIRECTO') = (clave_directo IS NOT NULL))
);
CREATE UNIQUE INDEX IF NOT EXISTS ux_tcanal_clave_directo
    ON comunicaciones.tcanal (clave_directo) WHERE clave_directo IS NOT NULL;
CREATE UNIQUE INDEX IF NOT EXISTS ux_tcanal_nombre_establecimiento
    ON comunicaciones.tcanal (COALESCE(establecimiento, ''), lower(nombre))
    WHERE tipo = 'CANAL' AND eliminado_en IS NULL;

CREATE TABLE IF NOT EXISTS comunicaciones.tcanal_miembro (
    fk_tcanal            BIGINT      NOT NULL REFERENCES comunicaciones.tcanal(pk_tcanal),
    fk_usuario           BIGINT      NOT NULL REFERENCES public.users(id_user),
    rol_canal            VARCHAR(10) NOT NULL DEFAULT 'MIEMBRO' CHECK (rol_canal IN ('ADMIN','MIEMBRO')),
    bloqueado            BOOLEAN     NOT NULL DEFAULT FALSE,
    silenciado_hasta     TIMESTAMPTZ,
    archivado            BOOLEAN     NOT NULL DEFAULT FALSE,
    ultimo_leido_msg     BIGINT      NOT NULL DEFAULT 0,
    marcado_no_leido     BOOLEAN     NOT NULL DEFAULT FALSE,
    menciones_pendientes INTEGER     NOT NULL DEFAULT 0,
    unido_en             TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    salio_en             TIMESTAMPTZ,
    PRIMARY KEY (fk_tcanal, fk_usuario)
);
CREATE INDEX IF NOT EXISTS ix_tcanal_miembro_usuario
    ON comunicaciones.tcanal_miembro (fk_usuario) WHERE salio_en IS NULL;

CREATE TABLE IF NOT EXISTS comunicaciones.tmensaje (
    pk_tmensaje          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fk_tcanal            BIGINT       NOT NULL REFERENCES comunicaciones.tcanal(pk_tcanal),
    fk_autor             BIGINT       NOT NULL REFERENCES public.users(id_user),
    fk_respuesta         BIGINT       REFERENCES comunicaciones.tmensaje(pk_tmensaje),
    tipo                 VARCHAR(10)  NOT NULL DEFAULT 'NORMAL' CHECK (tipo IN ('NORMAL','SISTEMA')),
    texto                TEXT         NOT NULL DEFAULT '',
    adjunto_nombre       VARCHAR(255),
    adjunto_formato      VARCHAR(10)  CHECK (adjunto_formato IN ('WORD','PDF','IMAGEN','VIDEO','OTRO')),
    adjunto_eliminado_en TIMESTAMPTZ,
    fijado               BOOLEAN      NOT NULL DEFAULT FALSE,
    -- Idempotencia del envio: el reintento del cliente devuelve el mismo mensaje.
    client_msg_id        UUID,
    created_at           TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    editado_en           TIMESTAMPTZ,
    eliminado_en         TIMESTAMPTZ,
    eliminado_por        BIGINT       REFERENCES public.users(id_user),
    CHECK (char_length(texto) <= 4000)
);
CREATE INDEX IF NOT EXISTS ix_tmensaje_canal_pk
    ON comunicaciones.tmensaje (fk_tcanal, pk_tmensaje DESC) WHERE eliminado_en IS NULL;
CREATE UNIQUE INDEX IF NOT EXISTS ux_tmensaje_autor_client_msg
    ON comunicaciones.tmensaje (fk_autor, client_msg_id) WHERE client_msg_id IS NOT NULL;

CREATE TABLE IF NOT EXISTS comunicaciones.tmensaje_mencion (
    pk_tmensaje_mencion BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fk_tmensaje         BIGINT      NOT NULL REFERENCES comunicaciones.tmensaje(pk_tmensaje),
    tipo                VARCHAR(10) NOT NULL CHECK (tipo IN ('USUARIO','CANAL','TODOS')),
    fk_usuario          BIGINT      REFERENCES public.users(id_user),
    CHECK ((tipo = 'USUARIO') = (fk_usuario IS NOT NULL))
);
CREATE INDEX IF NOT EXISTS ix_tmensaje_mencion_mensaje
    ON comunicaciones.tmensaje_mencion (fk_tmensaje);

CREATE TABLE IF NOT EXISTS comunicaciones.tmensaje_reaccion (
    fk_tmensaje BIGINT      NOT NULL REFERENCES comunicaciones.tmensaje(pk_tmensaje),
    fk_usuario  BIGINT      NOT NULL REFERENCES public.users(id_user),
    emoji       VARCHAR(32) NOT NULL,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    PRIMARY KEY (fk_tmensaje, fk_usuario, emoji)
);


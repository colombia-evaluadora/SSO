-- ---------------------------------------------------------------------------
-- 8. Roles: se COPIAN de los equivalentes de periodo, no del listado.
--    Guardar y eliminar el comentario del año tiene que alcanzar a la misma
--    gente que guarda y elimina el del periodo, ni mas ni menos.
-- ---------------------------------------------------------------------------
INSERT INTO public.role_query (query_id, role_id)
SELECT nuevo.id_query, rq.role_id
  FROM public.query nuevo
  JOIN public.query modelo ON modelo.microservice_id = nuevo.microservice_id
                          AND modelo.http_method     = 'POST'
                          AND modelo.path_template   = CASE nuevo.uuid
                              WHEN 'eval-col-informes-observacion-final-guardar-001'
                                  THEN '/informes/observacion/guardar'
                              WHEN 'eval-col-informes-observacion-final-eliminar-001'
                                  THEN '/informes/observacion/eliminar'
                          END
  JOIN public.role_query rq ON rq.query_id = modelo.id_query
 WHERE nuevo.uuid IN ('eval-col-informes-observacion-final-guardar-001',
                      'eval-col-informes-observacion-final-eliminar-001')
ON CONFLICT DO NOTHING;

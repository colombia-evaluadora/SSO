-- ===========================================================================
-- V435 - La observacion del año se genera, se edita y se guarda.
--
--   TESTUDIANTE_ANIO_OBSERVACION           tabla nueva
--   fn_estudiante_final_observacion        pasa a ser el GENERAR (borrador)
--   fn_estudiante_anio_observacion_guardar nueva
--   fn_estudiante_anio_observacion_eliminar nueva
--   fn_informe_grupo_listar                la fila Final lee lo GUARDADO
--   fn_informe_grupo_reporte               no imprime un Final vacio
--
--   POST /informes/observacion/final           (ya existia: generar)
--   POST /informes/observacion/final/guardar   nuevo
--   POST /informes/observacion/final/eliminar  nuevo
--
--
-- QUE CAMBIA RESPECTO DEL V434
--   Alli la observacion del Final era un DERIVADO: los resumenes ya
--   consolidados encadenados, calculados al mirarlos, sin guardar y sin
--   editar. Eso era correcto mientras el texto fuera una concatenacion.
--
--   Pero la concatenacion es provisional: el dia que exista el modelo, el
--   texto del año lo va a redactar la IA, y entonces alguien tiene que
--   poder leerlo, corregirlo y dejarlo aprobado -- exactamente el ciclo que
--   ya tienen los periodos. Un derivado no admite ese ciclo: no hay donde
--   poner "esto lo reviso un humano".
--
--   Asi que el concatenado pasa a ser el BORRADOR que devuelve generar, y
--   la fila Final arranca vacia como los periodos hasta que alguien guarde.
--   Cuando llegue la IA de verdad cambia lo que devuelve generar y nada mas:
--   el contrato del guardar, el estado y la pantalla quedan igual.
--
--
-- POR QUE UNA TABLA NUEVA Y NO LA MISMA CON EL PERIODO EN NULL
--   Se evaluaron las dos. La de reusar TESTUDIANTE_PERIODO_OBSERVACION
--   funciona: se le quita el NOT NULL a FK_TPERIODO_EVALUACION, NULL pasa a
--   significar "Final", y el indice unico se reemplaza por uno
--   NULLS NOT DISTINCT -- que existe desde PG15 y aca hay 16.4 -- porque si
--   no, cada guardado crearia una fila Final nueva en silencio. Es bastante
--   menos codigo.
--
--   Se eligio la tabla aparte por una razon concreta, no por prolijidad:
--   OBSERVACIONES_ORIGEN pasaria a contar DOS COSAS DISTINTAS segun la fila.
--   En un periodo cuenta las observaciones por actividad, porque lo que deja
--   viejo a ese texto es que el docente escriba una mas. En el año cuenta los
--   PERIODOS CONSOLIDADOS, porque lo que deja viejo al texto del año es que
--   se cierre un periodo nuevo. Misma columna, dos significados y dos
--   formulas: es justo la clase de cosa que despues nadie entiende. Aca la
--   columna se llama PERIODOS_ORIGEN y cuenta periodos.
--
--   De yapa: nada de lo que hoy lee la tabla de periodos se entera de esto,
--   la llave unica queda total y simple, y no queda un centinela NULL que
--   todo el que lea esa tabla de ahora en mas tenga que conocer.
--
--
-- LA LLAVE ES LA MATRICULA, SIN EL AÑO
--   Podria ser (matricula, periodo academico) por simetria con la otra
--   tabla, pero seria redundante: una matricula pertenece a un grupo, que
--   pertenece a un grado, que pertenece a UN periodo academico. El año ya
--   esta determinado. Agregarlo permitiria escribir la combinacion
--   incoherente, que es lo contrario de lo que uno quiere de una llave.
--
-- Idempotente: CREATE TABLE IF NOT EXISTS, CREATE OR REPLACE, ON CONFLICT
-- DO NOTHING en endpoints y roles.
-- ===========================================================================


-- ---------------------------------------------------------------------------
-- 1. La tabla.
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS academico_test.TESTUDIANTE_ANIO_OBSERVACION (
    PK_TESTUDIANTE_ANIO_OBSERVACION BIGINT GENERATED BY DEFAULT AS IDENTITY
        CONSTRAINT PK_TESTUDIANTE_ANIO_OBSERVACION PRIMARY KEY,
    FK_TMATRICULA                   BIGINT    NOT NULL,
    FK_TLV_ESTADO_OBSERVACION       BIGINT    NOT NULL,
    OBSERVACION                     TEXT      NOT NULL,
    OBSERVACION_IA                  TEXT      NOT NULL,
    -- Cuantos resumenes de periodo consolidados habia cuando se guardo. Es
    -- el equivalente de OBSERVACIONES_ORIGEN pero contando PERIODOS, que es
    -- lo que deja viejo a este texto. Ver la cabecera.
    PERIODOS_ORIGEN                 NUMERIC,
    CREATED_BY                      VARCHAR(100) NOT NULL,
    CREATED_AT                      TIMESTAMP    NOT NULL,
    MODIFIED_BY                     VARCHAR(100),
    MODIFIED_AT                     TIMESTAMP,
    ACTIVE                          BOOLEAN   NOT NULL DEFAULT TRUE,
    CONSTRAINT FK_TESTUDIANTE_ANIO_OBSERVACION_1
        FOREIGN KEY (FK_TMATRICULA)
        REFERENCES academico_test.TMATRICULA (PK_TMATRICULA),
    CONSTRAINT FK_TESTUDIANTE_ANIO_OBSERVACION_2
        FOREIGN KEY (FK_TLV_ESTADO_OBSERVACION)
        REFERENCES academico_test.TLISTA_VALOR (PK_LISTA_VALOR)
);

-- Total y no parcial sobre ACTIVE, igual que en la tabla de periodos:
-- guardar REEMPLAZA y nunca conviven dos versiones del mismo texto.
CREATE UNIQUE INDEX IF NOT EXISTS U_TESTUDIANTE_ANIO_OBSERVACION_1
    ON academico_test.TESTUDIANTE_ANIO_OBSERVACION (FK_TMATRICULA);

CREATE INDEX IF NOT EXISTS IDX_TESTUDIANTE_ANIO_OBSERVACION_1
    ON academico_test.TESTUDIANTE_ANIO_OBSERVACION (FK_TLV_ESTADO_OBSERVACION);

COMMENT ON TABLE academico_test.TESTUDIANTE_ANIO_OBSERVACION
    IS 'El comentario del AÑO de un estudiante: el equivalente de TESTUDIANTE_PERIODO_OBSERVACION para la fila Final. Mismo ciclo -- se genera, se revisa, se guarda -- y los mismos dos estados, APROBADA y MODIFICADA, sin PENDIENTE, porque generar no persiste y por lo tanto toda fila de aca es un texto que un humano ya acepto. LA LLAVE ES SOLO LA MATRICULA, sin el periodo academico: una matricula pertenece a un grupo, que pertenece a un grado, que pertenece a UN periodo academico, asi que el año ya esta determinado y agregarlo solo permitiria escribir la combinacion incoherente. ES UNA TABLA APARTE Y NO LA MISMA con el periodo en NULL por una razon concreta: OBSERVACIONES_ORIGEN contaria dos cosas distintas segun la fila -- en un periodo, las observaciones por actividad, porque eso es lo que deja viejo a ese texto; en el año, los PERIODOS CONSOLIDADOS, porque eso es lo que deja viejo a este --, con dos formulas y un solo nombre. Aca la columna se llama PERIODOS_ORIGEN y cuenta periodos. OBSERVACION_IA es el borrador original tal como se genero, se escribe al guardar y no se toca mas; OBSERVACION es lo que se muestra. Comparandolos se sabe si el docente lo reescribio, sin historial. V435.';

COMMENT ON COLUMN academico_test.TESTUDIANTE_ANIO_OBSERVACION.PERIODOS_ORIGEN
    IS 'Cuantos resumenes de periodo consolidados tenia el estudiante cuando se guardo este texto. Si hoy hay mas, el texto del año quedo viejo y la pantalla lo marca. NULL significa "no se", no "habia cero": quien lo lea debe tratarlo como desconocido y no marcar nada -- ese fue exactamente el defecto que el V433 tuvo que arreglar en la tabla de periodos.';


-- ---------------------------------------------------------------------------
-- 2. Generar: el concatenado pasa a ser un BORRADOR.
--
--    Cambian los nombres de las columnas de salida para que digan lo que
--    son, en simetria con fn_estudiante_periodo_observacion_generar:
--    observacion_ia (un borrador, no un texto aprobado) y periodos_origen
--    (lo que hay que reenviar al guardar).
-- ---------------------------------------------------------------------------
DROP FUNCTION IF EXISTS academico_test.fn_estudiante_final_observacion(BIGINT, BIGINT);

CREATE OR REPLACE FUNCTION academico_test.fn_estudiante_final_observacion(
    p_pk_usuario_solicitante BIGINT,
    p_fk_tmatricula          BIGINT
)
RETURNS TABLE(
    observacion_ia   TEXT,
    periodos_origen  NUMERIC
)
LANGUAGE plpgsql
STABLE
AS $function$
DECLARE
    v_fk_peraca  BIGINT;
    v_fk_sede    BIGINT;
    v_fk_jornada BIGINT;
    v_fk_ee      BIGINT;
BEGIN
    SELECT gd.FK_TPERIODO_ACADEMICO, s.PK_TSEDE, gr.FK_TLV_JORNADA, s.FK_TESTABLECIMIENTO
      INTO v_fk_peraca, v_fk_sede, v_fk_jornada, v_fk_ee
      FROM academico_test.TMATRICULA m
      JOIN academico_test.TGRUPO gr ON gr.PK_TGRUPO = m.FK_TGRUPO
      JOIN academico_test.TGRADO gd ON gd.PK_TGRADO = gr.FK_TGRADO
      JOIN academico_test.TPERIODO_ACADEMICO pa
        ON pa.PK_TPERIODO_ACADEMICO = gd.FK_TPERIODO_ACADEMICO
      JOIN academico_test.TSEDE s ON s.PK_TSEDE = pa.FK_TSEDE
     WHERE m.PK_TMATRICULA = p_fk_tmatricula
       AND m.ACTIVE = TRUE;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'No se encontro la matricula solicitada'
            USING ERRCODE = 'P0002';
    END IF;

    -- VER y no EDITAR: generar no escribe nada, igual que su gemela de
    -- periodo. Quien guarde necesitara EDITAR.
    PERFORM academico_test.fn_assert_permiso_seccion(
        p_pk_usuario_solicitante, 'INFORMES', 'VER',
        v_fk_ee, v_fk_sede, v_fk_jornada
    );

    RETURN QUERY
    -- -----------------------------------------------------------------
    -- *** AQUI IRA LA IA ***
    --
    -- Por ahora: encadenar los RESUMENES DE PERIODO ya consolidados, en
    -- orden y prefijados con el nombre del periodo. No las observaciones
    -- por actividad -- esas son la materia prima del resumen de PERIODO,
    -- y volver a masticarlas aca daria un texto de tres paginas.
    -- -----------------------------------------------------------------
    SELECT STRING_AGG(FORMAT('%s: %s', pe.NOMBRE, TRIM(ob.OBSERVACION)),
                      ' ' ORDER BY pe.FECHA_INICIO, pe.PK_TPERIODO_EVALUACION),
           COUNT(*)::NUMERIC
      FROM academico_test.TESTUDIANTE_PERIODO_OBSERVACION ob
      JOIN academico_test.TPERIODO_EVALUACION pe
        ON pe.PK_TPERIODO_EVALUACION = ob.FK_TPERIODO_EVALUACION
       AND pe.ACTIVE = TRUE
       AND pe.FK_TPERIODO_ACADEMICO = v_fk_peraca
     WHERE ob.FK_TMATRICULA = p_fk_tmatricula
       AND ob.ACTIVE = TRUE
       AND NULLIF(TRIM(COALESCE(ob.OBSERVACION, '')), '') IS NOT NULL;
END;
$function$;

COMMENT ON FUNCTION academico_test.fn_estudiante_final_observacion(BIGINT, BIGINT)
    IS 'GENERA el borrador del comentario del AÑO -- la fila Final --, sin escribir nada. Hoy encadena los resumenes de periodo YA CONSOLIDADOS, en orden y prefijados con el nombre del periodo; cuando exista el modelo, cambia lo que devuelve esta funcion y nada mas, porque el contrato ya es el definitivo. NO concatena las observaciones por ACTIVIDAD: esas son la materia prima del resumen de PERIODO, y volver a masticarlas aca daria un texto de tres paginas. Devuelve siempre una fila; con NULL y cero si el estudiante no tiene ningun resumen de periodo guardado. Lo que devuelve se reenvia tal cual a fn_estudiante_anio_observacion_guardar, que compara para deducir si el docente lo aprobo o lo modifico. Gate INFORMES/VER, porque no persiste. V434, V435.';


-- ---------------------------------------------------------------------------
-- 3. Guardar.
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION academico_test.fn_estudiante_anio_observacion_guardar(
    p_pk_usuario_solicitante BIGINT,
    p_fk_tmatricula          BIGINT,
    p_observacion            TEXT,
    p_observacion_ia         TEXT    DEFAULT NULL,
    p_periodos_origen        NUMERIC DEFAULT NULL
)
RETURNS BIGINT
LANGUAGE plpgsql
AS $function$
DECLARE
    v_fk_peraca  BIGINT;
    v_fk_sede    BIGINT;
    v_fk_jornada BIGINT;
    v_fk_ee      BIGINT;
    v_texto      TEXT;
    v_ia         TEXT;
    v_ia_previa  TEXT;
    v_origen     NUMERIC;
    v_estado     VARCHAR;
    v_pk_estado  BIGINT;
    v_pk         BIGINT;
BEGIN
    v_texto := NULLIF(TRIM(COALESCE(p_observacion, '')), '');
    IF v_texto IS NULL THEN
        RAISE EXCEPTION 'La observacion no puede quedar vacia'
            USING ERRCODE = '22023',
                  HINT    = 'Para quitar el comentario del año use fn_estudiante_anio_observacion_eliminar';
    END IF;

    SELECT gd.FK_TPERIODO_ACADEMICO, s.PK_TSEDE, gr.FK_TLV_JORNADA, s.FK_TESTABLECIMIENTO
      INTO v_fk_peraca, v_fk_sede, v_fk_jornada, v_fk_ee
      FROM academico_test.TMATRICULA m
      JOIN academico_test.TGRUPO gr ON gr.PK_TGRUPO = m.FK_TGRUPO
      JOIN academico_test.TGRADO gd ON gd.PK_TGRADO = gr.FK_TGRADO
      JOIN academico_test.TPERIODO_ACADEMICO pa
        ON pa.PK_TPERIODO_ACADEMICO = gd.FK_TPERIODO_ACADEMICO
      JOIN academico_test.TSEDE s ON s.PK_TSEDE = pa.FK_TSEDE
     WHERE m.PK_TMATRICULA = p_fk_tmatricula
       AND m.ACTIVE = TRUE;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'No se encontro la matricula solicitada'
            USING ERRCODE = 'P0002';
    END IF;

    PERFORM academico_test.fn_assert_permiso_seccion(
        p_pk_usuario_solicitante, 'INFORMES', 'EDITAR',
        v_fk_ee, v_fk_sede, v_fk_jornada
    );

    SELECT ao.OBSERVACION_IA
      INTO v_ia_previa
      FROM academico_test.TESTUDIANTE_ANIO_OBSERVACION ao
     WHERE ao.FK_TMATRICULA = p_fk_tmatricula
       AND ao.ACTIVE = TRUE;

    -- Misma prioridad que en la tabla de periodos desde el V433: lo que
    -- reenvia el caller, luego el borrador ya guardado, y recien al final el
    -- texto mismo. Sin el escalon del medio, editar un texto ya guardado lo
    -- dejaria como APROBADA sin cambios.
    v_ia := COALESCE(
                NULLIF(TRIM(COALESCE(p_observacion_ia, '')), ''),
                NULLIF(TRIM(COALESCE(v_ia_previa,      '')), ''),
                v_texto);

    v_origen := p_periodos_origen;

    IF v_origen IS NULL THEN
        -- Si no me dicen cuantos habia, los cuento. NULL aca significa "no
        -- se", y quien lo lea no puede distinguirlo de cero: ese fue el
        -- defecto que el V433 tuvo que arreglar en la otra tabla.
        SELECT COUNT(*)
          INTO v_origen
          FROM academico_test.TESTUDIANTE_PERIODO_OBSERVACION ob
          JOIN academico_test.TPERIODO_EVALUACION pe
            ON pe.PK_TPERIODO_EVALUACION = ob.FK_TPERIODO_EVALUACION
           AND pe.ACTIVE = TRUE
           AND pe.FK_TPERIODO_ACADEMICO = v_fk_peraca
         WHERE ob.FK_TMATRICULA = p_fk_tmatricula
           AND ob.ACTIVE = TRUE
           AND NULLIF(TRIM(COALESCE(ob.OBSERVACION, '')), '') IS NOT NULL;
    END IF;

    v_estado := CASE WHEN v_texto = TRIM(v_ia) THEN 'APROBADA' ELSE 'MODIFICADA' END;

    SELECT lv.PK_LISTA_VALOR INTO v_pk_estado
      FROM academico_test.TLISTA_VALOR lv
     WHERE lv.CATEGORIA = 'ESTADO_OBSERVACION_IA'
       AND lv.VALOR     = v_estado
       AND lv.ACTIVE    = TRUE;

    IF v_pk_estado IS NULL THEN
        RAISE EXCEPTION 'Falta el estado % en el catalogo ESTADO_OBSERVACION_IA', v_estado
            USING ERRCODE = 'P0002';
    END IF;

    INSERT INTO academico_test.TESTUDIANTE_ANIO_OBSERVACION (
        FK_TMATRICULA, FK_TLV_ESTADO_OBSERVACION,
        OBSERVACION, OBSERVACION_IA, PERIODOS_ORIGEN,
        CREATED_BY, CREATED_AT, ACTIVE
    ) VALUES (
        p_fk_tmatricula, v_pk_estado,
        v_texto, v_ia, v_origen,
        p_pk_usuario_solicitante::VARCHAR, CURRENT_TIMESTAMP, TRUE
    )
    ON CONFLICT (FK_TMATRICULA)
    DO UPDATE SET FK_TLV_ESTADO_OBSERVACION = EXCLUDED.FK_TLV_ESTADO_OBSERVACION,
                  OBSERVACION               = EXCLUDED.OBSERVACION,
                  OBSERVACION_IA            = EXCLUDED.OBSERVACION_IA,
                  PERIODOS_ORIGEN           = EXCLUDED.PERIODOS_ORIGEN,
                  ACTIVE                    = TRUE,
                  MODIFIED_BY               = p_pk_usuario_solicitante::VARCHAR,
                  MODIFIED_AT               = CURRENT_TIMESTAMP
    RETURNING PK_TESTUDIANTE_ANIO_OBSERVACION INTO v_pk;

    RETURN v_pk;
END;
$function$;

COMMENT ON FUNCTION academico_test.fn_estudiante_anio_observacion_guardar(BIGINT, BIGINT, TEXT, TEXT, NUMERIC)
    IS 'Guarda el comentario del AÑO de un estudiante -- la fila Final --, el equivalente de fn_estudiante_periodo_observacion_guardar para TESTUDIANTE_ANIO_OBSERVACION. Reemplaza: el indice unico es total sobre la matricula y no se versiona. El ESTADO se deduce comparando el texto contra OBSERVACION_IA (iguales APROBADA, distintos MODIFICADA) y nunca se pide por parametro, para que no pueda contradecirlo. Arrastra los dos arreglos del V433 desde el dia uno: si no llega OBSERVACION_IA pero ya hay fila, se conserva el borrador guardado en vez de asumir que el texto nuevo es el de la IA -- si no, editar quedaria como APROBADA sin cambios --, y si no llega PERIODOS_ORIGEN se cuentan los resumenes de periodo consolidados en el momento de guardar, en vez de dejar la columna en NULL, que el lector no puede distinguir de cero. Gate INFORMES/EDITAR. Errores: 22023 con el texto vacio -- para quitarlo esta _eliminar --, 404 si la matricula no existe. V435.';


-- ---------------------------------------------------------------------------
-- 4. Eliminar.
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION academico_test.fn_estudiante_anio_observacion_eliminar(
    p_pk_usuario_solicitante BIGINT,
    p_fk_tmatricula          BIGINT
)
RETURNS BIGINT
LANGUAGE plpgsql
AS $function$
DECLARE
    v_fk_sede    BIGINT;
    v_fk_jornada BIGINT;
    v_fk_ee      BIGINT;
    v_pk         BIGINT;
BEGIN
    SELECT s.PK_TSEDE, gr.FK_TLV_JORNADA, s.FK_TESTABLECIMIENTO
      INTO v_fk_sede, v_fk_jornada, v_fk_ee
      FROM academico_test.TMATRICULA m
      JOIN academico_test.TGRUPO gr ON gr.PK_TGRUPO = m.FK_TGRUPO
      JOIN academico_test.TGRADO gd ON gd.PK_TGRADO = gr.FK_TGRADO
      JOIN academico_test.TPERIODO_ACADEMICO pa
        ON pa.PK_TPERIODO_ACADEMICO = gd.FK_TPERIODO_ACADEMICO
      JOIN academico_test.TSEDE s ON s.PK_TSEDE = pa.FK_TSEDE
     WHERE m.PK_TMATRICULA = p_fk_tmatricula
       AND m.ACTIVE = TRUE;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'No se encontro la matricula solicitada'
            USING ERRCODE = 'P0002';
    END IF;

    -- ELIMINAR y no EDITAR, igual que en la tabla de periodos (V413):
    -- rehacer un texto es corregir, borrarlo es deshacer.
    PERFORM academico_test.fn_assert_permiso_seccion(
        p_pk_usuario_solicitante, 'INFORMES', 'ELIMINAR',
        v_fk_ee, v_fk_sede, v_fk_jornada
    );

    -- Borrado FISICO y no baja logica, por el mismo motivo que en la otra
    -- tabla: el indice unico es total, asi que una fila inactiva seguiria
    -- ocupando el lugar e impediria guardar una nueva. Y no hay nada que
    -- conservar: el texto se vuelve a generar desde los resumenes de
    -- periodo, que son el dato original.
    DELETE FROM academico_test.TESTUDIANTE_ANIO_OBSERVACION ao
     WHERE ao.FK_TMATRICULA = p_fk_tmatricula
    RETURNING ao.PK_TESTUDIANTE_ANIO_OBSERVACION INTO v_pk;

    IF v_pk IS NULL THEN
        RAISE EXCEPTION 'El estudiante no tiene comentario del año guardado'
            USING ERRCODE = 'P0002';
    END IF;

    RETURN v_pk;
END;
$function$;

COMMENT ON FUNCTION academico_test.fn_estudiante_anio_observacion_eliminar(BIGINT, BIGINT)
    IS 'Quita el comentario del AÑO de un estudiante. Devuelve el PK eliminado. BORRADO FISICO y no baja logica, igual que su gemela de periodo (V413): el indice unico de TESTUDIANTE_ANIO_OBSERVACION es total sobre la matricula, de modo que una fila inactiva seguiria ocupando el lugar e impediria guardar una nueva; y no hay nada que conservar, porque el texto se regenera desde los resumenes de periodo, que son el dato original. Despues de eliminar, la fila Final de /informes/grupo vuelve a traer observacion en NULL. Gate INFORMES/ELIMINAR -- mas exigente que el EDITAR de guardar, porque rehacer es corregir y borrar es deshacer. 404 si no habia nada guardado. V435.';


-- ---------------------------------------------------------------------------
-- 5. El listado: la fila Final lee lo GUARDADO, no el concatenado.
--
--    DROP porque la firma no cambia pero si el cuerpo... en realidad alcanza
--    CREATE OR REPLACE: ni los parametros ni las columnas de salida cambian.

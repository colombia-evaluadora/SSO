-- V559 — Verificación del boletín por QR, capa 0 de 4: la tabla de emisiones.
--
-- Qué hace: TBOLETIN_EMISION guarda cada boletín impreso (matrícula, periodo,
-- nivel y HUELLA sha-256 de sus datos) con un CODIGO aleatorio que va en el QR.
-- Una sola emisión VIGENTE por (matrícula, periodo); las anteriores quedan
-- REEMPLAZADA apuntando a la nueva, o REVOCADA por el rector.
-- Por qué aquí: tabla nueva del dominio informes/boletín.
-- Depende de: V22 (TMATRICULA, TPERIODO_EVALUACION), V283 (auditoría CDC).

CREATE TABLE IF NOT EXISTS academico_test.TBOLETIN_EMISION (
    PK_TBOLETIN_EMISION    BIGINT GENERATED BY DEFAULT AS IDENTITY,
    CODIGO                 VARCHAR(32)  NOT NULL,
    FK_TMATRICULA          BIGINT       NOT NULL,
    FK_TPERIODO_EVALUACION BIGINT       NOT NULL,
    NIVEL                  VARCHAR(20)  NOT NULL,
    HUELLA                 CHAR(64)     NOT NULL,
    ESTADO                 VARCHAR(12)  NOT NULL DEFAULT 'VIGENTE',
    REEMPLAZADA_POR        BIGINT,
    REVOCADA_POR           VARCHAR(120),
    REVOCADA_AT            TIMESTAMP,
    MOTIVO                 VARCHAR(500),
    CREATED_BY             VARCHAR(120) NOT NULL,
    CREATED_AT             TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    MODIFIED_BY            VARCHAR(120),
    MODIFIED_AT            TIMESTAMP,
    CONSTRAINT PK_TBOLETIN_EMISION PRIMARY KEY (PK_TBOLETIN_EMISION),
    CONSTRAINT U_TBOLETIN_EMISION_CODIGO UNIQUE (CODIGO),
    CONSTRAINT FK_TBOLETIN_EMISION_1 FOREIGN KEY (FK_TMATRICULA) REFERENCES academico_test.TMATRICULA (PK_TMATRICULA),
    CONSTRAINT FK_TBOLETIN_EMISION_2 FOREIGN KEY (FK_TPERIODO_EVALUACION) REFERENCES academico_test.TPERIODO_EVALUACION (PK_TPERIODO_EVALUACION),
    CONSTRAINT FK_TBOLETIN_EMISION_3 FOREIGN KEY (REEMPLAZADA_POR) REFERENCES academico_test.TBOLETIN_EMISION (PK_TBOLETIN_EMISION),
    CONSTRAINT CHK_TBOLETIN_EMISION_CODIGO CHECK (CODIGO ~ '^[A-Za-z0-9_-]{22,32}$'),
    CONSTRAINT CHK_TBOLETIN_EMISION_HUELLA CHECK (HUELLA ~ '^[0-9a-f]{64}$'),
    CONSTRAINT CHK_TBOLETIN_EMISION_NIVEL CHECK (NIVEL IN ('preescolar', 'primaria', 'secundaria', 'media')),
    CONSTRAINT CHK_TBOLETIN_EMISION_ESTADO CHECK (ESTADO IN ('VIGENTE', 'REEMPLAZADA', 'REVOCADA')),
    CONSTRAINT CHK_TBOLETIN_EMISION_REVOCADA CHECK (ESTADO <> 'REVOCADA' OR REVOCADA_AT IS NOT NULL)
);

CREATE INDEX IF NOT EXISTS IDX_TBOLETIN_EMISION_MATRICULA_PERIODO
    ON academico_test.TBOLETIN_EMISION (FK_TMATRICULA, FK_TPERIODO_EVALUACION);
-- Reimprimir no puede dejar dos QR "vigentes" del mismo boletín.
CREATE UNIQUE INDEX IF NOT EXISTS UX_TBOLETIN_EMISION_VIGENTE
    ON academico_test.TBOLETIN_EMISION (FK_TMATRICULA, FK_TPERIODO_EVALUACION)
    WHERE ESTADO = 'VIGENTE';
CREATE INDEX IF NOT EXISTS IDX_TBOLETIN_EMISION_PERIODO
    ON academico_test.TBOLETIN_EMISION (FK_TPERIODO_EVALUACION);
CREATE INDEX IF NOT EXISTS IDX_TBOLETIN_EMISION_REEMPLAZADA_POR
    ON academico_test.TBOLETIN_EMISION (REEMPLAZADA_POR) WHERE REEMPLAZADA_POR IS NOT NULL;

COMMENT ON TABLE academico_test.TBOLETIN_EMISION
    IS 'Boletin impreso con QR de verificacion publica. CODIGO es aleatorio (>=128 bits, base64url) y es lo unico que viaja en el QR. HUELLA es el sha-256 que reporting-service calcula sobre los datos normalizados del boletin de ese estudiante: si al verificar la huella de los datos actuales difiere, el boletin fue ACTUALIZADO. Una sola VIGENTE por (matricula, periodo).';

SELECT academico_test.fn_cdc_asegurar_auditoria('academico_test', 'tboletin_emision');

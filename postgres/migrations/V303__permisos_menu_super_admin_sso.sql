-- ===========================================================================
-- V303 - fn_usuario_permisos_menu: capabilities por menu para el front
-- (GET /usuarios/permisos-menu) y base del gate fn_usuario_puede_en_menu.
-- El super admin del SSO recibe todos los menus con los 4 permisos. El
-- CODIGO sale canonico (MATRÍCULA => MATRICULA): el front compara exacto.
-- Crea TROL_MENU.SOLO_LECTURA y TROL_MENU_PERMISO (VER/CREAR/EDITAR/ELIMINAR),
-- la fuente de los permisos del rol; un trigger la deriva de SOLO_LECTURA.
-- TMENU.ADMITE_GUARDAR/ADMITE_ELIMINAR: las acciones que la vista tiene; un
-- permiso de rol sobre una accion que la vista no tiene no cuenta.
-- Registra GET /usuarios/:PK_TUSUARIO/permisos-menu. Depende de: V29, V302.
-- ===========================================================================

SET search_path TO academico_test, public;

ALTER TABLE academico_test.TMENU
    ADD COLUMN IF NOT EXISTS ADMITE_GUARDAR  BOOLEAN DEFAULT TRUE NOT NULL,
    ADD COLUMN IF NOT EXISTS ADMITE_ELIMINAR BOOLEAN DEFAULT TRUE NOT NULL;

COMMENT ON COLUMN academico_test.TMENU.ADMITE_GUARDAR IS
    'La vista tiene crear y editar. En FALSE ningun rol puede guardar en ella.';
COMMENT ON COLUMN academico_test.TMENU.ADMITE_ELIMINAR IS
    'La vista tiene eliminar. En FALSE ningun rol puede eliminar en ella.';

ALTER TABLE academico_test.TROL_MENU
    ADD COLUMN IF NOT EXISTS SOLO_LECTURA VARCHAR(5);

COMMENT ON COLUMN academico_test.TROL_MENU.SOLO_LECTURA IS
    'Concesion de solo lectura del rol: ''SI'' => solo ver; otro valor => los 4 permisos. TROL_MENU_PERMISO se deriva de esta columna.';

CREATE TABLE IF NOT EXISTS academico_test.TROL_MENU_PERMISO (
  PK_TROL_MENU_PERMISO BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  FK_TROL_MENU BIGINT NOT NULL,
  VER BOOLEAN DEFAULT TRUE NOT NULL,
  CREAR BOOLEAN DEFAULT FALSE NOT NULL,
  EDITAR BOOLEAN DEFAULT FALSE NOT NULL,
  ELIMINAR BOOLEAN DEFAULT FALSE NOT NULL,
  CREATED_BY VARCHAR(120) NOT NULL,
  CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
  MODIFIED_BY VARCHAR(120),
  MODIFIED_AT TIMESTAMP,
  CONSTRAINT PK_TROL_MENU_PERMISO PRIMARY KEY (PK_TROL_MENU_PERMISO),
  CONSTRAINT U_TROL_MENU_PERMISO_1 UNIQUE (FK_TROL_MENU),
  CONSTRAINT FK_TROL_MENU_PERMISO_1 FOREIGN KEY (FK_TROL_MENU)
    REFERENCES academico_test.TROL_MENU (PK_TROL_MENU) ON DELETE CASCADE,
  -- Crear, editar o eliminar sin ver no existe.
  CONSTRAINT CK_TROL_MENU_PERMISO_VER CHECK (VER OR NOT (CREAR OR EDITAR OR ELIMINAR))
);

COMMENT ON TABLE academico_test.TROL_MENU_PERMISO IS
    'Permisos base de un rol sobre un menu (VER, CREAR, EDITAR, ELIMINAR): lo maximo que puede un funcionario con ese rol';

CREATE OR REPLACE FUNCTION academico_test.fn_trol_menu_permiso_sincronizar()
RETURNS TRIGGER
LANGUAGE plpgsql
SET search_path = academico_test, public
AS $$
DECLARE
    v_edita BOOLEAN := NEW.solo_lectura IS DISTINCT FROM 'SI';
BEGIN
    INSERT INTO academico_test.trol_menu_permiso
           (fk_trol_menu, ver, crear, editar, eliminar, created_by)
    VALUES (NEW.pk_trol_menu, TRUE, v_edita, v_edita, v_edita,
            COALESCE(NEW.modified_by, NEW.created_by))
    ON CONFLICT (fk_trol_menu) DO UPDATE
       SET ver         = TRUE,
           crear       = EXCLUDED.crear,
           editar      = EXCLUDED.editar,
           eliminar    = EXCLUDED.eliminar,
           modified_by = EXCLUDED.created_by,
           modified_at = CURRENT_TIMESTAMP;
    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_trol_menu_permiso_sincronizar ON academico_test.TROL_MENU;
CREATE TRIGGER trg_trol_menu_permiso_sincronizar
    AFTER INSERT OR UPDATE OF SOLO_LECTURA ON academico_test.TROL_MENU
    FOR EACH ROW EXECUTE FUNCTION academico_test.fn_trol_menu_permiso_sincronizar();

-- Solo las concesiones sin fila: no pisa permisos ya editados.
INSERT INTO academico_test.trol_menu_permiso
       (fk_trol_menu, ver, crear, editar, eliminar, created_by)
SELECT tm.pk_trol_menu, TRUE,
       tm.solo_lectura IS DISTINCT FROM 'SI',
       tm.solo_lectura IS DISTINCT FROM 'SI',
       tm.solo_lectura IS DISTINCT FROM 'SI',
       tm.created_by
  FROM academico_test.trol_menu tm
 WHERE NOT EXISTS (
       SELECT 1 FROM academico_test.trol_menu_permiso p
        WHERE p.fk_trol_menu = tm.pk_trol_menu
 );


CREATE OR REPLACE FUNCTION academico_test.fn_usuario_permisos_menu(p_pk_tusuario BIGINT)
RETURNS TABLE(
    pk_tmenu        BIGINT,
    codigo          CHARACTER VARYING,
    nombre          CHARACTER VARYING,
    path            CHARACTER VARYING,
    puede_crear     BOOLEAN,
    puede_editar    BOOLEAN,
    puede_eliminar  BOOLEAN,
    puede_ver       BOOLEAN
)
LANGUAGE plpgsql
STABLE
AS $function$
BEGIN
    -- Super admin del SSO: todos los menus activos con lo que admita cada uno.
    IF academico_test.fn_es_super_admin_sso(p_pk_tusuario) THEN
        RETURN QUERY
        SELECT m.PK_TMENU,
               academico_test.fn_menu_codigo_canonico(m.CODIGO),
               m.NOMBRE,
               m.URL,
               m.ADMITE_GUARDAR, m.ADMITE_GUARDAR, m.ADMITE_ELIMINAR, TRUE
          FROM academico_test.TMENU m
          LEFT JOIN academico_test.TMENU p ON p.PK_TMENU = m.FK_TMENU
         WHERE m.ACTIVE = TRUE AND m.ESTADO = 'A'
           AND (m.FK_TMENU IS NULL OR (p.ACTIVE = TRUE AND p.ESTADO = 'A'))
         ORDER BY m.NOMBRE ASC, m.PK_TMENU ASC;
        RETURN;
    END IF;

    RETURN QUERY
    WITH roles_activos AS (
        SELECT DISTINCT su.FK_TROL AS pk_trol
          FROM academico_test.TSEDE_USUARIO su
         WHERE su.FK_TUSUARIO = p_pk_tusuario
           AND su.ACTIVE = TRUE
    ),
    menus_del_rol AS (
        -- Una fila por (rol, menu). Sin fila en TROL_MENU_PERMISO se cae a
        -- SOLO_LECTURA: 'SI' => solo ver; otro valor => los 4.
        SELECT rm.PK_TROL_MENU, m.PK_TMENU, m.CODIGO, m.NOMBRE, m.URL,
               m.ADMITE_GUARDAR  AND COALESCE(rp.CREAR,    rm.SOLO_LECTURA IS DISTINCT FROM 'SI') AS base_crear,
               m.ADMITE_GUARDAR  AND COALESCE(rp.EDITAR,   rm.SOLO_LECTURA IS DISTINCT FROM 'SI') AS base_editar,
               m.ADMITE_ELIMINAR AND COALESCE(rp.ELIMINAR, rm.SOLO_LECTURA IS DISTINCT FROM 'SI') AS base_eliminar,
               COALESCE(rp.VER, TRUE)                                      AS base_ver
          FROM roles_activos ra
          JOIN academico_test.TROL_MENU rm
            ON rm.FK_TROL = ra.pk_trol AND rm.ACTIVE = TRUE
          LEFT JOIN academico_test.TROL_MENU_PERMISO rp
            ON rp.FK_TROL_MENU = rm.PK_TROL_MENU
          -- Un menu inactivo, o con el padre inactivo, no da permisos.
          JOIN academico_test.TMENU m
            ON m.PK_TMENU = rm.FK_TMENU AND m.ACTIVE = TRUE AND m.ESTADO = 'A'
          LEFT JOIN academico_test.TMENU pm ON pm.PK_TMENU = m.FK_TMENU
         WHERE m.FK_TMENU IS NULL OR (pm.ACTIVE = TRUE AND pm.ESTADO = 'A')
    ),
    bloqueos AS (
        -- Recorte del usuario: solo cuenta SOLO_LECTURA = 'SI'.
        SELECT DISTINCT p.FK_TROL_MENU
          FROM academico_test.TUSUARIO_ROL_PERMISO p
         WHERE p.FK_TUSUARIO = p_pk_tusuario
           AND p.ACTIVE = TRUE
           AND p.SOLO_LECTURA = 'SI'
    ),
    permisos_por_combo AS (
        -- Base del rol menos el recorte del usuario (solo baja crear/editar/eliminar).
        SELECT mr.PK_TMENU, mr.CODIGO, mr.NOMBRE, mr.URL,
               mr.base_crear    AND (b.FK_TROL_MENU IS NULL) AS puede_crear_combo,
               mr.base_editar   AND (b.FK_TROL_MENU IS NULL) AS puede_editar_combo,
               mr.base_eliminar AND (b.FK_TROL_MENU IS NULL) AS puede_eliminar_combo,
               mr.base_ver                                   AS puede_ver_combo
          FROM menus_del_rol mr
          LEFT JOIN bloqueos b ON b.FK_TROL_MENU = mr.PK_TROL_MENU
    )
    -- Cast a VARCHAR: MIN() devuelve TEXT y RETURN QUERY exige el tipo exacto.
    SELECT pc.PK_TMENU,
           academico_test.fn_menu_codigo_canonico(MIN(pc.CODIGO)::CHARACTER VARYING),
           MIN(pc.NOMBRE)::CHARACTER VARYING,
           MIN(pc.URL)::CHARACTER VARYING,
           bool_or(pc.puede_crear_combo)    AS puede_crear,
           bool_or(pc.puede_editar_combo)   AS puede_editar,
           bool_or(pc.puede_eliminar_combo) AS puede_eliminar,
           bool_or(pc.puede_ver_combo)      AS puede_ver
      FROM permisos_por_combo pc
     GROUP BY pc.PK_TMENU
     ORDER BY MIN(pc.NOMBRE) ASC, pc.PK_TMENU ASC;
END;
$function$;

COMMENT ON FUNCTION academico_test.fn_usuario_permisos_menu(BIGINT) IS
    'Capabilities por menu para el front (GET /usuarios/permisos-menu); CODIGO en forma canonica (fn_menu_codigo_canonico). Guardar y eliminar se limitan a lo que admite el menu (TMENU.ADMITE_GUARDAR/ADMITE_ELIMINAR). El super admin del SSO (fn_es_super_admin_sso) obtiene todos los menus activos con todo lo que admitan.';

-- GET /usuarios/:PK_TUSUARIO/permisos-menu: solo CEVAL-SUPER_ADMINISTRADOR,
-- porque recibe el PK y cualquier rol veria los permisos de otros.
INSERT INTO public.query
    (uuid, query, type, public_end, captcha, microservice_id, path_template, execution_mode, http_method, param_types, detail)
SELECT
    gen_random_uuid()::text,
    'SELECT * FROM academico_test.fn_usuario_permisos_menu(
    CAST(:PARAM.PK_TUSUARIO AS BIGINT)
);',
    'postgres', false, false,
    m.id_microservice, '/usuarios/:PK_TUSUARIO/permisos-menu', 'SELECT', 'GET',
    '{"PARAM.PK_TUSUARIO": "BIGINT"}'::jsonb,
    'Permisos de menu (crear/editar/eliminar/ver) del usuario, para que el front decida que botones mostrar.'
  FROM public.microservice m
 WHERE m.serviceid = 'eval-col'
ON CONFLICT (microservice_id, path_template, http_method) WHERE path_template IS NOT NULL
DO UPDATE SET query       = EXCLUDED.query,
              param_types = EXCLUDED.param_types,
              detail      = EXCLUDED.detail;

INSERT INTO public.role_query (role_id, query_id)
SELECT
    (SELECT id_role FROM public.role WHERE name = 'CEVAL-SUPER_ADMINISTRADOR'),
    q.id_query
  FROM public.query q
  JOIN public.microservice m ON m.id_microservice = q.microservice_id
 WHERE m.serviceid = 'eval-col'
   AND q.path_template = '/usuarios/:PK_TUSUARIO/permisos-menu'
   AND q.http_method = 'GET'
ON CONFLICT DO NOTHING;

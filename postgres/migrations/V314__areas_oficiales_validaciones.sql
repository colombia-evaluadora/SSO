-- V314 - Catálogo de Áreas oficiales, capa 1 de 4: DDL, datos y validaciones.
-- El área oficial ES la fila de área de TAREA_ASIGNATURA (CODIGO_ASIGNATURA = 0),
-- el catálogo de áreas de ley que ya usan el Plan de Estudio (TAREA) y el
-- Referente (TREFERENTE_CURRICULAR_AREA): las asociaciones no se mueven. Suma
-- HABILITADO (estado Activa/Inactiva; ACTIVE sigue siendo el borrado lógico),
-- ES_DIMENSION_TRANSVERSAL (Dimensiones de Preescolar) y sus niveles educativos
-- (TAREA_ASIGNATURA_NIVEL), sembrados por uso y, sin uso, por especialidad.
-- Depende de: V22 (TAREA_ASIGNATURA, TNIVEL_ENSENANZA, Plan de Estudio),
-- V212 (TREFERENTE_CURRICULAR_AREA y _NIVEL).

SET search_path TO academico_test, public;

ALTER TABLE academico_test.TAREA_ASIGNATURA
    ADD COLUMN IF NOT EXISTS HABILITADO               BOOLEAN NOT NULL DEFAULT TRUE,
    ADD COLUMN IF NOT EXISTS ES_DIMENSION_TRANSVERSAL BOOLEAN NOT NULL DEFAULT FALSE;

CREATE TABLE IF NOT EXISTS academico_test.TAREA_ASIGNATURA_NIVEL (
    PK_TAREA_ASIGNATURA_NIVEL BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    FK_TAREA_ASIGNATURA       BIGINT NOT NULL,
    FK_TNIVEL_ENSENANZA       BIGINT NOT NULL,
    CREATED_BY                VARCHAR(120) NOT NULL,
    CREATED_AT                TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    MODIFIED_BY               VARCHAR(120),
    MODIFIED_AT               TIMESTAMP,
    ACTIVE                    BOOLEAN DEFAULT TRUE NOT NULL,
    CONSTRAINT PK_TAREA_ASIGNATURA_NIVEL PRIMARY KEY (PK_TAREA_ASIGNATURA_NIVEL),
    CONSTRAINT FK_TAREA_ASIGNATURA_NIVEL_1 FOREIGN KEY (FK_TAREA_ASIGNATURA)
        REFERENCES academico_test.TAREA_ASIGNATURA (PK_TAREA_ASIGNATURA),
    CONSTRAINT FK_TAREA_ASIGNATURA_NIVEL_2 FOREIGN KEY (FK_TNIVEL_ENSENANZA)
        REFERENCES academico_test.TNIVEL_ENSENANZA (PK_NIVEL_ENSENANZA)
);

CREATE INDEX IF NOT EXISTS IDX_TAREA_ASIGNATURA_NIVEL_1
    ON academico_test.TAREA_ASIGNATURA_NIVEL (FK_TAREA_ASIGNATURA);
CREATE UNIQUE INDEX IF NOT EXISTS U_TAREA_ASIGNATURA_NIVEL_1
    ON academico_test.TAREA_ASIGNATURA_NIVEL (FK_TAREA_ASIGNATURA, FK_TNIVEL_ENSENANZA)
    WHERE ACTIVE = TRUE;

COMMENT ON TABLE academico_test.TAREA_ASIGNATURA_NIVEL
    IS 'Niveles educativos (TNIVEL_ENSENANZA) de cada área oficial: la fila de área de TAREA_ASIGNATURA (CODIGO_ASIGNATURA = 0). Al asociar un área del Plan de Estudio solo se ofrecen las áreas oficiales de su nivel.';
COMMENT ON COLUMN academico_test.TAREA_ASIGNATURA.HABILITADO
    IS 'Estado del área oficial (Activa/Inactiva): inactiva deja de ofrecerse para asociaciones nuevas, pero las ya hechas la siguen mostrando. ACTIVE es el borrado lógico.';
COMMENT ON COLUMN academico_test.TAREA_ASIGNATURA.ES_DIMENSION_TRANSVERSAL
    IS 'Marca el área oficial Dimensiones: la dimensión transversal de Preescolar.';

UPDATE academico_test.TAREA_ASIGNATURA
   SET ES_DIMENSION_TRANSVERSAL = TRUE
 WHERE CODIGO_ASIGNATURA = 0
   AND UPPER(TRIM(NOMBRE)) = 'DIMENSIONES'
   AND ES_DIMENSION_TRANSVERSAL = FALSE;

-- Niveles iniciales: los de los grados cuyo Plan de Estudio usa el área (o una
-- de sus asignaturas) y los de los Referentes que la declaran; sin uso, por
-- especialidad (DANE: 0 No aplica -> Preescolar, 5 Académico -> Primaria a
-- Media, el resto -> Media). Solo áreas que aún no tienen ningún nivel.
WITH oficial AS (
    SELECT cat.PK_TAREA_ASIGNATURA AS pk_catalogo, area.PK_TAREA_ASIGNATURA AS pk_area
      FROM academico_test.TAREA_ASIGNATURA cat
      JOIN academico_test.TAREA_ASIGNATURA area
        ON area.CODIGO_ASIGNATURA = 0
       AND area.CODIGO_AREA = cat.CODIGO_AREA
       AND area.FK_TESPECIALIDAD IS NOT DISTINCT FROM cat.FK_TESPECIALIDAD
),
sin_niveles AS (
    SELECT a.PK_TAREA_ASIGNATURA AS pk, e.CODIGO AS especialidad
      FROM academico_test.TAREA_ASIGNATURA a
      LEFT JOIN academico_test.TESPECIALIDAD e ON e.PK_ESPECIALIDAD = a.FK_TESPECIALIDAD
     WHERE a.CODIGO_ASIGNATURA = 0 AND a.ACTIVE = TRUE
       AND NOT EXISTS (SELECT 1 FROM academico_test.TAREA_ASIGNATURA_NIVEL n
                        WHERE n.FK_TAREA_ASIGNATURA = a.PK_TAREA_ASIGNATURA AND n.ACTIVE = TRUE)
),
uso AS (
    SELECT o.pk_area, g.FK_TNIVEL_ENSENANZA AS nivel
      FROM academico_test.TAREA t
      JOIN oficial o ON o.pk_catalogo = t.FK_TAREA_ASIGNATURA
      JOIN academico_test.TASIGNATURA s ON s.FK_TAREA = t.PK_TAREA AND s.ACTIVE = TRUE
      JOIN academico_test.TASIGNATURA_PLAN sp ON sp.FK_TASIGNATURA = s.PK_TASIGNATURA AND sp.ACTIVE = TRUE
      JOIN academico_test.TPLAN p ON p.PK_TPLAN = sp.FK_TPLAN AND p.ACTIVE = TRUE
      JOIN academico_test.TGRADO g ON g.PK_TGRADO = p.FK_TGRADO
     WHERE t.ACTIVE = TRUE
    UNION
    SELECT o.pk_area, rn.FK_TNIVEL_ENSENANZA
      FROM academico_test.TREFERENTE_CURRICULAR_AREA ra
      JOIN oficial o ON o.pk_catalogo = ra.FK_TAREA_ASIGNATURA
      JOIN academico_test.TREFERENTE_CURRICULAR_NIVEL rn
        ON rn.FK_REFERENTE_CURRICULAR = ra.FK_REFERENTE_CURRICULAR AND rn.ACTIVE = TRUE
     WHERE ra.ACTIVE = TRUE
),
por_especialidad AS (
    SELECT sn.pk, ne.PK_NIVEL_ENSENANZA AS nivel
      FROM sin_niveles sn
      JOIN academico_test.TNIVEL_ENSENANZA ne ON ne.ACTIVE = TRUE
       AND ne.CODIGO = ANY (CASE sn.especialidad
                                WHEN '0' THEN ARRAY['1']
                                WHEN '5' THEN ARRAY['2', '3', '4']
                                ELSE ARRAY['4']
                            END)
     WHERE NOT EXISTS (SELECT 1 FROM uso u WHERE u.pk_area = sn.pk)
)
INSERT INTO academico_test.TAREA_ASIGNATURA_NIVEL (FK_TAREA_ASIGNATURA, FK_TNIVEL_ENSENANZA, CREATED_BY)
SELECT DISTINCT x.pk, x.nivel, 'migracion'
  FROM (SELECT u.pk_area AS pk, u.nivel FROM uso u JOIN sin_niveles sn ON sn.pk = u.pk_area
        UNION
        SELECT pe.pk, pe.nivel FROM por_especialidad pe) x
 WHERE x.nivel IS NOT NULL;

CREATE OR REPLACE FUNCTION academico_test.fn_areaoficial_validar_existente(p_pk_area BIGINT)
RETURNS VOID
LANGUAGE plpgsql
STABLE
AS $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM academico_test.TAREA_ASIGNATURA
                    WHERE PK_TAREA_ASIGNATURA = p_pk_area
                      AND CODIGO_ASIGNATURA = 0 AND ACTIVE = TRUE) THEN
        RAISE EXCEPTION 'No existe el área oficial solicitada.'
            USING ERRCODE = 'P0002';
    END IF;
END;
$$;

COMMENT ON FUNCTION academico_test.fn_areaoficial_validar_existente(BIGINT)
    IS 'P0002 si no hay un área oficial (fila de área de TAREA_ASIGNATURA, no eliminada) con ese pk.';

CREATE OR REPLACE FUNCTION academico_test.fn_areaoficial_validar_nombre(p_nombre VARCHAR)
RETURNS VOID
LANGUAGE plpgsql
IMMUTABLE
AS $$
BEGIN
    IF p_nombre IS NULL OR length(TRIM(p_nombre)) NOT BETWEEN 3 AND 100 THEN
        RAISE EXCEPTION 'El nombre del área oficial debe tener entre 3 y 100 caracteres.'
            USING ERRCODE = '22023';
    END IF;
END;
$$;

COMMENT ON FUNCTION academico_test.fn_areaoficial_validar_nombre(VARCHAR)
    IS '22023 si el nombre no tiene entre 3 y 100 caracteres.';

CREATE OR REPLACE FUNCTION academico_test.fn_areaoficial_validar_nombre_unico(
    p_nombre       VARCHAR,
    p_pk_excluir   BIGINT DEFAULT NULL
)
RETURNS VOID
LANGUAGE plpgsql
STABLE
AS $$
BEGIN
    IF EXISTS (SELECT 1 FROM academico_test.TAREA_ASIGNATURA
                WHERE CODIGO_ASIGNATURA = 0 AND ACTIVE = TRUE
                  AND lower(TRIM(NOMBRE)) = lower(TRIM(p_nombre))
                  AND PK_TAREA_ASIGNATURA IS DISTINCT FROM p_pk_excluir) THEN
        RAISE EXCEPTION 'El nombre ya existe en el catálogo de áreas oficiales.'
            USING ERRCODE = '23505';
    END IF;
END;
$$;

COMMENT ON FUNCTION academico_test.fn_areaoficial_validar_nombre_unico(VARCHAR, BIGINT)
    IS '23505 si otra área oficial no eliminada tiene el mismo nombre (sin distinguir mayúsculas). Activas e inactivas cuentan: una inactiva se reactiva, no se duplica.';

CREATE OR REPLACE FUNCTION academico_test.fn_areaoficial_validar_niveles(p_niveles BIGINT[])
RETURNS VOID
LANGUAGE plpgsql
STABLE
AS $$
DECLARE
    v_invalido BIGINT;
BEGIN
    IF p_niveles IS NULL OR cardinality(p_niveles) = 0 THEN
        RAISE EXCEPTION 'Seleccione al menos un nivel educativo.'
            USING ERRCODE = '22023';
    END IF;

    SELECT n INTO v_invalido
      FROM unnest(p_niveles) n
     WHERE NOT EXISTS (SELECT 1 FROM academico_test.TNIVEL_ENSENANZA ne
                        WHERE ne.PK_NIVEL_ENSENANZA = n AND ne.ACTIVE = TRUE)
     LIMIT 1;
    IF FOUND THEN
        RAISE EXCEPTION 'Uno de los niveles educativos seleccionados no existe o está inactivo.'
            USING ERRCODE = '22023';
    END IF;
END;
$$;

COMMENT ON FUNCTION academico_test.fn_areaoficial_validar_niveles(BIGINT[])
    IS '22023 si no llega ningún nivel educativo o alguno no existe o está inactivo en TNIVEL_ENSENANZA.';

CREATE OR REPLACE FUNCTION academico_test.fn_areaoficial_usos(p_pk_area BIGINT)
RETURNS TABLE (planes_estudio BIGINT, referentes BIGINT)
LANGUAGE sql
STABLE
AS $$
    WITH catalogo AS (
        SELECT cat.PK_TAREA_ASIGNATURA AS pk
          FROM academico_test.TAREA_ASIGNATURA area
          JOIN academico_test.TAREA_ASIGNATURA cat
            ON cat.CODIGO_AREA = area.CODIGO_AREA
           AND cat.FK_TESPECIALIDAD IS NOT DISTINCT FROM area.FK_TESPECIALIDAD
         WHERE area.PK_TAREA_ASIGNATURA = p_pk_area AND area.CODIGO_ASIGNATURA = 0
    )
    SELECT (SELECT count(*) FROM academico_test.TAREA t
             WHERE t.ACTIVE = TRUE AND t.FK_TAREA_ASIGNATURA IN (SELECT pk FROM catalogo))
         + (SELECT count(*) FROM academico_test.TASIGNATURA s
             WHERE s.ACTIVE = TRUE AND s.FK_TAREA_ASIGNATURA IN (SELECT pk FROM catalogo)),
           (SELECT count(DISTINCT ra.FK_REFERENTE_CURRICULAR) FROM academico_test.TREFERENTE_CURRICULAR_AREA ra
             WHERE ra.ACTIVE = TRUE AND ra.FK_TAREA_ASIGNATURA IN (SELECT pk FROM catalogo));
$$;

COMMENT ON FUNCTION academico_test.fn_areaoficial_usos(BIGINT)
    IS 'Cuántas áreas y asignaturas activas de Planes de Estudio (TAREA y TASIGNATURA) y cuántos Referentes curriculares usan el área oficial o alguna de sus asignaturas del catálogo.';

CREATE OR REPLACE FUNCTION academico_test.fn_areaoficial_validar_no_en_uso(p_pk_area BIGINT)
RETURNS VOID
LANGUAGE plpgsql
STABLE
AS $$
DECLARE
    v_planes     BIGINT;
    v_referentes BIGINT;
BEGIN
    SELECT planes_estudio, referentes INTO v_planes, v_referentes
      FROM academico_test.fn_areaoficial_usos(p_pk_area);
    IF v_planes > 0 OR v_referentes > 0 THEN
        RAISE EXCEPTION 'En uso en [Áreas] de Planes de Estudio y en Referentes: no se puede eliminar.'
            USING ERRCODE = '23503',
                  DETAIL = format('Planes de Estudio: %s; Referentes: %s', v_planes, v_referentes);
    END IF;
END;
$$;

COMMENT ON FUNCTION academico_test.fn_areaoficial_validar_no_en_uso(BIGINT)
    IS '23503 si algún Plan de Estudio o Referente usa el área oficial (fn_areaoficial_usos): en uso solo se inactiva.';

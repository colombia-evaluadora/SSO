DO $$
DECLARE
    v_rq BIGINT; v_re BIGINT; v_rr BIGINT; v_ra BIGINT;
BEGIN
    SELECT count(*) INTO v_rq FROM public.role_query;
    SELECT count(*) INTO v_re FROM public.role_endpoint;
    SELECT count(*) INTO v_rr FROM public.role_route;
    SELECT count(*) INTO v_ra FROM public.role_app;
    RAISE NOTICE 'V305: role_query=% role_endpoint=% role_route=% role_app=%',
        v_rq, v_re, v_rr, v_ra;

    IF (SELECT count(*) FROM public.role_query rq
          JOIN public.role r ON r.id_role = rq.role_id
         WHERE r.name = 'CEVAL-RECTOR') < 2 THEN
        RAISE WARNING 'V305: CEVAL-RECTOR sigue con menos de 2 queries. Revisa que el rol exista con ese nombre exacto en public.role.';
    END IF;
END $$;


-- ===========================================================================
-- V305 - repone los permisos de rol que produccion nunca recibio.
--        Sin esto un rector ve sus menus pero no puede abrir ninguno.
--
-- EL SINTOMA
--   Un funcionario con rol academico -- rector, coordinador, docente --
--   entra al sistema, ve su menu lateral completo y al pulsar cualquier
--   opcion recibe un 403 "El catalogo rechazo la consulta". No es que le
--   falte el menu: es que no tiene permiso sobre los endpoints que ese menu
--   consulta.
--
--   Medido en produccion, CEVAL-RECTOR tenia UNA sola query autorizada:
--
--       eval-col-my-menus-001 | GET /my-menus
--
--   Justamente la que pinta el menu. Todo lo demas -- funcionarios, sedes,
--   periodos, matricula -- le respondia 403. Los 15 roles CEVAL no-super
--   estaban igual: exactamente una query cada uno.
--
-- POR QUE PASO
--   Las migraciones que siembran role_query resuelven los roles POR NOMBRE:
--
--       JOIN public.role r ON r.name IN ('CEVAL-RECTOR', ..., 'SSO-ADMIN')
--       ...
--       ON CONFLICT DO NOTHING;
--
--   Si un rol no existe con ese nombre exacto cuando la migracion corre, el
--   JOIN no devuelve fila y el INSERT es un no-op SILENCIOSO: ni error, ni
--   aviso, ni fila. Eso ocurrio en produccion por dos motivos que se suman:
--
--     1. Los roles CEVAL-* se derivan de academico_test.TROL, que NO esta en
--        las migraciones -- el catalogo real viene del dump base. Cuando
--        corrieron las migraciones de role_query, public.role todavia no los
--        tenia.
--
--     2. El rol de administrador del SSO se llama 'ADMIN' en produccion y
--        'SSO-ADMIN' en el servidor de pruebas. Toda migracion que nombra
--        'SSO-ADMIN' literal ha sido, y seguira siendo, un no-op en
--        produccion.
--
--   Hoy los roles SI existen: si aquellas migraciones se reejecutaran ahora
--   insertarian correctamente. Pero Flyway no reejecuta lo ya aplicado, asi
--   que el hueco solo se cierra reponiendo los pares explicitamente.
--
-- EL ALCANCE, MEDIDO
--   Comparando produccion contra el servidor de pruebas -- que si esta
--   funcional -- y normalizando el alias ADMIN/SSO-ADMIN:
--
--       role_query      faltan 1124   sobran  0
--       role_endpoint   faltan   28   sobran 20
--       role_route      faltan   12   sobran  0
--       role_app        faltan    1   sobran  0
--
--   Esta migracion repone los 1165 que faltan. Los 20 role_endpoint que
--   produccion tiene de mas NO se tocan: quitar un permiso es mucho mas
--   arriesgado que anadirlo, y no hay forma de saber desde aqui si son
--   drift o una decision deliberada. Quedan anotados para revisarlos
--   aparte.
--
-- POR QUE EMPAREJA POR RUTA Y NO POR UUID
--   Los 261 endpoints de public.query son los MISMOS en los dos entornos
--   (mismo serviceid + path_template + http_method), pero 71 de ellos
--   tienen UUID distinto. Emparejar por uuid dejaria fuera esos 71 sin
--   avisar -- el mismo tipo de fallo silencioso que causo todo esto. La
--   identidad estable de una query es (microservicio, ruta, metodo).
--
-- EL ALIAS DEL ROL ADMINISTRADOR
--   La CTE roles_alias hace que 'SSO-ADMIN' encuentre tambien al rol
--   llamado 'ADMIN', y lo mismo con 'SSO-USER'/'USER'. Asi la migracion
--   funciona en los dos entornos sin tener que renombrar nada. El problema
--   de fondo -- dos nombres para el mismo rol -- sigue abierto y merece
--   decidirse aparte; esto solo evita que vuelva a morderse aqui.
--
-- IDEMPOTENTE
--   Todo va con ON CONFLICT DO NOTHING: reaplicarla no duplica nada, y en
--   un entorno ya completo no inserta ninguna fila.
-- ===========================================================================

-- Alias: 'SSO-ADMIN' resuelve tambien al rol 'ADMIN' (y SSO-USER a USER).
CREATE TEMP VIEW v305_roles AS
    SELECT id_role, name FROM public.role
    UNION ALL SELECT id_role, 'SSO-ADMIN' FROM public.role WHERE name = 'ADMIN'
    UNION ALL SELECT id_role, 'SSO-USER'  FROM public.role WHERE name = 'USER'
    UNION ALL SELECT id_role, 'ADMIN'     FROM public.role WHERE name = 'SSO-ADMIN'
    UNION ALL SELECT id_role, 'USER'      FROM public.role WHERE name = 'SSO-USER';



-- V308 - Parámetros de edad, capa 0 de 5: tablas.
-- Edad recomendada por grado (lista GRADOS) y fecha de corte por calendario
-- (lista CALENDARIO), con las que se calcula la situación de edad. Son globales:
-- un registro por grado y uno por calendario, sin baja (la vista no elimina).
-- Depende de: V22 (TLISTA_VALOR), V283 (auditoría CDC).

SET search_path TO academico_test, public;

CREATE TABLE IF NOT EXISTS academico_test.TEDAD_RECOMENDADA_GRADO (
    PK_TEDAD_RECOMENDADA_GRADO BIGINT GENERATED BY DEFAULT AS IDENTITY,
    FK_TLV_GRADO               BIGINT       NOT NULL,
    EDAD                       SMALLINT     NOT NULL,
    CREATED_BY                 VARCHAR(120) NOT NULL,
    CREATED_AT                 TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    MODIFIED_BY                VARCHAR(120),
    MODIFIED_AT                TIMESTAMP,
    CONSTRAINT PK_TEDAD_RECOMENDADA_GRADO PRIMARY KEY (PK_TEDAD_RECOMENDADA_GRADO),
    CONSTRAINT U_TEDAD_RECOMENDADA_GRADO_GRADO UNIQUE (FK_TLV_GRADO),
    CONSTRAINT FK_TEDAD_RECOMENDADA_GRADO_1 FOREIGN KEY (FK_TLV_GRADO) REFERENCES academico_test.TLISTA_VALOR (PK_LISTA_VALOR),
    CONSTRAINT CHK_TEDAD_RECOMENDADA_GRADO_EDAD CHECK (EDAD BETWEEN 2 AND 25)
);

COMMENT ON TABLE academico_test.TEDAD_RECOMENDADA_GRADO
    IS 'Edad recomendada (años) de cada grado de la lista GRADOS. Global, una fila por grado.';

CREATE TABLE IF NOT EXISTS academico_test.TFECHA_CORTE_CALENDARIO (
    PK_TFECHA_CORTE_CALENDARIO BIGINT GENERATED BY DEFAULT AS IDENTITY,
    FK_TLV_CALENDARIO          BIGINT       NOT NULL,
    MES                        SMALLINT     NOT NULL,
    DIA                        SMALLINT     NOT NULL,
    CREATED_BY                 VARCHAR(120) NOT NULL,
    CREATED_AT                 TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    MODIFIED_BY                VARCHAR(120),
    MODIFIED_AT                TIMESTAMP,
    CONSTRAINT PK_TFECHA_CORTE_CALENDARIO PRIMARY KEY (PK_TFECHA_CORTE_CALENDARIO),
    CONSTRAINT U_TFECHA_CORTE_CALENDARIO_CALENDARIO UNIQUE (FK_TLV_CALENDARIO),
    CONSTRAINT FK_TFECHA_CORTE_CALENDARIO_1 FOREIGN KEY (FK_TLV_CALENDARIO) REFERENCES academico_test.TLISTA_VALOR (PK_LISTA_VALOR),
    CONSTRAINT CHK_TFECHA_CORTE_CALENDARIO_MES CHECK (MES BETWEEN 1 AND 12),
    -- 2023 no es bisiesto: el 29 de febrero queda fuera, como pide la regla.
    CONSTRAINT CHK_TFECHA_CORTE_CALENDARIO_DIA CHECK (
        DIA BETWEEN 1 AND EXTRACT(DAY FROM (make_date(2023, MES, 1) + INTERVAL '1 month - 1 day'))::INT)
);

COMMENT ON TABLE academico_test.TFECHA_CORTE_CALENDARIO
    IS 'Fecha de corte (mes y día, sin año) de cada calendario de la lista CALENDARIO: a esa fecha del año lectivo se cuentan los años cumplidos. Global, una fila por calendario; nunca el 29 de febrero.';

SELECT academico_test.fn_cdc_asegurar_auditoria('academico_test', 'tedad_recomendada_grado');
SELECT academico_test.fn_cdc_asegurar_auditoria('academico_test', 'tfecha_corte_calendario');

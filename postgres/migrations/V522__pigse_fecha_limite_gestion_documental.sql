BEGIN
    SELECT count(*) INTO v_endpoints FROM public.query
     WHERE uuid IN ('pigse-gestion-documental-fecha-limite-obtener',
                     'pigse-gestion-documental-fecha-limite-guardar',
                     'pigse-gestion-documental-excepcion-guardar',
                     'pigse-gestion-documental-excepcion-eliminar');

    SELECT count(*) INTO v_grants_lectura FROM public.role_query rq
      JOIN public.query q ON q.id_query = rq.query_id
     WHERE q.uuid = 'pigse-gestion-documental-fecha-limite-obtener';

    SELECT count(*) INTO v_grants_escritura FROM public.role_query rq
      JOIN public.query q ON q.id_query = rq.query_id
     WHERE q.uuid IN ('pigse-gestion-documental-fecha-limite-guardar',
                       'pigse-gestion-documental-excepcion-guardar',
                       'pigse-gestion-documental-excepcion-eliminar');

    IF v_endpoints <> 4 THEN
        RAISE EXCEPTION 'V522 fallo: se esperaban 4 endpoints nuevos, hay %', v_endpoints;
    END IF;
    IF v_grants_lectura <> 4 THEN
        RAISE EXCEPTION 'V522 fallo: se esperaban 4 grants de lectura, hay %', v_grants_lectura;
    END IF;
    IF v_grants_escritura <> 6 THEN
        RAISE EXCEPTION 'V522 fallo: se esperaban 6 grants de escritura (3 endpoints x 2 roles), hay %', v_grants_escritura;
    END IF;

    RAISE NOTICE 'V522 OK: % endpoints, % grants lectura, % grants escritura.', v_endpoints, v_grants_lectura, v_grants_escritura;
END $$;

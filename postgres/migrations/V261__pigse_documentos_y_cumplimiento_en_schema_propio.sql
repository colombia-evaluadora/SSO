-- Mueve al schema propio de PIGSE los documentos institucionales (PEI/PEC/PMI)
-- y el monitoreo de cumplimiento, replicando el comportamiento VIGENTE de las
-- academico_test.fn_pigse_* (V149 + V152 + V196). Nada de academico_test se
-- toca: las funciones originales quedan intactas y siguen leyendo su fuente.
-- Los catalogos (tlista_valor, tmunicipio) siguen siendo los compartidos.

-- ---------------------------------------------------------------------------
-- De donde se leen los metadatos de un archivo.
--
-- fk_tarchivo NO lleva FK a proposito: la autoridad de en que schema vive un
-- archivo es public.file_reference_location, y el pk es global
-- (public.seq_pk_tarchivo, V147). Los archivos historicos de PIGSE quedaron en
-- academico_test.tarchivo (V149 apuntaba file_storage_schema ahi); los nuevos
-- caen en pigse.tarchivo (V262). Esta vista los resuelve por pk sin duplicar
-- filas ni mover blobs.
-- ---------------------------------------------------------------------------
CREATE OR REPLACE VIEW pigse.v_archivo AS
SELECT pk_tarchivo, nombre, peso, created_at FROM pigse.tarchivo          WHERE active
UNION ALL
SELECT pk_tarchivo, nombre, peso, created_at FROM academico_test.tarchivo WHERE active;

-- ---------------------------------------------------------------------------
-- Tablas
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS pigse.tdocumento_institucional (
    pk_documento_institucional BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    fk_testablecimiento        BIGINT NOT NULL,
    tipo                       VARCHAR(10) NOT NULL,
    fk_tarchivo                BIGINT,
    created_by                 VARCHAR(120) NOT NULL,
    created_at                 TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    modified_by                VARCHAR(120),
    modified_at                TIMESTAMP,
    active                     BOOLEAN DEFAULT TRUE NOT NULL,
    CONSTRAINT pigse_tdocumento_institucional_pk PRIMARY KEY (pk_documento_institucional),
    CONSTRAINT pigse_tdocumento_institucional_tipo_chk CHECK (tipo IN ('PEI', 'PEC', 'PMI')),
    CONSTRAINT fk_pigse_tdocumento_inst_testablec FOREIGN KEY (fk_testablecimiento)
        REFERENCES pigse.testablecimiento (PK_ESTABLECIMIENTO)
);

-- Un documento VIGENTE por EE+tipo: reemplazar es UPDATE, no un segundo INSERT.
CREATE UNIQUE INDEX IF NOT EXISTS U_PIGSE_TDOCUMENTO_INST_EE_TIPO
    ON pigse.tdocumento_institucional (fk_testablecimiento, tipo)
    WHERE active = true;
CREATE INDEX IF NOT EXISTS IDX_PIGSE_TDOCUMENTO_INST_ARCHIVO
    ON pigse.tdocumento_institucional (fk_tarchivo);
CREATE INDEX IF NOT EXISTS IDX_PIGSE_TDOCUMENTO_INST_ACTIVE
    ON pigse.tdocumento_institucional (pk_documento_institucional) WHERE active = true;

CREATE TABLE IF NOT EXISTS pigse.tdocumento_institucional_hist (
    pk_documento_institucional_hist BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    fk_documento_institucional      BIGINT NOT NULL,
    fk_tarchivo                     BIGINT NOT NULL,
    reemplazado_by                  VARCHAR(120) NOT NULL,
    reemplazado_at                  TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT pigse_tdoc_inst_hist_pk PRIMARY KEY (pk_documento_institucional_hist),
    CONSTRAINT fk_pigse_tdoc_inst_hist_doc FOREIGN KEY (fk_documento_institucional)
        REFERENCES pigse.tdocumento_institucional (pk_documento_institucional)
);

CREATE INDEX IF NOT EXISTS IDX_PIGSE_TDOC_INST_HIST_DOC
    ON pigse.tdocumento_institucional_hist (fk_documento_institucional);

COMMENT ON TABLE pigse.tdocumento_institucional IS
    'PIGSE -- documento institucional vigente por establecimiento y tipo (PEI/PEC/PMI). fk_tarchivo NULL = PENDIENTE.';
COMMENT ON TABLE pigse.tdocumento_institucional_hist IS
    'PIGSE -- versiones reemplazadas o retiradas de un documento institucional.';


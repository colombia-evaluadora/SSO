DO $$
DECLARE
    r RECORD;
BEGIN
    FOR r IN
        SELECT t.schemaname, t.tablename
          FROM pg_tables t
         WHERE t.schemaname = 'pigse'
           AND t.tablename IN ('tdocumento_institucional', 'tdocumento_institucional_hist')
           AND NOT EXISTS (
               SELECT 1
                 FROM pg_trigger tg
                 JOIN pg_class c     ON c.oid = tg.tgrelid
                 JOIN pg_namespace n ON n.oid = c.relnamespace
                WHERE n.nspname = t.schemaname
                  AND c.relname = t.tablename
                  AND tg.tgname = 'trg_audit_ctx'
                  AND NOT tg.tgisinternal
           )
         ORDER BY t.tablename
    LOOP
        EXECUTE format(
            'CREATE TRIGGER trg_audit_ctx BEFORE INSERT OR UPDATE OR DELETE ON %I.%I
             FOR EACH STATEMENT EXECUTE FUNCTION academico_test.fn_audit_ctx()',
            r.schemaname, r.tablename
        );
        RAISE NOTICE 'trg_audit_ctx instalado en %.%', r.schemaname, r.tablename;
    END LOOP;
END $$;

-- ---------------------------------------------------------------------------
-- Resolucion de identidad: espejo de public.fn_get_academico_usuario_id, pero
-- contra pigse.tusuario. Solo por FK_ID_USER: en pigse el enlace con el login
-- es explicito, no hay que adivinarlo por correo.
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.fn_get_pigse_usuario_id(p_id_user BIGINT)
RETURNS BIGINT
LANGUAGE plpgsql
STABLE
SET search_path TO 'public', 'pigse'
AS $$
DECLARE
    v_pk BIGINT;
BEGIN
    IF p_id_user IS NULL THEN
        RETURN NULL;
    END IF;

    SELECT u.PK_TUSUARIO INTO v_pk
      FROM pigse.tusuario u
     WHERE u.FK_ID_USER = p_id_user
       AND u.ACTIVE = TRUE
     ORDER BY u.PK_TUSUARIO
     LIMIT 1;

    RETURN v_pk;
END;
$$;

-- ---------------------------------------------------------------------------
-- Establecimiento del usuario autenticado. El vinculo puede venir del puente
-- con rol o del perfil de funcionario; tiene que resolver a exactamente uno.
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION pigse.fn_mi_establecimiento(p_email TEXT)
RETURNS BIGINT
LANGUAGE plpgsql
STABLE
AS $$
DECLARE
    v_pk    BIGINT;
    v_count INT;
BEGIN
    SELECT COUNT(*), MIN(pk_establecimiento)
      INTO v_count, v_pk
      FROM (
            SELECT te.PK_ESTABLECIMIENTO AS pk_establecimiento
              FROM pigse.tusuario t
              JOIN pigse.testablecimiento_usuario eu ON eu.FK_TUSUARIO = t.PK_TUSUARIO
              JOIN pigse.testablecimiento te ON te.PK_ESTABLECIMIENTO = eu.FK_TESTABLECIMIENTO
             WHERE upper(t.CORREO_ELECTRONICO) = upper(p_email)
               AND t.ACTIVE AND eu.ACTIVE AND eu.TLV_ESTADO = 'ACTIVO' AND te.ACTIVE
            UNION
            SELECT te.PK_ESTABLECIMIENTO
              FROM pigse.tusuario t
              JOIN pigse.tfuncionario f ON f.FK_TUSUARIO = t.PK_TUSUARIO
              JOIN pigse.testablecimiento te ON te.PK_ESTABLECIMIENTO = f.FK_TESTABLECIMIENTO
             WHERE upper(t.CORREO_ELECTRONICO) = upper(p_email)
               AND t.ACTIVE AND f.ACTIVE AND te.ACTIVE
           ) x;

    IF v_count IS NULL OR v_count <> 1 THEN
        RAISE EXCEPTION 'pigse: % no esta vinculado a exactamente un establecimiento (encontrados: %)',
            p_email, COALESCE(v_count, 0);
    END IF;
    RETURN v_pk;
END;
$$;


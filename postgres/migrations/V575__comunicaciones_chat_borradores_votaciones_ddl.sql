-- V575 -- Chat: borradores por canal y votaciones rapidas (capa 0, DDL)
-- Que hace: un borrador por (canal, usuario) que pasa a ENVIADO al mandarse, y
--   la votacion rapida (pregunta de dos opciones con cierre por tiempo) colgada
--   de un mensaje, con un voto por persona.
-- Por que aqui: lo escribe y lee comms-service (Java), igual que V560. Sin funciones.
-- Depende de: V560 (tcanal, tmensaje), public.users.

CREATE TABLE IF NOT EXISTS comunicaciones.tborrador (
    pk_tborrador BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fk_tcanal    BIGINT      NOT NULL REFERENCES comunicaciones.tcanal(pk_tcanal),
    fk_usuario   BIGINT      NOT NULL REFERENCES public.users(id_user),
    texto        TEXT        NOT NULL CHECK (char_length(texto) <= 4000),
    estado       VARCHAR(10) NOT NULL DEFAULT 'BORRADOR' CHECK (estado IN ('BORRADOR','ENVIADO')),
    -- Mensaje que lo envio (estado ENVIADO).
    fk_tmensaje  BIGINT      REFERENCES comunicaciones.tmensaje(pk_tmensaje),
    created_at   TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    modified_at  TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    eliminado_en TIMESTAMPTZ
);
-- Un solo borrador vivo por canal y persona: guardar lo reemplaza.
CREATE UNIQUE INDEX IF NOT EXISTS ux_tborrador_canal_usuario
    ON comunicaciones.tborrador (fk_tcanal, fk_usuario) WHERE estado = 'BORRADOR' AND eliminado_en IS NULL;
CREATE INDEX IF NOT EXISTS ix_tborrador_usuario
    ON comunicaciones.tborrador (fk_usuario, modified_at DESC) WHERE eliminado_en IS NULL;

CREATE TABLE IF NOT EXISTS comunicaciones.tvotacion_rapida (
    fk_tmensaje BIGINT      PRIMARY KEY REFERENCES comunicaciones.tmensaje(pk_tmensaje),
    pregunta    VARCHAR(300) NOT NULL,
    tipo        VARCHAR(16) NOT NULL CHECK (tipo IN ('SI_NO','VERDADERO_FALSO')),
    minutos     INTEGER     NOT NULL CHECK (minutos BETWEEN 1 AND 1440),
    cierra_en   TIMESTAMPTZ NOT NULL
);

CREATE TABLE IF NOT EXISTS comunicaciones.tvotacion_rapida_voto (
    fk_tmensaje BIGINT      NOT NULL REFERENCES comunicaciones.tvotacion_rapida(fk_tmensaje),
    fk_usuario  BIGINT      NOT NULL REFERENCES public.users(id_user),
    -- 1 = Si/Verdadero, 2 = No/Falso.
    opcion      SMALLINT    NOT NULL CHECK (opcion IN (1, 2)),
    created_at  TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    PRIMARY KEY (fk_tmensaje, fk_usuario)
);


-- V580 -- Schema comunicaciones: actividades de canal (capa 0, DDL)
-- Que hace: comunicados (audiencia por rol, confirmacion de lectura, mensaje
--   fijado), encuestas (preguntas de opcion unica/multiple/si-no/redaccion,
--   respuestas anonimas), elecciones (candidatos, censo de votantes, voto
--   secreto) y evaluaciones (preguntas con puntaje, entregas e intentos).
-- Por que aqui: lo escribe y lee comms-service (Java), igual que V560. Cada
--   actividad es 1:1 con un tcanal de su categoria (ANUNCIO, ENCUESTA,
--   VOTACION, EXAMEN). Sin funciones.
-- Voto secreto: tvotante dice QUIEN voto (para impedir el doble voto y avisar
--   solo a quien falta); tvoto dice POR QUIEN, sin usuario ni hora. No hay
--   columna que una las dos tablas.
-- Depende de: V560 (tcanal, tmensaje), public.users, V283 (fn_cdc_asegurar_auditoria).

-- ── comunicados ─────────────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS comunicaciones.tcomunicado (
    fk_tcanal       BIGINT       PRIMARY KEY REFERENCES comunicaciones.tcanal(pk_tcanal),
    titulo          VARCHAR(100) NOT NULL,
    descripcion     VARCHAR(500) NOT NULL DEFAULT '',
    -- ESTUDIANTES | DOCENTES | PADRES | DIRECTIVOS | ADMINISTRATIVOS
    audiencia       VARCHAR(20)[] NOT NULL,
    publicar_en     TIMESTAMPTZ  NOT NULL,
    contenido_html  TEXT         NOT NULL,
    -- Mensaje fijado del canal: base de la confirmacion de lectura.
    fk_tmensaje     BIGINT       REFERENCES comunicaciones.tmensaje(pk_tmensaje),
    -- Aviso CHAT_COMUNICADO encolado (al publicar, aunque se programe).
    notificado_en   TIMESTAMPTZ,
    CHECK (cardinality(audiencia) > 0),
    CHECK (char_length(contenido_html) <= 100000)
);

-- ── encuestas ───────────────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS comunicaciones.tencuesta (
    fk_tcanal      BIGINT       PRIMARY KEY REFERENCES comunicaciones.tcanal(pk_tcanal),
    nombre         VARCHAR(100) NOT NULL,
    descripcion    VARCHAR(500) NOT NULL DEFAULT '',
    fecha_inicio   TIMESTAMPTZ,
    fecha_cierre   TIMESTAMPTZ,
    resultados     VARCHAR(10)  NOT NULL DEFAULT 'PUBLICOS' CHECK (resultados IN ('PUBLICOS','ADMIN')),
    notificado_en  TIMESTAMPTZ,
    CHECK (fecha_cierre IS NULL OR fecha_inicio IS NULL OR fecha_cierre > fecha_inicio)
);

CREATE TABLE IF NOT EXISTS comunicaciones.tencuesta_pregunta (
    pk_tencuesta_pregunta BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fk_tcanal             BIGINT       NOT NULL REFERENCES comunicaciones.tencuesta(fk_tcanal),
    orden                 INTEGER      NOT NULL,
    tipo                  VARCHAR(10)  NOT NULL CHECK (tipo IN ('MULTIPLE','UNICA','REDACCION','SI_NO')),
    texto                 VARCHAR(500) NOT NULL
);
CREATE INDEX IF NOT EXISTS ix_tencuesta_pregunta_canal ON comunicaciones.tencuesta_pregunta (fk_tcanal);

CREATE TABLE IF NOT EXISTS comunicaciones.tencuesta_opcion (
    pk_tencuesta_opcion   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fk_tencuesta_pregunta BIGINT       NOT NULL REFERENCES comunicaciones.tencuesta_pregunta(pk_tencuesta_pregunta),
    orden                 INTEGER      NOT NULL,
    texto                 VARCHAR(200) NOT NULL
);
CREATE INDEX IF NOT EXISTS ix_tencuesta_opcion_pregunta ON comunicaciones.tencuesta_opcion (fk_tencuesta_pregunta);

-- Quien respondio (una sola vez). Las respuestas en si no guardan el usuario.
CREATE TABLE IF NOT EXISTS comunicaciones.tencuesta_participante (
    fk_tcanal  BIGINT NOT NULL REFERENCES comunicaciones.tencuesta(fk_tcanal),
    fk_usuario BIGINT NOT NULL REFERENCES public.users(id_user),
    PRIMARY KEY (fk_tcanal, fk_usuario)
);

CREATE TABLE IF NOT EXISTS comunicaciones.tencuesta_respuesta (
    pk_tencuesta_respuesta BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fk_tencuesta_pregunta  BIGINT NOT NULL REFERENCES comunicaciones.tencuesta_pregunta(pk_tencuesta_pregunta),
    -- Opciones elegidas (vacio en redaccion) o texto libre (solo redaccion).
    opciones               BIGINT[] NOT NULL DEFAULT '{}',
    texto                  VARCHAR(2000),
    created_at             TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS ix_tencuesta_respuesta_pregunta ON comunicaciones.tencuesta_respuesta (fk_tencuesta_pregunta);

-- ── elecciones ──────────────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS comunicaciones.televeccion (
    fk_tcanal              BIGINT       PRIMARY KEY REFERENCES comunicaciones.tcanal(pk_tcanal),
    nombre                 VARCHAR(100) NOT NULL,
    descripcion            VARCHAR(500) NOT NULL DEFAULT '',
    fecha_inicio           TIMESTAMPTZ,
    fecha_cierre           TIMESTAMPTZ,
    fk_jornada             BIGINT       NOT NULL,
    ver_resultados_en_vivo BOOLEAN      NOT NULL DEFAULT FALSE,
    cerrada_en             TIMESTAMPTZ,
    -- Aviso CHAT_ELECCION encolado al abrir la votacion.
    notificado_en          TIMESTAMPTZ,
    CHECK (fecha_cierre IS NULL OR fecha_inicio IS NULL OR fecha_cierre > fecha_inicio)
);

CREATE TABLE IF NOT EXISTS comunicaciones.televeccion_candidato (
    pk_televeccion_candidato BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fk_tcanal                BIGINT       NOT NULL REFERENCES comunicaciones.televeccion(fk_tcanal),
    orden                    INTEGER      NOT NULL,
    nombre                   VARCHAR(150) NOT NULL,
    numero                   VARCHAR(10)  NOT NULL,
    lema                     VARCHAR(200) NOT NULL DEFAULT '',
    -- Data URL reducida en el front (JPEG/PNG/WebP, <= 300 KB).
    foto_url                 TEXT,
    CHECK (foto_url IS NULL OR char_length(foto_url) <= 400000)
);
CREATE INDEX IF NOT EXISTS ix_televeccion_candidato_canal ON comunicaciones.televeccion_candidato (fk_tcanal);

-- Censo: quien puede votar y si ya lo hizo (sin decir por quien).
CREATE TABLE IF NOT EXISTS comunicaciones.televeccion_votante (
    fk_tcanal  BIGINT  NOT NULL REFERENCES comunicaciones.televeccion(fk_tcanal),
    fk_usuario BIGINT  NOT NULL REFERENCES public.users(id_user),
    voto       BOOLEAN NOT NULL DEFAULT FALSE,
    PRIMARY KEY (fk_tcanal, fk_usuario)
);

-- Urna: por quien (NULL = voto en blanco), sin usuario ni hora.
CREATE TABLE IF NOT EXISTS comunicaciones.televeccion_voto (
    -- UUID aleatorio: un consecutivo permitiria cruzar el orden de los votos con el de los votantes.
    pk_televeccion_voto      UUID   PRIMARY KEY DEFAULT gen_random_uuid(),
    fk_tcanal                BIGINT NOT NULL REFERENCES comunicaciones.televeccion(fk_tcanal),
    fk_televeccion_candidato BIGINT REFERENCES comunicaciones.televeccion_candidato(pk_televeccion_candidato)
);
CREATE INDEX IF NOT EXISTS ix_televeccion_voto_canal ON comunicaciones.televeccion_voto (fk_tcanal);

-- ── evaluaciones ────────────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS comunicaciones.tevaluacion (
    fk_tcanal          BIGINT        PRIMARY KEY REFERENCES comunicaciones.tcanal(pk_tcanal),
    nombre             VARCHAR(100)  NOT NULL,
    descripcion        VARCHAR(500)  NOT NULL DEFAULT '',
    fecha_inicio       TIMESTAMPTZ,
    fecha_cierre       TIMESTAMPTZ,
    tiempo_limite_min  INTEGER       CHECK (tiempo_limite_min IS NULL OR tiempo_limite_min > 0),
    puntaje_total      NUMERIC(8,2)  NOT NULL CHECK (puntaje_total > 0),
    intentos           INTEGER       CHECK (intentos IS NULL OR intentos > 0),
    mostrar_resultados VARCHAR(10)   NOT NULL DEFAULT 'AL_CIERRE' CHECK (mostrar_resultados IN ('INMEDIATO','AL_CIERRE')),
    notificado_en      TIMESTAMPTZ,
    CHECK (fecha_cierre IS NULL OR fecha_inicio IS NULL OR fecha_cierre > fecha_inicio)
);

CREATE TABLE IF NOT EXISTS comunicaciones.tevaluacion_pregunta (
    pk_tevaluacion_pregunta BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fk_tcanal               BIGINT       NOT NULL REFERENCES comunicaciones.tevaluacion(fk_tcanal),
    orden                   INTEGER      NOT NULL,
    tipo                    VARCHAR(10)  NOT NULL CHECK (tipo IN ('MULTIPLE','UNICA','REDACCION','SI_NO')),
    texto                   VARCHAR(1000) NOT NULL,
    puntos                  NUMERIC(8,2) NOT NULL CHECK (puntos >= 0)
);
CREATE INDEX IF NOT EXISTS ix_tevaluacion_pregunta_canal ON comunicaciones.tevaluacion_pregunta (fk_tcanal);

CREATE TABLE IF NOT EXISTS comunicaciones.tevaluacion_opcion (
    pk_tevaluacion_opcion   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fk_tevaluacion_pregunta BIGINT       NOT NULL REFERENCES comunicaciones.tevaluacion_pregunta(pk_tevaluacion_pregunta),
    orden                   INTEGER      NOT NULL,
    texto                   VARCHAR(300) NOT NULL,
    correcta                BOOLEAN      NOT NULL DEFAULT FALSE
);
CREATE INDEX IF NOT EXISTS ix_tevaluacion_opcion_pregunta ON comunicaciones.tevaluacion_opcion (fk_tevaluacion_pregunta);

CREATE TABLE IF NOT EXISTS comunicaciones.tevaluacion_entrega (
    pk_tevaluacion_entrega BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fk_tcanal              BIGINT      NOT NULL REFERENCES comunicaciones.tevaluacion(fk_tcanal),
    fk_usuario             BIGINT      NOT NULL REFERENCES public.users(id_user),
    estado                 VARCHAR(10) NOT NULL CHECK (estado IN ('PENDIENTE','CALIFICADA')),
    created_at             TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    calificada_por         BIGINT      REFERENCES public.users(id_user),
    calificada_en          TIMESTAMPTZ
);
CREATE INDEX IF NOT EXISTS ix_tevaluacion_entrega_canal_usuario
    ON comunicaciones.tevaluacion_entrega (fk_tcanal, fk_usuario);

CREATE TABLE IF NOT EXISTS comunicaciones.tevaluacion_respuesta (
    fk_tevaluacion_entrega  BIGINT       NOT NULL REFERENCES comunicaciones.tevaluacion_entrega(pk_tevaluacion_entrega),
    fk_tevaluacion_pregunta BIGINT       NOT NULL REFERENCES comunicaciones.tevaluacion_pregunta(pk_tevaluacion_pregunta),
    opciones                BIGINT[]     NOT NULL DEFAULT '{}',
    texto                   VARCHAR(4000),
    -- Automatica (opciones) al entregar; redaccion la pone el docente.
    puntos                  NUMERIC(8,2),
    PRIMARY KEY (fk_tevaluacion_entrega, fk_tevaluacion_pregunta)
);


CREATE OR REPLACE FUNCTION academico_test.fn_criterioprio_regla_motivo(
    p_pk_campo     BIGINT,
    p_codigo_regla VARCHAR
)
RETURNS VARCHAR
LANGUAGE sql
STABLE
AS $$
    SELECT CASE
        WHEN c.TIPO = 'SI_NO' AND p_codigo_regla <> 'ES_SI'
            THEN format('%s no aplica: el campo es Sí/No.', r.NOMBRE)
        WHEN c.TIPO = 'SELECTOR' AND p_codigo_regla = 'ES_SI'
            THEN format('%s no aplica: el campo es un selector.', r.NOMBRE)
        WHEN c.TIPO = 'SELECTOR' AND c.CATEGORIA IS NULL AND p_codigo_regla <> 'TIENE_VALOR'
            THEN format('%s no aplica: el campo no usa una lista de valores.', r.NOMBRE)
        WHEN p_codigo_regla IN ('MENOR_A_MAYOR', 'MAYOR_A_MENOR') AND NOT COALESCE(lc.ES_ORDINAL, FALSE)
            THEN format('%s no aplica: la lista %s no es ordinal.', r.NOMBRE, COALESCE(lc.NOMBRE, c.CATEGORIA))
    END
      FROM academico_test.TCRITERIO_CAMPO c
      JOIN academico_test.TLISTA_VALOR r ON r.CATEGORIA = 'REGLA_PRIORIDAD' AND r.VALOR = p_codigo_regla AND r.ACTIVE = TRUE
      LEFT JOIN academico_test.TLISTA_CATEGORIA lc ON lc.CODIGO = c.CATEGORIA AND lc.ACTIVE = TRUE
     WHERE c.PK_TCRITERIO_CAMPO = p_pk_campo;
$$;

COMMENT ON FUNCTION academico_test.fn_criterioprio_regla_motivo(BIGINT, VARCHAR)
    IS 'Por qué una regla de REGLA_PRIORIDAD no aplica a un campo (NULL = aplica): Es Sí solo en Sí/No; Tiene valor y Es uno de en selectores (Es uno de, solo si el selector usa una Lista de Valores); De menor a mayor y De mayor a menor solo en listas ordinales. Es la ayuda que muestra el formulario.';

CREATE OR REPLACE FUNCTION academico_test.fn_criterioprio_validar_regla(
    p_pk_campo BIGINT,
    p_pk_regla BIGINT
)
RETURNS VARCHAR
LANGUAGE plpgsql
STABLE
AS $$
DECLARE
    v_codigo VARCHAR;
    v_motivo VARCHAR;
BEGIN
    SELECT VALOR INTO v_codigo FROM academico_test.TLISTA_VALOR
     WHERE PK_LISTA_VALOR = p_pk_regla AND CATEGORIA = 'REGLA_PRIORIDAD' AND ACTIVE = TRUE;
    IF v_codigo IS NULL THEN
        RAISE EXCEPTION 'Seleccione una regla de prioridad válida.' USING ERRCODE = '22023';
    END IF;
    v_motivo := academico_test.fn_criterioprio_regla_motivo(p_pk_campo, v_codigo);
    IF v_motivo IS NOT NULL THEN
        RAISE EXCEPTION '%', v_motivo USING ERRCODE = '22023';
    END IF;
    RETURN v_codigo;
END;
$$;

COMMENT ON FUNCTION academico_test.fn_criterioprio_validar_regla(BIGINT, BIGINT)
    IS '22023 si la regla no es de REGLA_PRIORIDAD o no aplica al tipo del campo (fn_criterioprio_regla_motivo). Devuelve el código de la regla.';

CREATE OR REPLACE FUNCTION academico_test.fn_criterioprio_validar_valores(
    p_pk_campo     BIGINT,
    p_codigo_regla VARCHAR,
    p_valores      BIGINT[]
)
RETURNS VOID
LANGUAGE plpgsql
STABLE
AS $$
BEGIN
    IF p_codigo_regla <> 'ES_UNO_DE' THEN
        IF cardinality(COALESCE(p_valores, '{}')) > 0 THEN
            RAISE EXCEPTION 'Los valores solo se eligen con la regla Es uno de.' USING ERRCODE = '22023';
        END IF;
        RETURN;
    END IF;
    IF cardinality(COALESCE(p_valores, '{}')) = 0 THEN
        RAISE EXCEPTION 'Seleccione al menos un valor.' USING ERRCODE = '22023';
    END IF;
    IF EXISTS (SELECT 1 FROM unnest(p_valores) v
                WHERE NOT EXISTS (SELECT 1 FROM academico_test.TLISTA_VALOR lv
                                    JOIN academico_test.TCRITERIO_CAMPO c ON c.CATEGORIA = lv.CATEGORIA
                                   WHERE lv.PK_LISTA_VALOR = v AND lv.ACTIVE = TRUE AND lv.HABILITADO = TRUE
                                     AND c.PK_TCRITERIO_CAMPO = p_pk_campo)) THEN
        RAISE EXCEPTION 'Uno de los valores no pertenece a la lista del campo o está inactivo.' USING ERRCODE = '22023';
    END IF;
END;
$$;

COMMENT ON FUNCTION academico_test.fn_criterioprio_validar_valores(BIGINT, VARCHAR, BIGINT[])
    IS '22023 si con Es uno de no llega ningún valor o alguno no es un valor activo de la lista del campo; con otra regla, si llega alguno.';


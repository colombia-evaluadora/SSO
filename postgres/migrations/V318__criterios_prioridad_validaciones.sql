CREATE OR REPLACE FUNCTION academico_test.fn_criterioprio_validar_existente(p_pk_criterio BIGINT)
RETURNS VOID
LANGUAGE plpgsql
STABLE
AS $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM academico_test.TCRITERIO_PRIORIDAD
                    WHERE PK_TCRITERIO_PRIORIDAD = p_pk_criterio AND ACTIVE = TRUE) THEN
        RAISE EXCEPTION 'No existe el criterio de prioridad solicitado.' USING ERRCODE = 'P0002';
    END IF;
END;
$$;

COMMENT ON FUNCTION academico_test.fn_criterioprio_validar_existente(BIGINT)
    IS 'P0002 si no hay un criterio de prioridad no eliminado con ese pk.';

CREATE OR REPLACE FUNCTION academico_test.fn_criterioprio_validar_nombre(
    p_nombre     VARCHAR,
    p_pk_excluir BIGINT DEFAULT NULL
)
RETURNS VOID
LANGUAGE plpgsql
STABLE
AS $$
BEGIN
    IF p_nombre IS NULL OR length(TRIM(p_nombre)) NOT BETWEEN 4 AND 80 THEN
        RAISE EXCEPTION 'El nombre del criterio debe tener entre 4 y 80 caracteres.' USING ERRCODE = '22023';
    END IF;
    IF EXISTS (SELECT 1 FROM academico_test.TCRITERIO_PRIORIDAD
                WHERE ACTIVE = TRUE AND lower(TRIM(NOMBRE)) = lower(TRIM(p_nombre))
                  AND PK_TCRITERIO_PRIORIDAD IS DISTINCT FROM p_pk_excluir) THEN
        RAISE EXCEPTION 'El nombre ya existe en otro criterio de prioridad.' USING ERRCODE = '23505';
    END IF;
END;
$$;

COMMENT ON FUNCTION academico_test.fn_criterioprio_validar_nombre(VARCHAR, BIGINT)
    IS '22023 si el nombre no tiene entre 4 y 80 caracteres; 23505 si otro criterio no eliminado (activo o inactivo) se llama igual, sin distinguir mayúsculas.';


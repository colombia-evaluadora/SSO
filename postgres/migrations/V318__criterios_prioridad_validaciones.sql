CREATE OR REPLACE FUNCTION academico_test.fn_criterioprio_validar_campo(p_pk_campo BIGINT)
RETURNS VOID
LANGUAGE plpgsql
STABLE
AS $$
BEGIN
    IF p_pk_campo IS NULL THEN
        RAISE EXCEPTION 'Seleccione el campo que evalúa el criterio.' USING ERRCODE = '22023';
    END IF;
    IF NOT EXISTS (SELECT 1 FROM academico_test.TCRITERIO_CAMPO c
                     LEFT JOIN academico_test.TMATRICULA_CAMPO mc ON mc.PK_MATRICULA_CAMPO = c.FK_TMATRICULA_CAMPO
                    WHERE c.PK_TCRITERIO_CAMPO = p_pk_campo AND c.ACTIVE = TRUE
                      AND (c.FK_TMATRICULA_CAMPO IS NULL OR mc.ACTIVE = TRUE)) THEN
        RAISE EXCEPTION 'El campo seleccionado no existe o ya no se puede evaluar.' USING ERRCODE = '22023';
    END IF;
END;
$$;


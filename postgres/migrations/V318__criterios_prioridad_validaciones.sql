    IS '23503 si el criterio está en uso (fn_criterioprio_en_uso): no se modifica ni se elimina.';

CREATE OR REPLACE FUNCTION academico_test.fn_criterioprio_validar_campo_libre(
    p_pk_campos BIGINT[],
    p_cambio    VARCHAR
)
RETURNS VOID
LANGUAGE plpgsql
STABLE
AS $$
DECLARE
    v_criterios TEXT;
BEGIN
    SELECT string_agg(p.NOMBRE, ', ' ORDER BY p.NOMBRE) INTO v_criterios
      FROM academico_test.TCRITERIO_PRIORIDAD p
     WHERE p.FK_TCRITERIO_CAMPO = ANY (p_pk_campos) AND p.ACTIVE = TRUE AND p.HABILITADO = TRUE;
    IF v_criterios IS NOT NULL THEN
        RAISE EXCEPTION 'No se puede % porque lo usan estos criterios de prioridad activos: %. Desactívelos primero.',
            p_cambio, v_criterios USING ERRCODE = '23503';
    END IF;
END;
$$;

COMMENT ON FUNCTION academico_test.fn_criterioprio_validar_campo_libre(BIGINT[], VARCHAR)
    IS '23503 si algún criterio de prioridad activo evalúa uno de esos campos (TCRITERIO_CAMPO). La usan los triggers de dependencia.';

CREATE OR REPLACE FUNCTION academico_test.fn_trg_criterioprio_matricula_campo()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    PERFORM academico_test.fn_criterioprio_validar_campo_libre(
        ARRAY(SELECT PK_TCRITERIO_CAMPO FROM academico_test.TCRITERIO_CAMPO
               WHERE FK_TMATRICULA_CAMPO = OLD.PK_MATRICULA_CAMPO AND ACTIVE = TRUE),
        format('eliminar el campo de matrícula %s', OLD.NOMBRE));
    RETURN COALESCE(NEW, OLD);
END;
$$;

DROP TRIGGER IF EXISTS trg_criterioprio_matricula_campo ON academico_test.TMATRICULA_CAMPO;
CREATE TRIGGER trg_criterioprio_matricula_campo
    BEFORE DELETE OR UPDATE OF ACTIVE ON academico_test.TMATRICULA_CAMPO
    FOR EACH ROW
    WHEN (OLD.ACTIVE = TRUE)
    EXECUTE FUNCTION academico_test.fn_trg_criterioprio_matricula_campo();

CREATE OR REPLACE FUNCTION academico_test.fn_trg_criterioprio_campo()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    IF TG_OP = 'DELETE' OR NEW.ACTIVE = FALSE OR NEW.TIPO IS DISTINCT FROM OLD.TIPO
       OR NEW.CATEGORIA IS DISTINCT FROM OLD.CATEGORIA THEN
        PERFORM academico_test.fn_criterioprio_validar_campo_libre(
            ARRAY[OLD.PK_TCRITERIO_CAMPO], format('eliminar o cambiar el tipo del campo %s', OLD.NOMBRE));
    END IF;
    RETURN COALESCE(NEW, OLD);
END;
$$;

DROP TRIGGER IF EXISTS trg_criterioprio_campo ON academico_test.TCRITERIO_CAMPO;
CREATE TRIGGER trg_criterioprio_campo
    BEFORE DELETE OR UPDATE OF ACTIVE, TIPO, CATEGORIA ON academico_test.TCRITERIO_CAMPO
    FOR EACH ROW
    WHEN (OLD.ACTIVE = TRUE)
    EXECUTE FUNCTION academico_test.fn_trg_criterioprio_campo();

CREATE OR REPLACE FUNCTION academico_test.fn_trg_criterioprio_lista_ordinal()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
    v_criterios TEXT;
BEGIN
    SELECT string_agg(p.NOMBRE, ', ' ORDER BY p.NOMBRE) INTO v_criterios
      FROM academico_test.TCRITERIO_PRIORIDAD p
      JOIN academico_test.TCRITERIO_CAMPO c ON c.PK_TCRITERIO_CAMPO = p.FK_TCRITERIO_CAMPO
      JOIN academico_test.TLISTA_VALOR r ON r.PK_LISTA_VALOR = p.FK_TLV_REGLA
     WHERE c.CATEGORIA = OLD.CODIGO AND p.ACTIVE = TRUE AND p.HABILITADO = TRUE
       AND r.VALOR IN ('MENOR_A_MAYOR', 'MAYOR_A_MENOR');
    IF v_criterios IS NOT NULL THEN
        RAISE EXCEPTION 'La lista % debe seguir siendo ordinal: la ordenan estos criterios de prioridad activos: %. Desactívelos primero.',
            OLD.NOMBRE, v_criterios USING ERRCODE = '23503';
    END IF;
    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_criterioprio_lista_ordinal ON academico_test.TLISTA_CATEGORIA;
CREATE TRIGGER trg_criterioprio_lista_ordinal
    BEFORE UPDATE OF ES_ORDINAL ON academico_test.TLISTA_CATEGORIA
    FOR EACH ROW
    WHEN (OLD.ES_ORDINAL = TRUE AND NEW.ES_ORDINAL = FALSE)
    EXECUTE FUNCTION academico_test.fn_trg_criterioprio_lista_ordinal();

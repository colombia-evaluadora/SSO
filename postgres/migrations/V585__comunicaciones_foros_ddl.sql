-- V585 -- Foros de comunicaciones: publicaciones, etiquetas, respuestas y seguidores (capa 0, DDL)
-- Que hace: un canal FORO (V560) agrupa publicaciones (thilo) con titulo, etiquetas,
--   fijada/cerrada/resuelta y busqueda FTS en espanol. El cuerpo y las respuestas son
--   filas de tmensaje (reacciones, menciones y adjuntos del chat); thilo_mensaje las ata.
-- Por que aqui: lo escribe comms-service (Java) tras validar la politica; sin funciones.
-- Depende de: V560 (tcanal, tmensaje), V283 (fn_cdc_asegurar_auditoria).

CREATE TABLE IF NOT EXISTS comunicaciones.tforo_etiqueta (
    pk_tforo_etiqueta BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fk_tcanal         BIGINT       NOT NULL REFERENCES comunicaciones.tcanal(pk_tcanal),
    nombre            VARCHAR(40)  NOT NULL CHECK (char_length(btrim(nombre)) > 0),
    color             VARCHAR(10)  NOT NULL DEFAULT 'BLUE'
                        CHECK (color IN ('BLUE','GREEN','YELLOW','RED','PURPLE','ORANGE','NAVY')),
    solo_moderadores  BOOLEAN      NOT NULL DEFAULT FALSE,
    creado_por        BIGINT       NOT NULL REFERENCES public.users(id_user),
    created_at        TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    eliminado_en      TIMESTAMPTZ
);
CREATE UNIQUE INDEX IF NOT EXISTS ux_tforo_etiqueta_nombre
    ON comunicaciones.tforo_etiqueta (fk_tcanal, lower(nombre)) WHERE eliminado_en IS NULL;

CREATE TABLE IF NOT EXISTS comunicaciones.thilo (
    pk_thilo             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fk_tcanal            BIGINT       NOT NULL REFERENCES comunicaciones.tcanal(pk_tcanal),
    fk_tmensaje_raiz     BIGINT       NOT NULL UNIQUE REFERENCES comunicaciones.tmensaje(pk_tmensaje),
    fk_autor             BIGINT       NOT NULL REFERENCES public.users(id_user),
    titulo               VARCHAR(150) NOT NULL CHECK (char_length(btrim(titulo)) > 0),
    created_at           TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    ultima_actividad     TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    fijado               BOOLEAN      NOT NULL DEFAULT FALSE,
    cerrado              BOOLEAN      NOT NULL DEFAULT FALSE,
    cerrado_por          BIGINT       REFERENCES public.users(id_user),
    resuelto             BOOLEAN      NOT NULL DEFAULT FALSE,
    fk_tmensaje_solucion BIGINT       REFERENCES comunicaciones.tmensaje(pk_tmensaje),
    resuelto_por         BIGINT       REFERENCES public.users(id_user),
    -- Titulo (peso A) + cuerpo (B); lo recalcula comms-service al crear o editar.
    busqueda             TSVECTOR     NOT NULL DEFAULT ''::tsvector,
    modified_at          TIMESTAMPTZ,
    eliminado_en         TIMESTAMPTZ,
    eliminado_por        BIGINT       REFERENCES public.users(id_user)
);
CREATE INDEX IF NOT EXISTS ix_thilo_canal_actividad
    ON comunicaciones.thilo (fk_tcanal, ultima_actividad DESC) WHERE eliminado_en IS NULL;
CREATE INDEX IF NOT EXISTS ix_thilo_busqueda
    ON comunicaciones.thilo USING GIN (busqueda);

CREATE TABLE IF NOT EXISTS comunicaciones.thilo_etiqueta (
    fk_thilo          BIGINT NOT NULL REFERENCES comunicaciones.thilo(pk_thilo),
    fk_tforo_etiqueta BIGINT NOT NULL REFERENCES comunicaciones.tforo_etiqueta(pk_tforo_etiqueta),
    PRIMARY KEY (fk_thilo, fk_tforo_etiqueta)
);
CREATE INDEX IF NOT EXISTS ix_thilo_etiqueta_etiqueta
    ON comunicaciones.thilo_etiqueta (fk_tforo_etiqueta);

CREATE TABLE IF NOT EXISTS comunicaciones.thilo_mensaje (
    fk_tmensaje BIGINT NOT NULL PRIMARY KEY REFERENCES comunicaciones.tmensaje(pk_tmensaje),
    fk_thilo    BIGINT NOT NULL REFERENCES comunicaciones.thilo(pk_thilo)
);
CREATE INDEX IF NOT EXISTS ix_thilo_mensaje_hilo
    ON comunicaciones.thilo_mensaje (fk_thilo, fk_tmensaje);

CREATE TABLE IF NOT EXISTS comunicaciones.thilo_seguidor (
    fk_thilo   BIGINT      NOT NULL REFERENCES comunicaciones.thilo(pk_thilo),
    fk_usuario BIGINT      NOT NULL REFERENCES public.users(id_user),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    PRIMARY KEY (fk_thilo, fk_usuario)
);


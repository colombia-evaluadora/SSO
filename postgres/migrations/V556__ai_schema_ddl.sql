-- V556 -- Schema ai del agente: catalogo y operacion (capa 0, DDL)
-- Que hace: crea el schema ai con el catalogo de herramientas, rutas de UI y
--   formularios, y el historial de conversaciones, acciones pendientes y eventos.
-- Por que aqui: primera capa del agente. Las utilidades (V556.1), las semillas
--   (V556.2) y los endpoints (V556.3) la leen. Sin funciones ni permisos.
-- Depende de: nada; solo referencias internas al schema ai.

CREATE SCHEMA IF NOT EXISTS ai;

-- Catalogo: ai.herramienta es una allowlist. Una ruta que no esta aqui no existe
-- para el agente. query_uuid apunta a public.query.uuid (varchar), nunca a id_query.
CREATE TABLE IF NOT EXISTS ai.herramienta (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo                VARCHAR(80)  NOT NULL,
    tipo                  VARCHAR(20)  NOT NULL CHECK (tipo IN
                            ('LECTURA','ESCRITURA','ANALITICA','NAVEGACION','UI','CONTROL')),
    query_uuid            VARCHAR(64),
    menu_codigo           VARCHAR(30),
    descripcion_modelo    TEXT         NOT NULL,
    parametros            JSONB        NOT NULL DEFAULT '{}'::jsonb,
    requiere_confirmacion BOOLEAN      NOT NULL DEFAULT FALSE,
    ejemplos              JSONB        NOT NULL DEFAULT '[]'::jsonb,
    version               INTEGER      NOT NULL DEFAULT 1,
    created_by            VARCHAR(120) NOT NULL,
    created_at            TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    modified_by           VARCHAR(120),
    modified_at           TIMESTAMP,
    active                BOOLEAN      NOT NULL DEFAULT TRUE,
    CHECK (tipo NOT IN ('LECTURA','ESCRITURA','ANALITICA') OR query_uuid IS NOT NULL),
    CHECK (tipo <> 'ESCRITURA' OR requiere_confirmacion)
);
CREATE UNIQUE INDEX IF NOT EXISTS ux_ai_herramienta_codigo
    ON ai.herramienta (codigo) WHERE active = TRUE;

-- Enriquece TMENU por menu_codigo: la URL y el nombre salen de academico_test.tmenu.
CREATE TABLE IF NOT EXISTS ai.ruta_ui (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo        VARCHAR(80)  NOT NULL,
    menu_codigo   VARCHAR(30)  NOT NULL,
    descripcion   TEXT         NOT NULL,
    sinonimos     TEXT[]       NOT NULL DEFAULT '{}',
    parametros    JSONB        NOT NULL DEFAULT '{}'::jsonb,
    ruta_sufijo   VARCHAR(120),
    created_by    VARCHAR(120) NOT NULL,
    created_at    TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    modified_by   VARCHAR(120),
    modified_at   TIMESTAMP,
    active        BOOLEAN      NOT NULL DEFAULT TRUE
);
CREATE UNIQUE INDEX IF NOT EXISTS ux_ai_ruta_ui_codigo
    ON ai.ruta_ui (codigo) WHERE active = TRUE;

-- Registro ligero. origen FRONT: los campos los manda la UI. origen DB: los da campos_fuente.
CREATE TABLE IF NOT EXISTS ai.ui_formulario (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo                 VARCHAR(80) NOT NULL,
    ruta_ui_id             BIGINT      NOT NULL REFERENCES ai.ruta_ui(id),
    origen                 VARCHAR(5)  NOT NULL CHECK (origen IN ('FRONT','DB')),
    campos_fuente          VARCHAR(200),
    herramienta_escritura  BIGINT      REFERENCES ai.herramienta(id),
    created_by             VARCHAR(120) NOT NULL,
    created_at             TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    modified_by            VARCHAR(120),
    modified_at            TIMESTAMP,
    active                 BOOLEAN      NOT NULL DEFAULT TRUE,
    CHECK (origen <> 'DB' OR campos_fuente IS NOT NULL)
);
CREATE UNIQUE INDEX IF NOT EXISTS ux_ai_ui_formulario_codigo
    ON ai.ui_formulario (codigo) WHERE active = TRUE;

-- Operacion: conversaciones del usuario (fk_usuario = id de public.users del JWT).
CREATE TABLE IF NOT EXISTS ai.conversacion (
    id                UUID         PRIMARY KEY,
    fk_usuario        BIGINT       NOT NULL,
    titulo            VARCHAR(200),
    estado            VARCHAR(20)  NOT NULL DEFAULT 'ACTIVA'
                        CHECK (estado IN ('ACTIVA','ARCHIVADA','BLOQUEADA')),
    ultimo_mensaje_at TIMESTAMP,
    created_by        VARCHAR(120) NOT NULL,
    created_at        TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    modified_by       VARCHAR(120),
    modified_at       TIMESTAMP,
    active            BOOLEAN      NOT NULL DEFAULT TRUE
);
CREATE INDEX IF NOT EXISTS ix_ai_conversacion_usuario
    ON ai.conversacion (fk_usuario, ultimo_mensaje_at DESC) WHERE active = TRUE;

-- contenido ya anonimizado. El razonamiento del modelo no se guarda, solo sus tokens.
CREATE TABLE IF NOT EXISTS ai.mensaje (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversacion_id     UUID        NOT NULL REFERENCES ai.conversacion(id),
    secuencia           INTEGER     NOT NULL,
    rol                 VARCHAR(12) NOT NULL CHECK (rol IN ('USER','ASSISTANT','TOOL','SYSTEM')),
    contenido           TEXT        NOT NULL,
    tipo_respuesta      VARCHAR(20),
    acciones_ui         JSONB,
    modelo              VARCHAR(120),
    tokens_entrada      INTEGER,
    tokens_salida       INTEGER,
    tokens_razonamiento INTEGER,
    latencia_ms         INTEGER,
    created_by          VARCHAR(120) NOT NULL,
    created_at          TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    modified_by         VARCHAR(120),
    modified_at         TIMESTAMP,
    active              BOOLEAN      NOT NULL DEFAULT TRUE
);
CREATE UNIQUE INDEX IF NOT EXISTS ux_ai_mensaje_secuencia
    ON ai.mensaje (conversacion_id, secuencia) WHERE active = TRUE;

CREATE TABLE IF NOT EXISTS ai.tool_invocacion (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mensaje_id        BIGINT      NOT NULL REFERENCES ai.mensaje(id),
    herramienta_id    BIGINT      REFERENCES ai.herramienta(id),
    nombre            VARCHAR(80) NOT NULL,
    argumentos        JSONB,
    estado            VARCHAR(20) NOT NULL CHECK (estado IN
                        ('OK','ERROR','RECHAZADA','PENDIENTE','LIMITE')),
    http_status       INTEGER,
    resultado_resumen TEXT,
    duracion_ms       INTEGER,
    created_by        VARCHAR(120) NOT NULL,
    created_at        TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    modified_by       VARCHAR(120),
    modified_at       TIMESTAMP,
    active            BOOLEAN      NOT NULL DEFAULT TRUE
);
CREATE INDEX IF NOT EXISTS ix_ai_tool_invocacion_mensaje
    ON ai.tool_invocacion (mensaje_id) WHERE active = TRUE;

-- Una accion de escritura espera confirmacion con boton. payload_hash se verifica al confirmar.
CREATE TABLE IF NOT EXISTS ai.accion_pendiente (
    id              UUID        PRIMARY KEY,
    conversacion_id UUID        NOT NULL REFERENCES ai.conversacion(id),
    fk_usuario      BIGINT      NOT NULL,
    herramienta_id  BIGINT      NOT NULL REFERENCES ai.herramienta(id),
    payload         JSONB       NOT NULL,
    payload_hash    CHAR(64)    NOT NULL,
    resumen         TEXT        NOT NULL,
    estado          VARCHAR(20) NOT NULL DEFAULT 'PENDIENTE'
                      CHECK (estado IN ('PENDIENTE','EJECUTADA','FALLIDA','DESCARTADA','EXPIRADA')),
    expira_at       TIMESTAMP   NOT NULL,
    resuelta_at     TIMESTAMP,
    resultado       JSONB,
    created_by      VARCHAR(120) NOT NULL,
    created_at      TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    modified_by     VARCHAR(120),
    modified_at     TIMESTAMP,
    active          BOOLEAN      NOT NULL DEFAULT TRUE
);
CREATE INDEX IF NOT EXISTS ix_ai_accion_pendiente_vivas
    ON ai.accion_pendiente (expira_at) WHERE estado = 'PENDIENTE';
CREATE INDEX IF NOT EXISTS ix_ai_accion_pendiente_conversacion
    ON ai.accion_pendiente (conversacion_id) WHERE active = TRUE;

-- Nivel 1 (consulta curada) y 2 (SQL generado). En v1 solo se usa el nivel 1.
CREATE TABLE IF NOT EXISTS ai.consulta_analitica (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mensaje_id  BIGINT      NOT NULL REFERENCES ai.mensaje(id),
    nivel       SMALLINT    NOT NULL CHECK (nivel IN (1,2)),
    sql_texto   TEXT,
    sql_hash    CHAR(64),
    vistas      TEXT[],
    filas       INTEGER,
    duracion_ms INTEGER,
    estado      VARCHAR(20) NOT NULL CHECK (estado IN ('OK','RECHAZADA','ERROR','TIMEOUT')),
    motivo      TEXT,
    created_by  VARCHAR(120) NOT NULL,
    created_at  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    modified_by VARCHAR(120),
    modified_at TIMESTAMP,
    active      BOOLEAN      NOT NULL DEFAULT TRUE
);
CREATE INDEX IF NOT EXISTS ix_ai_consulta_analitica_mensaje
    ON ai.consulta_analitica (mensaje_id) WHERE active = TRUE;

-- Bloqueos y descartes. fragmento_hash en vez del texto crudo.
CREATE TABLE IF NOT EXISTS ai.evento_seguridad (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversacion_id UUID,
    fk_usuario      BIGINT      NOT NULL,
    capa            VARCHAR(30) NOT NULL,
    riesgo          VARCHAR(10) NOT NULL CHECK (riesgo IN ('BAJO','MEDIO','ALTO')),
    motivo          TEXT        NOT NULL,
    fragmento_hash  CHAR(64),
    created_by      VARCHAR(120) NOT NULL,
    created_at      TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    modified_by     VARCHAR(120),
    modified_at     TIMESTAMP,
    active          BOOLEAN      NOT NULL DEFAULT TRUE
);
CREATE INDEX IF NOT EXISTS ix_ai_evento_seguridad_usuario
    ON ai.evento_seguridad (fk_usuario, created_at) WHERE active = TRUE;

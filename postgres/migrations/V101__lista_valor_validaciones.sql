-- V101 - CRUD de listas de valores, capa 1 de 4: DDL y validaciones.
-- TLISTA_CATEGORIA es la lista (código inmutable = TLISTA_VALOR.CATEGORIA,
-- descripción, lista padre, ordinal, habilitada); el trigger la crea cuando una
-- migración siembra valores de una categoría nueva. En TLISTA_VALOR, ACTIVE es
-- el borrado lógico y HABILITADO el interruptor de los selectores: un valor
-- deshabilitado no se ofrece, pero sigue en los registros que ya lo tienen.
-- ES_SISTEMA nace TRUE para lo sembrado por migraciones (el código lo busca por
-- CATEGORIA+VALOR en texto): solo se renombra y reordena. FK_TLISTA_VALOR_PADRE
-- liga cada valor a uno de la lista padre (municipio -> departamento).
-- Depende de: V22 (TLISTA_VALOR), V71 (UNIQUE parcial categoria+valor).

SET search_path TO academico_test, public;

ALTER TABLE academico_test.TLISTA_VALOR
    ADD COLUMN IF NOT EXISTS ES_SISTEMA            BOOLEAN NOT NULL DEFAULT TRUE,
    ADD COLUMN IF NOT EXISTS FK_TLISTA_VALOR_PADRE BIGINT,
    ADD COLUMN IF NOT EXISTS ETIQUETA              VARCHAR(10),
    ADD COLUMN IF NOT EXISTS ORDEN                 INTEGER,
    ADD COLUMN IF NOT EXISTS PREDETERMINADO        BOOLEAN NOT NULL DEFAULT FALSE,
    ADD COLUMN IF NOT EXISTS HABILITADO            BOOLEAN NOT NULL DEFAULT TRUE;

ALTER TABLE academico_test.TLISTA_VALOR DROP CONSTRAINT IF EXISTS FK_TLISTA_VALOR_PADRE;
ALTER TABLE academico_test.TLISTA_VALOR ADD CONSTRAINT FK_TLISTA_VALOR_PADRE
    FOREIGN KEY (FK_TLISTA_VALOR_PADRE) REFERENCES academico_test.TLISTA_VALOR (PK_LISTA_VALOR);

CREATE INDEX IF NOT EXISTS IDX_TLISTA_VALOR_PADRE
    ON academico_test.TLISTA_VALOR (FK_TLISTA_VALOR_PADRE)
    WHERE FK_TLISTA_VALOR_PADRE IS NOT NULL;

CREATE UNIQUE INDEX IF NOT EXISTS UQ_TLISTA_VALOR_PREDETERMINADO
    ON academico_test.TLISTA_VALOR (CATEGORIA)
    WHERE PREDETERMINADO AND ACTIVE = TRUE;

-- Orden inicial = el que daban los selectores (por VALOR); los dados de baja al final.
UPDATE academico_test.TLISTA_VALOR lv
   SET ORDEN = x.orden
  FROM (SELECT v.PK_LISTA_VALOR,
               COALESCE(m.maximo, 0)
                 + ROW_NUMBER() OVER (PARTITION BY v.CATEGORIA
                                          ORDER BY v.ACTIVE DESC, v.VALOR, v.PK_LISTA_VALOR) AS orden
          FROM academico_test.TLISTA_VALOR v
          LEFT JOIN (SELECT CATEGORIA, MAX(ORDEN) AS maximo
                       FROM academico_test.TLISTA_VALOR GROUP BY CATEGORIA) m ON m.CATEGORIA = v.CATEGORIA
         WHERE v.ORDEN IS NULL) x
 WHERE lv.PK_LISTA_VALOR = x.PK_LISTA_VALOR;

ALTER TABLE academico_test.TLISTA_VALOR ALTER COLUMN ORDEN SET NOT NULL;

COMMENT ON COLUMN academico_test.TLISTA_VALOR.ES_SISTEMA
    IS 'TRUE si el valor lo sembró una migración (el código puede buscarlo por CATEGORIA+VALOR): se renombra y reordena, pero no se deshabilita ni se elimina.';
COMMENT ON COLUMN academico_test.TLISTA_VALOR.FK_TLISTA_VALOR_PADRE
    IS 'Valor padre (relación reflexiva): p.ej. el departamento de un municipio. Es de la lista padre de su categoría (TLISTA_CATEGORIA.FK_TLISTA_CATEGORIA_PADRE).';
COMMENT ON COLUMN academico_test.TLISTA_VALOR.ETIQUETA
    IS 'Abreviatura opcional que algunos módulos muestran junto al valor (p.ej. Ret, Pro).';
COMMENT ON COLUMN academico_test.TLISTA_VALOR.ORDEN
    IS 'Orden de presentación en los selectores; en una lista ordinal expresa la gradación. Si llega NULL, el trigger lo pone al final.';
COMMENT ON COLUMN academico_test.TLISTA_VALOR.PREDETERMINADO
    IS 'Valor que los formularios preseleccionan; como máximo uno por categoría (UQ_TLISTA_VALOR_PREDETERMINADO).';
COMMENT ON COLUMN academico_test.TLISTA_VALOR.HABILITADO
    IS 'FALSE: el valor no se ofrece en los selectores, pero sigue en los registros que ya lo tienen. Distinto de ACTIVE (borrado lógico).';

CREATE TABLE IF NOT EXISTS academico_test.TLISTA_CATEGORIA (
    PK_LISTA_CATEGORIA        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CODIGO                    VARCHAR(30)  NOT NULL,
    DESCRIPCION               VARCHAR(300),
    FK_TLISTA_CATEGORIA_PADRE BIGINT REFERENCES academico_test.TLISTA_CATEGORIA (PK_LISTA_CATEGORIA),
    ES_ORDINAL                BOOLEAN      NOT NULL DEFAULT FALSE,
    HABILITADA                BOOLEAN      NOT NULL DEFAULT TRUE,
    CREATED_BY                VARCHAR(120) NOT NULL DEFAULT 'sistema',
    CREATED_AT                TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    MODIFIED_BY               VARCHAR(120),
    MODIFIED_AT               TIMESTAMP,
    ACTIVE                    BOOLEAN      NOT NULL DEFAULT TRUE
);

CREATE UNIQUE INDEX IF NOT EXISTS UQ_TLISTA_CATEGORIA_CODIGO
    ON academico_test.TLISTA_CATEGORIA (CODIGO) WHERE ACTIVE = TRUE;
CREATE INDEX IF NOT EXISTS IDX_TLISTA_CATEGORIA_PADRE
    ON academico_test.TLISTA_CATEGORIA (FK_TLISTA_CATEGORIA_PADRE)
    WHERE FK_TLISTA_CATEGORIA_PADRE IS NOT NULL;

COMMENT ON TABLE academico_test.TLISTA_CATEGORIA
    IS 'Listas de la Lista de Valores. CODIGO = TLISTA_VALOR.CATEGORIA y no cambia nunca: el código busca los valores por ese texto.';

INSERT INTO academico_test.TLISTA_CATEGORIA (CODIGO, ACTIVE, CREATED_BY)
SELECT lv.CATEGORIA, bool_or(lv.ACTIVE), 'migracion'
  FROM academico_test.TLISTA_VALOR lv
 WHERE NOT EXISTS (SELECT 1 FROM academico_test.TLISTA_CATEGORIA c WHERE c.CODIGO = lv.CATEGORIA)
 GROUP BY lv.CATEGORIA;

-- Lista padre deducida de los padres que ya tienen sus valores, si son de una sola lista.
UPDATE academico_test.TLISTA_CATEGORIA c
   SET FK_TLISTA_CATEGORIA_PADRE = cp.PK_LISTA_CATEGORIA
  FROM (SELECT lv.CATEGORIA, MIN(p.CATEGORIA) AS padre
          FROM academico_test.TLISTA_VALOR lv
          JOIN academico_test.TLISTA_VALOR p ON p.PK_LISTA_VALOR = lv.FK_TLISTA_VALOR_PADRE
         WHERE lv.ACTIVE = TRUE
         GROUP BY lv.CATEGORIA
        HAVING count(DISTINCT p.CATEGORIA) = 1) x
  JOIN academico_test.TLISTA_CATEGORIA cp ON cp.CODIGO = x.padre AND cp.ACTIVE = TRUE
 WHERE c.CODIGO = x.CATEGORIA
   AND c.ACTIVE = TRUE
   AND c.FK_TLISTA_CATEGORIA_PADRE IS NULL
   AND cp.PK_LISTA_CATEGORIA <> c.PK_LISTA_CATEGORIA;

CREATE OR REPLACE FUNCTION academico_test.fn_listavalor_completar_tg()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    IF NEW.ORDEN IS NULL THEN
        SELECT COALESCE(MAX(ORDEN), 0) + 1 INTO NEW.ORDEN
          FROM academico_test.TLISTA_VALOR
         WHERE CATEGORIA = NEW.CATEGORIA AND ACTIVE = TRUE;
    END IF;

    IF NEW.ACTIVE AND NOT EXISTS (SELECT 1 FROM academico_test.TLISTA_CATEGORIA
                                   WHERE CODIGO = NEW.CATEGORIA AND ACTIVE = TRUE) THEN
        INSERT INTO academico_test.TLISTA_CATEGORIA (CODIGO, CREATED_BY)
        VALUES (NEW.CATEGORIA, COALESCE(NEW.CREATED_BY, 'sistema'));
    END IF;
    RETURN NEW;
END;
$$;

COMMENT ON FUNCTION academico_test.fn_listavalor_completar_tg()
    IS 'Trigger BEFORE INSERT/UPDATE OF CATEGORIA, ACTIVE de TLISTA_VALOR: ORDEN NULL va al final de su categoría y un valor activo cuya categoría no tiene fila activa en TLISTA_CATEGORIA la crea (seeds que insertan directo, valor recuperado desde la bitácora).';

DROP TRIGGER IF EXISTS TRG_TLISTA_VALOR_COMPLETAR ON academico_test.TLISTA_VALOR;
CREATE TRIGGER TRG_TLISTA_VALOR_COMPLETAR
    BEFORE INSERT OR UPDATE OF CATEGORIA, ACTIVE ON academico_test.TLISTA_VALOR
    FOR EACH ROW EXECUTE FUNCTION academico_test.fn_listavalor_completar_tg();


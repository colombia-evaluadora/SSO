CREATE OR REPLACE FUNCTION academico_test.fn_listavalor_validar_valores_lote(p_valores JSONB)
RETURNS VOID
LANGUAGE plpgsql
IMMUTABLE
AS $$
DECLARE
    v_repetido TEXT;
BEGIN
    IF p_valores IS NULL OR p_valores = '[]'::jsonb THEN
        RETURN;
    END IF;
    IF jsonb_typeof(p_valores) <> 'array' THEN
        RAISE EXCEPTION 'VALORES debe ser un arreglo [{nombre, valor, etiqueta, accion, padre, predeterminado}]'
            USING ERRCODE = '22023';
    END IF;

    SELECT UPPER(TRIM(e->>'valor')) INTO v_repetido
      FROM jsonb_array_elements(p_valores) e
     GROUP BY UPPER(TRIM(e->>'valor'))
    HAVING count(*) > 1
     LIMIT 1;
    IF v_repetido IS NOT NULL THEN
        RAISE EXCEPTION 'El código "%" está repetido en los valores enviados', v_repetido
            USING ERRCODE = '22023';
    END IF;

    IF (SELECT count(*) FROM jsonb_array_elements(p_valores) e
         WHERE (e->>'predeterminado')::BOOLEAN IS TRUE) > 1 THEN
        RAISE EXCEPTION 'Solo un valor de la lista puede ser predeterminado'
            USING ERRCODE = '22023';
    END IF;
END;
$$;

COMMENT ON FUNCTION academico_test.fn_listavalor_validar_valores_lote(JSONB)
    IS '22023 si VALORES no es un arreglo, repite un código o marca más de un predeterminado. Vacío o NULL es válido (lista sin valores). Cada elemento se valida después como un valor suelto.';


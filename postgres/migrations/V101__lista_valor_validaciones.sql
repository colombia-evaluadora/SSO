CREATE OR REPLACE FUNCTION academico_test.fn_listavalor_validar_categoria_padre(
    p_categoria       VARCHAR,
    p_categoria_padre VARCHAR
)
RETURNS VOID
LANGUAGE plpgsql
STABLE
AS $$
BEGIN
    IF p_categoria_padre IS NULL THEN
        RETURN;
    END IF;

    IF NOT EXISTS (SELECT 1 FROM academico_test.TLISTA_CATEGORIA
                    WHERE CODIGO = p_categoria_padre AND ACTIVE = TRUE) THEN
        RAISE EXCEPTION 'La lista padre % no existe', p_categoria_padre
            USING ERRCODE = '22023';
    END IF;

    -- Sube desde la lista padre propuesta; si llega a la propia lista, cerraría un ciclo.
    IF p_categoria_padre = p_categoria OR EXISTS (
        WITH RECURSIVE ancestros(pk, codigo) AS (
            SELECT c.FK_TLISTA_CATEGORIA_PADRE, c.CODIGO
              FROM academico_test.TLISTA_CATEGORIA c
             WHERE c.CODIGO = p_categoria_padre AND c.ACTIVE = TRUE
            UNION
            SELECT c.FK_TLISTA_CATEGORIA_PADRE, c.CODIGO
              FROM academico_test.TLISTA_CATEGORIA c
              JOIN ancestros a ON a.pk = c.PK_LISTA_CATEGORIA
        )
        SELECT 1 FROM ancestros WHERE codigo = p_categoria
    ) THEN
        RAISE EXCEPTION 'La lista padre no puede ser la misma lista ni formar un ciclo (% -> %)',
            p_categoria, p_categoria_padre
            USING ERRCODE = '22023';
    END IF;
END;
$$;

COMMENT ON FUNCTION academico_test.fn_listavalor_validar_categoria_padre(VARCHAR, VARCHAR)
    IS '22023 si la lista padre no existe, es la misma lista o forma un ciclo. NULL = sin lista padre, válido.';

CREATE OR REPLACE FUNCTION academico_test.fn_listavalor_validar_categoria_padre_compatible(
    p_categoria       VARCHAR,
    p_categoria_padre VARCHAR
)
RETURNS VOID
LANGUAGE plpgsql
STABLE
AS $$
DECLARE
    v_otra VARCHAR;
BEGIN
    SELECT p.CATEGORIA INTO v_otra
      FROM academico_test.TLISTA_VALOR lv
      JOIN academico_test.TLISTA_VALOR p ON p.PK_LISTA_VALOR = lv.FK_TLISTA_VALOR_PADRE
     WHERE lv.CATEGORIA = p_categoria
       AND lv.ACTIVE = TRUE
       AND p.CATEGORIA IS DISTINCT FROM p_categoria_padre
     LIMIT 1;

    IF v_otra IS NOT NULL THEN
        RAISE EXCEPTION 'No se puede cambiar la lista padre de %: sus valores tienen valor padre en %. Quíteselos primero',
            p_categoria, v_otra
            USING ERRCODE = '22023';
    END IF;
END;
$$;

COMMENT ON FUNCTION academico_test.fn_listavalor_validar_categoria_padre_compatible(VARCHAR, VARCHAR)
    IS '22023 si algún valor activo de la lista tiene valor padre fuera de la nueva lista padre (NULL = quitar la lista padre).';


-- V214.1 - Tablas puente de la unidad y la actividad con el referente curricular.
-- Quedan TUNIDAD_ENUNCIADO, TACTIVIDAD_EVIDENCIA y TACTIVIDAD_CRITERIO_UNIDAD
-- con sus índices. Las funciones que las escriben viven hoy en V492.1-V492.3
-- (unidad) y V496.1-V496.3 (actividad).


SET search_path TO academico_test, public;

CREATE TABLE IF NOT EXISTS TUNIDAD_ENUNCIADO (
  PK_TUNIDAD_ENUNCIADO BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  FK_TUNIDAD BIGINT NOT NULL,
  FK_REFERENTE_ENUNCIADO BIGINT NOT NULL,
  CREATED_BY VARCHAR(120) NOT NULL,
  CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
  MODIFIED_BY VARCHAR(120),
  MODIFIED_AT TIMESTAMP,
  ACTIVE BOOLEAN DEFAULT TRUE NOT NULL,
  CONSTRAINT PK_TUNIDAD_ENUNCIADO PRIMARY KEY (PK_TUNIDAD_ENUNCIADO),
  CONSTRAINT FK_TUNIDAD_ENUNCIADO_UNIDAD FOREIGN KEY (FK_TUNIDAD)
    REFERENCES TUNIDAD (PK_TUNIDAD) ON DELETE CASCADE,
  CONSTRAINT FK_TUNIDAD_ENUNCIADO_ENUNCIADO FOREIGN KEY (FK_REFERENTE_ENUNCIADO)
    REFERENCES TREFERENTE_ENUNCIADO (PK_REFERENTE_ENUNCIADO)
);

CREATE INDEX IF NOT EXISTS IDX_TUNIDAD_ENUNCIADO_UNIDAD ON TUNIDAD_ENUNCIADO (FK_TUNIDAD);

CREATE INDEX IF NOT EXISTS IDX_TUNIDAD_ENUNCIADO_ENUNCIADO ON TUNIDAD_ENUNCIADO (FK_REFERENTE_ENUNCIADO);

CREATE INDEX IF NOT EXISTS IDX_TUNIDAD_ENUNCIADO_ACTIVE ON TUNIDAD_ENUNCIADO (PK_TUNIDAD_ENUNCIADO) WHERE ACTIVE = true;

CREATE UNIQUE INDEX IF NOT EXISTS U_TUNIDAD_ENUNCIADO_1
  ON TUNIDAD_ENUNCIADO (FK_TUNIDAD, FK_REFERENTE_ENUNCIADO)
  WHERE ACTIVE = true;

COMMENT ON COLUMN TUNIDAD_ENUNCIADO.PK_TUNIDAD_ENUNCIADO IS 'Llave primaria de la tabla';

COMMENT ON COLUMN TUNIDAD_ENUNCIADO.FK_TUNIDAD IS 'Llave foranea a tabla TUNIDAD';

COMMENT ON COLUMN TUNIDAD_ENUNCIADO.FK_REFERENTE_ENUNCIADO IS 'Llave foranea a TREFERENTE_ENUNCIADO (nivel 1, FK_PADRE IS NULL) del mismo nivel de ensenanza que la unidad; el enunciado marcado como aplicable/seleccionado para esa unidad';

COMMENT ON TABLE TUNIDAD_ENUNCIADO IS 'Relacion N:N entre TUNIDAD y los enunciados (TREFERENTE_ENUNCIADO nivel 1) del referente curricular que aplican a esa unidad';

CREATE TABLE IF NOT EXISTS TACTIVIDAD_EVIDENCIA (
  PK_TACTIVIDAD_EVIDENCIA BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  FK_TACTIVIDAD BIGINT NOT NULL,
  FK_REFERENTE_ENUNCIADO BIGINT NOT NULL,
  CREATED_BY VARCHAR(120) NOT NULL,
  CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
  MODIFIED_BY VARCHAR(120),
  MODIFIED_AT TIMESTAMP,
  ACTIVE BOOLEAN DEFAULT TRUE NOT NULL,
  CONSTRAINT PK_TACTIVIDAD_EVIDENCIA PRIMARY KEY (PK_TACTIVIDAD_EVIDENCIA),
  CONSTRAINT FK_TACTIVIDAD_EVIDENCIA_ACTIVIDAD FOREIGN KEY (FK_TACTIVIDAD)
    REFERENCES TACTIVIDAD (PK_TACTIVIDAD) ON DELETE CASCADE,
  CONSTRAINT FK_TACTIVIDAD_EVIDENCIA_EVIDENCIA FOREIGN KEY (FK_REFERENTE_ENUNCIADO)
    REFERENCES TREFERENTE_ENUNCIADO (PK_REFERENTE_ENUNCIADO)
);

CREATE INDEX IF NOT EXISTS IDX_TACTIVIDAD_EVIDENCIA_ACTIVIDAD ON TACTIVIDAD_EVIDENCIA (FK_TACTIVIDAD);

CREATE INDEX IF NOT EXISTS IDX_TACTIVIDAD_EVIDENCIA_EVIDENCIA ON TACTIVIDAD_EVIDENCIA (FK_REFERENTE_ENUNCIADO);

CREATE INDEX IF NOT EXISTS IDX_TACTIVIDAD_EVIDENCIA_ACTIVE ON TACTIVIDAD_EVIDENCIA (PK_TACTIVIDAD_EVIDENCIA) WHERE ACTIVE = true;

CREATE UNIQUE INDEX IF NOT EXISTS U_TACTIVIDAD_EVIDENCIA_1
  ON TACTIVIDAD_EVIDENCIA (FK_TACTIVIDAD, FK_REFERENTE_ENUNCIADO)
  WHERE ACTIVE = true;

COMMENT ON COLUMN TACTIVIDAD_EVIDENCIA.PK_TACTIVIDAD_EVIDENCIA IS 'Llave primaria de la tabla';

COMMENT ON COLUMN TACTIVIDAD_EVIDENCIA.FK_TACTIVIDAD IS 'Llave foranea a tabla TACTIVIDAD (debe tener FK_TUNIDAD asignado)';

COMMENT ON COLUMN TACTIVIDAD_EVIDENCIA.FK_REFERENTE_ENUNCIADO IS 'Llave foranea a TREFERENTE_ENUNCIADO (nivel 2, FK_PADRE NOT NULL = evidencia) cuyo enunciado padre esta relacionado con la unidad de la actividad (TUNIDAD_ENUNCIADO)';

COMMENT ON TABLE TACTIVIDAD_EVIDENCIA IS 'Relacion N:N entre TACTIVIDAD y las evidencias (TREFERENTE_ENUNCIADO nivel 2) del enunciado relacionado con la unidad de esa actividad';

CREATE TABLE IF NOT EXISTS TACTIVIDAD_CRITERIO_UNIDAD (
  PK_TACTIVIDAD_CRITERIO_UNIDAD BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  FK_TACTIVIDAD BIGINT NOT NULL,
  FK_TCRITERIO_UNIDAD BIGINT NOT NULL,
  CREATED_BY VARCHAR(120) NOT NULL,
  CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
  MODIFIED_BY VARCHAR(120),
  MODIFIED_AT TIMESTAMP,
  ACTIVE BOOLEAN DEFAULT TRUE NOT NULL,
  CONSTRAINT PK_TACTIVIDAD_CRITERIO_UNIDAD PRIMARY KEY (PK_TACTIVIDAD_CRITERIO_UNIDAD),
  CONSTRAINT FK_TACTIVIDAD_CRITERIO_UNIDAD_ACTIVIDAD FOREIGN KEY (FK_TACTIVIDAD)
    REFERENCES TACTIVIDAD (PK_TACTIVIDAD) ON DELETE CASCADE,
  CONSTRAINT FK_TACTIVIDAD_CRITERIO_UNIDAD_CRITERIO FOREIGN KEY (FK_TCRITERIO_UNIDAD)
    REFERENCES TCRITERIO_UNIDAD (PK_TCRITERIO_UNIDAD)
);

CREATE INDEX IF NOT EXISTS IDX_TACTIVIDAD_CRITERIO_UNIDAD_ACTIVIDAD ON TACTIVIDAD_CRITERIO_UNIDAD (FK_TACTIVIDAD);

CREATE INDEX IF NOT EXISTS IDX_TACTIVIDAD_CRITERIO_UNIDAD_CRITERIO ON TACTIVIDAD_CRITERIO_UNIDAD (FK_TCRITERIO_UNIDAD);

CREATE INDEX IF NOT EXISTS IDX_TACTIVIDAD_CRITERIO_UNIDAD_ACTIVE ON TACTIVIDAD_CRITERIO_UNIDAD (PK_TACTIVIDAD_CRITERIO_UNIDAD) WHERE ACTIVE = true;

CREATE UNIQUE INDEX IF NOT EXISTS U_TACTIVIDAD_CRITERIO_UNIDAD_1
  ON TACTIVIDAD_CRITERIO_UNIDAD (FK_TACTIVIDAD, FK_TCRITERIO_UNIDAD)
  WHERE ACTIVE = true;

COMMENT ON COLUMN TACTIVIDAD_CRITERIO_UNIDAD.PK_TACTIVIDAD_CRITERIO_UNIDAD IS 'Llave primaria de la tabla';

COMMENT ON COLUMN TACTIVIDAD_CRITERIO_UNIDAD.FK_TACTIVIDAD IS 'Llave foranea a tabla TACTIVIDAD (debe tener FK_TUNIDAD asignado)';

COMMENT ON COLUMN TACTIVIDAD_CRITERIO_UNIDAD.FK_TCRITERIO_UNIDAD IS 'Llave foranea a TCRITERIO_UNIDAD; debe pertenecer a la rubrica (TRUBRICA_UNIDAD) de la misma unidad de la actividad';

COMMENT ON TABLE TACTIVIDAD_CRITERIO_UNIDAD IS 'Relacion N:N entre TACTIVIDAD y los criterios (TCRITERIO_UNIDAD) de la rubrica de la unidad de esa actividad que se seleccionaron para evaluarla';

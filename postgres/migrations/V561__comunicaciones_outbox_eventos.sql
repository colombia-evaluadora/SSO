-- Que hace: tabla toutbox_evento; comms-service la publica a RabbitMQ.
-- Por que aqui: OpenSpec add-notificaciones-eventos-dominio D-5.1 (publicar tras
--   commit, sin depender de la pestana del front).
-- Depende de: V560 (schema comunicaciones), V283 (fn_cdc_asegurar_auditoria).

CREATE TABLE IF NOT EXISTS comunicaciones.toutbox_evento (
    pk_toutbox_evento BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo              VARCHAR(60)  NOT NULL,
    destinatarios     TEXT[]       NOT NULL,
    titulo            VARCHAR(200) NOT NULL,
    cuerpo            VARCHAR(500),
    deep_link         VARCHAR(500),
    datos             JSONB        NOT NULL DEFAULT '{}'::jsonb,
    dedupe_key        VARCHAR(200),
    agrupacion_key    VARCHAR(200),
    actor             VARCHAR(120),
    prioridad         VARCHAR(25),
    app               VARCHAR(50)  NOT NULL DEFAULT 'COLOMBIA-EVALUADORA',
    created_at        TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    publicado_en      TIMESTAMPTZ,
    intentos          INTEGER      NOT NULL DEFAULT 0,
    ultimo_error      VARCHAR(500),
    CHECK (cardinality(destinatarios) > 0)
);
CREATE INDEX IF NOT EXISTS ix_toutbox_evento_pendientes
    ON comunicaciones.toutbox_evento (pk_toutbox_evento) WHERE publicado_en IS NULL;


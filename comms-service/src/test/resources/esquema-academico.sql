-- V299: por CUENTA (funcionario/acudiente) y si no, por correo (estudiante).
DROP FUNCTION IF EXISTS public.fn_get_academico_usuario_id(BIGINT);
CREATE FUNCTION public.fn_get_academico_usuario_id(p_user_id BIGINT) RETURNS BIGINT LANGUAGE sql STABLE AS $$
    SELECT COALESCE(
        (SELECT t.PK_TUSUARIO FROM academico_test.TUSUARIO t JOIN public.users u ON u.email = t.CUENTA
          WHERE u.id_user = p_user_id ORDER BY t.ACTIVE DESC, t.PK_TUSUARIO LIMIT 1),
        (SELECT t.PK_TUSUARIO FROM academico_test.TUSUARIO t JOIN public.users u ON upper(u.email) = upper(t.CORREO_ELECTRONICO)
          WHERE u.id_user = p_user_id AND t.ACTIVE LIMIT 1))
$$;

